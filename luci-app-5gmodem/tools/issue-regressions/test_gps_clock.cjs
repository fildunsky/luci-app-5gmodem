const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname, '../../htdocs/luci-static/resources/view/modem5g/gps.js'), 'utf8');
const create = new Function(source.slice(source.indexOf('function createGPSClock('), source.indexOf('\nreturn view.extend(')) + '\nreturn createGPSClock;')();
let elapsed = 0;
const clock = create(() => elapsed);
clock.sample('2026-01-01T20:59:59');
assert.equal(clock.read(), null, 'wait for router timezone rather than use browser timezone');
clock.setZone({offset:10800});
assert.deepEqual(clock.read(), {time:'23:59:59', date:'2026-01-01', zone:'UTC+03:00'});
elapsed = 1000;
assert.deepEqual(clock.read(), {time:'00:00:00', date:'2026-01-02', zone:'UTC+03:00'});
clock.sample('2026-01-01T20:59:59');
elapsed = 2000;
assert.equal(clock.read().time, '00:00:01', 'cached samples must not reset the clock');
clock.sample('2026-01-01T21:00:04Z');
assert.equal(clock.read().time, '00:00:04', 'fresh samples resynchronize');
clock.setZone({offset:-12600, zone:'invalid'});
assert.equal(clock.read().time, '17:30:04');
assert.equal(clock.read().zone, 'UTC-03:30');
clock.setZone({offset:20700});
assert.equal(clock.read().time, '02:45:04');
assert.equal(clock.setZone(null), false);
assert.equal(clock.read().zone, 'UTC+05:45', 'failed refresh preserves timezone');
clock.setZone({offset:0, zone:'Europe/Berlin', now:Date.parse('2026-01-01T00:00:00Z')/1000});
assert.equal(clock.read().zone, 'UTC', 'runtime offset wins over unapplied saved settings');
clock.setZone({offset:3600, zone:'Europe/Berlin', now:Date.parse('2026-03-29T00:59:59Z')/1000});
clock.sample('2026-03-29T00:59:59Z');
assert.equal(clock.read().time, '01:59:59');
elapsed += 1000;
assert.deepEqual(clock.read(), {time:'03:00:00', date:'2026-03-29', zone:'UTC+02:00'}, 'IANA zones follow daylight saving transitions');
clock.sample(null);
assert.equal(clock.read(), null, 'off or unavailable receiver clears the clock');
clock.sample('invalid');
assert.equal(clock.read(), null);
console.log('GPS clock: ticking, synchronization, timezone fallback and DST passed');
