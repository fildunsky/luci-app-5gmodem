const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const text = fs.readFileSync(path.join(__dirname, '../../htdocs/luci-static/resources/view/modem5g/readsms.js'), 'utf8');
const context = { smsSeen: new Set(), smsSeenFirst: false, sms_msg_pairs: () => [['new', 'old']] };
vm.createContext(context);
vm.runInContext(text.slice(text.indexOf('function sms_android_read('), text.indexOf('function sms_make_card(')), context);
assert.equal(context.sms_item_new({ android_read: 1 }), false);
assert.equal(context.sms_item_new({ android_read: 0, android_seen: 1 }), false);
assert.equal(context.sms_android_new([{ android_read: 1, android_seen: 0 }, { android_read: 0, android_seen: 1 }]), 0);
context.smsSeen.add('new');
assert.equal(context.sms_item_new({ android_read: 0 }), true);
assert.equal(context.sms_android_read([{ android_read: 1 }, { android_read: 1 }]), 1);
assert.equal(context.sms_android_read([{ android_read: 1 }, { android_read: 0 }]), 0);
assert.equal(context.sms_android_read([{}]), undefined);
assert.equal(context.sms_item_new({}), false);
context.smsSeen.clear();
assert.equal(context.sms_item_new({}), true);
console.log('PASS: Android SMS use the phone read flag; other modem unread tracking is unchanged');
