#!/bin/sh
# Свежая установка: СЛЕЖЕНИЕ сторожа интернета включено по умолчанию - оно
# read-only (лампочки здоровья, журнал), пользователь сразу видит пользу.
# Действия (переключение трафика, лечение модемов) остаются выключенными:
# наблюдать по умолчанию, действовать по согласию.
#
# Апгрейд не трогаем: секция health уже есть - её состояние выбрал пользователь
# (в том числе осознанно выключенное слежение).
[ -n "$(uci -q show 5gmodem.health 2>/dev/null)" ] && exit 0
uci -q set 5gmodem.health=health
uci -q set 5gmodem.health.enabled='1'
uci -q commit 5gmodem
exit 0
