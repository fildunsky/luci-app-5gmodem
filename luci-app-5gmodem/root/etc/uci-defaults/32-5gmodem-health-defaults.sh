#!/bin/sh
# Свежая установка: СЛЕЖЕНИЕ сторожа интернета и ПЕРЕКЛЮЧЕНИЕ ТРАФИКА включены
# по умолчанию. Лечение модемов (перезагрузка модуля, питание USB) остаётся
# выключенным: наблюдать и переставлять маршрут - обратимо и безопасно, лезть в
# железо - по согласию.
#
# Почему переключение теперь по умолчанию ДА. Аплинк с адресом, но без выхода в
# сеть, для ядра здоров: маршрут на месте, сам он никуда не денется. Живой
# случай (zbt, 4 модема): Wi-Fi-аплинк стоял первым в приоритете, после загрузки
# прицепился к точке без интернета и семь минут держал трафик поверх четырёх
# работающих модемов. Сторож это ВИДЕЛ - и молчал, потому что галка была снята.
# Значение по умолчанию, при котором функция бездействует, стоит ровно столько,
# сколько стоит её отсутствие.
#
# Апгрейд не трогаем: секция health уже есть - её состояние выбрал пользователь
# (в том числе осознанно выключенное переключение).
[ -n "$(uci -q show 5gmodem.health 2>/dev/null)" ] && exit 0
uci -q set 5gmodem.health=health
uci -q set 5gmodem.health.enabled='1'
uci -q set 5gmodem.health.failover='1'
uci -q commit 5gmodem
exit 0
