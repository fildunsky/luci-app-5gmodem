#!/bin/sh
# luci-app-5gmodem: снять ошибочную пометку kind=hilink с обычных модемов.
#
# ЧТО БЫЛО. is_hilink() считала HiLink-ом любой модем, у которого есть сетевая
# карта. Но она есть и у обычного: qmi_wwan создаёт wwan0. Под это правило
# попадал каждый QMI/MBIM-модем - живьём поймано на Telit LM960 (1bc7:1040):
# подпись «(Debug)», настройка через несуществующий веб-API и, как следствие,
# модем «не определяется» вовсе.
#
# ПОЧЕМУ ОДНОЙ ПРАВКИ КОДА МАЛО. Ошибочный признак не вычислялся заново каждый
# раз - он БЫЛ ЗАПИСАН В КОНФИГ, а в is_hilink() сохранённое значение стоит
# первой проверкой и перебивает всё остальное. Без этой миграции пользователь,
# обновившийся с багованной версии, остался бы с прежним поведением навсегда:
# новый белый список до его модема просто не дошёл бы.
#
# ЧТО ЧИСТИМ. Только чужие вендоры. HiLink у нас поддержан ровно для Huawei
# (12d1), и у настоящего E3372 пометка ЗАКОННА - в том числе в композициях с
# AT-портами, куда он переходит из веб-режима. Поэтому 12d1 не трогаем совсем:
# ошибиться в эту сторону дороже, чем оставить лишнюю запись.
# Секции без vidpid тоже не трогаем - судить не по чему.

[ -f /etc/config/5gmodem ] || exit 0

CHANGED=0

for SEC in $(uci -q show 5gmodem 2>/dev/null \
		| sed -n "s/^5gmodem\.\(m_[A-Za-z0-9_]*\)\.kind='hilink'\$/\1/p"); do
	VIDPID=$(uci -q get "5gmodem.$SEC.vidpid")
	[ -n "$VIDPID" ] || continue
	case "$VIDPID" in
		12d1:*) continue ;;
	esac
	uci -q delete "5gmodem.$SEC.kind"
	# netdev держал сетевую карту, по которой модем и был опознан ошибочно,
	# at_debug - галку режима, которой у обычного модема быть не должно.
	uci -q delete "5gmodem.$SEC.netdev"
	uci -q delete "5gmodem.$SEC.at_debug"
	logger -t 5gmodem "миграция: снята ошибочная пометка hilink с $SEC ($VIDPID)"
	CHANGED=1
done

[ "$CHANGED" = "1" ] && uci -q commit 5gmodem

exit 0
