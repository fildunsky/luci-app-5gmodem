#!/bin/sh
#
# СБОРКА PDU ДЛЯ ИСХОДЯЩЕЙ SMS - РАДИ КИРИЛЛИЦЫ.
#
# ЗАЧЕМ. `sms_tool ... send` кодирует текст ТОЛЬКО в GSM-7, и всё, чего в этой
# таблице нет, уходит вопросительными знаками: русский текст доезжает как
# «?????». Флаг `-c 2` относится к USSD, на отправку он не действует (проверено
# на живом модеме, воспроизводится и без нашего приложения - это поведение самого
# инструмента). Поэтому PDU для не-латиницы собираем сами и отдаём модему через
# AT+CMGS.
#
# ЧТО ЗДЕСЬ. Кодировщик SMS-SUBMIT: UCS2 (DCS=0x08), при длинном тексте -
# разбиение на части с UDH-заголовком конкатенации. Ничего не отправляет и в порт
# не ходит: печатает строки «<длина TPDU> <PDU>», по строке на часть. Отправкой
# занимается smsbridge.sh.
#
# ПОЧЕМУ awk. На роутере нет ни iconv, ни python, ни perl, а od отсутствует в
# busybox этой сборки. Зато awk в локали C читает СТРОКУ КАК БАЙТЫ, а таблицу
# «байт -> число» можно построить через sprintf("%c"). На этом и стоит разбор
# UTF-8.
#
#   smspdu.sh needucs2 <текст>          - код 0, если текст НЕ влезает в GSM-7
#   smspdu.sh encode <номер> <текст>    - строки «<len> <pdu>» (по строке на часть)

_NUM="$2"
_TXT="$3"

# GSM-7 покрывает латиницу, цифры и горсть знаков. Всё остальное (кириллица,
# эмодзи, «ё», длинное тире) требует UCS2. Судим по байтам: любой байт >= 0x80 в
# UTF-8 означает символ вне ASCII, а из ASCII в GSM-7 не входят только несколько
# знаков, которые модем и сам заменит - гадать за него не будем.
needucs2() {
	printf '%s' "$1" | awk '
		BEGIN { for (i = 1; i < 256; i++) ord[sprintf("%c", i)] = i; rc = 1 }
		{ line = $0
		  for (i = 1; i <= length(line); i++) {
			c = ord[substr(line, i, 1)]
			if (c >= 128) { rc = 0 }
		  }
		}
		END { exit rc }
	'
}

# Номер -> полу-октеты с перестановкой нибблов, как требует 3GPP 23.040.
# Печатает «<число цифр> <TOA> <полу-октеты>».
_num_pdu() {
	printf '%s' "$1" | awk '
		{
			n = $0
			gsub(/[^0-9+]/, "", n)
			# ТИП НОМЕРА. 91 - международный, 81 - национальный, и ошибиться здесь
			# значит получить «+CMS ERROR» на ровном месте: сеть не принимает
			# номер вида 79626999032, объявленный национальным. А страница «+»
			# как раз не передаёт - у неё номер приходит из поля как есть.
			#   +7...   / 007...  - международный (00 - лишь когда за ним
			#                       полноценный номер: 000100 - сервисный);
			#   8XXXXXXXXXX       - настоящий национальный (транковая «8»);
			#   11+ цифр не с 8/0 - международный, у которого просто потеряли «+»;
			#   короткие (900)    - национальные, как есть.
			toa = "81"
			if (substr(n, 1, 1) == "+") { toa = "91"; n = substr(n, 2) }
			else if (substr(n, 1, 2) == "00" && length(n) >= 11) { toa = "91"; n = substr(n, 3) }
			gsub(/[^0-9]/, "", n)
			if (toa == "81" && length(n) >= 11 \
			    && substr(n, 1, 1) != "8" && substr(n, 1, 1) != "0") toa = "91"
			len = length(n)
			if (len % 2) n = n "F"
			out = ""
			for (i = 1; i <= length(n); i += 2) out = out substr(n, i + 1, 1) substr(n, i, 1)
			printf "%d %s %s", len, toa, out
		}
	'
}

encode() {
	_e_num="$1"; _e_txt="$2"
	[ -n "$_e_num" ] || return 1

	set -- $(_num_pdu "$_e_num")
	_e_dlen="$1"; _e_toa="$2"; _e_digits="$3"
	[ -n "$_e_dlen" ] && [ "$_e_dlen" -gt 0 ] || return 1

	# Ссылка на набор частей: одна на сообщение, лишь бы отличалась от соседних.
	# Берём младший байт от секунд аптайма - часы роутера могут быть не выставлены,
	# а /proc/uptime есть всегда.
	read -r _e_up _ < /proc/uptime
	_e_ref=$(( ${_e_up%%.*} % 256 ))

	printf '%s' "$_e_txt" | awk -v dlen="$_e_dlen" -v toa="$_e_toa" -v digits="$_e_digits" -v ref="$_e_ref" '
		BEGIN {
			for (i = 1; i < 256; i++) ord[sprintf("%c", i)] = i
			body = ""
			nl = 0
		}
		{ body = (nl++ ? body "\n" $0 : $0) }
		END {
			# --- UTF-8 -> UTF-16BE, по 4 hex-символа на кодовую единицу --------
			n = length(body)
			nu = 0
			i = 1
			while (i <= n) {
				c = ord[substr(body, i, 1)]
				if (c < 0x80) { cp = c; i += 1 }
				else if (c >= 0xC0 && c < 0xE0) {
					cp = (c - 0xC0) * 64 + (ord[substr(body, i + 1, 1)] - 0x80); i += 2
				}
				else if (c >= 0xE0 && c < 0xF0) {
					cp = (c - 0xE0) * 4096 + (ord[substr(body, i + 1, 1)] - 0x80) * 64 \
					     + (ord[substr(body, i + 2, 1)] - 0x80); i += 3
				}
				else if (c >= 0xF0) {
					cp = (c - 0xF0) * 262144 + (ord[substr(body, i + 1, 1)] - 0x80) * 4096 \
					     + (ord[substr(body, i + 2, 1)] - 0x80) * 64 \
					     + (ord[substr(body, i + 3, 1)] - 0x80); i += 4
				}
				else { i += 1; continue }
				if (cp > 0xFFFF) {
					# Суррогатная пара: символ вне BMP (эмодзи) - ДВЕ кодовые
					# единицы, и разрывать их между частями нельзя (см. ниже).
					cp -= 0x10000
					units[++nu] = sprintf("%04X", 0xD800 + int(cp / 1024))
					pair[nu] = 1
					units[++nu] = sprintf("%04X", 0xDC00 + (cp % 1024))
					pair[nu] = 2
				} else {
					units[++nu] = sprintf("%04X", cp)
					pair[nu] = 0
				}
			}

			# --- разбиение на части ------------------------------------------
			# 140 октетов на сообщение; с UDH конкатенации (6 октетов) остаётся
			# 134, то есть 67 кодовых единиц UCS2.
			if (nu <= 70) { total = 1; per = 70 } else { per = 67; total = int((nu + per - 1) / per) }

			u = 1
			for (p = 1; p <= total; p++) {
				cnt = 0; ud = ""
				while (u <= nu && cnt < per) {
					# Не разрываем суррогатную пару: если следующей влезает только
					# первая половина - переносим обе в следующую часть.
					if (pair[u] == 1 && cnt + 2 > per) break
					ud = ud units[u]; u++; cnt++
				}
				udlen = cnt * 2                      # октеты полезной нагрузки
				if (total > 1) {
					udh = sprintf("050003%02X%02X%02X", ref, total, p)
					fo = "51"                        # SMS-SUBMIT + VP + UDHI
					udl = udlen + 6
					ud = udh ud
				} else {
					fo = "11"
					udl = udlen
				}
				pdu = sprintf("00%s00%02X%s%s0008AA%02X%s", fo, dlen, toa, digits, udl, ud)
				# Длина TPDU для AT+CMGS - в октетах и БЕЗ ведущего SCA («00»).
				printf "%d %s\n", (length(pdu) / 2) - 1, pdu
			}
		}
	'
}

case "$1" in
	needucs2) needucs2 "$2"; exit $? ;;
	encode)   encode "$_NUM" "$_TXT"; exit $? ;;
	*) echo "usage: $0 needucs2 <текст> | encode <номер> <текст>" >&2; exit 2 ;;
esac
