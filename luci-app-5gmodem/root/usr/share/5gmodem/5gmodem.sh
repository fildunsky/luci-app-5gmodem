# Статичные поля (модель/IMEI/прошивка/ICCID) не меняются, но опрашивались КАЖДЫЙ
# опрос (5 из 6 AT-вызовов = основные ~секунды). При смене SIM (IMSI из батча !=
# сохранённого) кэш сбрасывается.
#
# КЛЮЧ - ПУТЬ ТОГО МОДЕМА, ЧЕЙ ПОРТ У НАС В РУКАХ, а не «активный модем» из
# настроек. Разница неочевидна, но именно она портила данные у пользователя с
# двумя одинаковыми Thales MV31-W (05c6:90d5, 1-1.2 и 1-1.3): переключение
# вкладки меняет active_modem и at_port НЕ одновременно, и опрос, начавшийся в
# этот зазор, читал IMEI из порта СТАРОГО модема, а складывал под ключом
# НОВОГО. Дальше кэш отдавал чужой IMEI уже «законно» - он и уезжал в секцию,
# в интерфейс (modem_imei) и в карточку профиля, где два разных модема
# показывали один номер. Ключ от реального порта делает подмену невозможной:
# данные всегда лежат под тем модемом, с которого сняты.
_STKEY=$(tty_usbpath "$DEVICE" 2>/dev/null | tr -d '\n' | tr -c 'A-Za-z0-9' '_')
# при адресном опросе (POLL_MODEM) фолбэк-ключ - ОПРАШИВАЕМЫЙ модем, а не
# активный: иначе подогрев соседа порол кэш статики активного (ревью)
[ -n "$_STKEY" ] || _STKEY=$(printf '%s' "${_POLL_AM:-$(uci -q get 5gmodem.@5gmodem[0].active_modem 2>/dev/null)}" | tr -c 'A-Za-z0-9' '_')
[ -n "$_STKEY" ] || _STKEY="$(basename "$DEVICE" 2>/dev/null)"
STATIC_CACHE="/tmp/5gmodem_static_$_STKEY"
# РОУМИНГ ВНУТРИ СТРАНЫ - НЕ РОУМИНГ.
#
# Модем считает роумингом любую сеть, чей код не совпадает с домашним кодом
# симки. Для MVNO это ЛОЖНАЯ тревога: T-Mobile (250-62) работает НА СЕТИ Tele2
# (250-20), и модем рапортует "+CREG: 2,5" при том, что абонент дома и платит
# по домашнему тарифу. Прошивка самого Huawei это понимает - в её API cellroam=0
# при том же состоянии; а вот AT-статус врёт.
#
# Правило: совпал MCC (страна) - показываем как дом. Роуминг для пользователя -
# это про другой тариф, а MVNO на своей хост-сети тарифицируется как дом;
# национальный роуминг в РФ отменён с 2017 года. Заодно это выравнивает
# поведение разных модемов с одной и той же симкой: Telit рапортовал "дом",
# Huawei - "роуминг".
#
# Коды роуминга: 5 (registered, roaming), 7 (SMS only, roaming),
# 10 (CSFB not preferred, roaming). Домашние аналоги: 1, 6, 9.
case "$REG" in
	5|7|10)
		_sim_mcc=$(printf '%s' "$SIMID" | cut -c1-3)
		case "$_sim_mcc" in
			''|*[!0-9]*) : ;;
			*)
				if [ -n "$COPS_MCC" ] && [ "$COPS_MCC" = "$_sim_mcc" ]; then
					case "$REG" in
						5)  REG=1 ;;
						7)  REG=6 ;;
						10) REG=9 ;;
					esac
					logger -t 5gmodem "network $COPS_NUM is in the same country as the SIM ($_sim_mcc) - not showing roaming"
				fi
				;;
		esac
		;;
esac

_PREV_IMSI=$(cat "${STATIC_CACHE}.imsi" 2>/dev/null)
if [ -n "$SIMID" ] && [ "$_PREV_IMSI" != "$SIMID" ]; then
	rm -f "${STATIC_CACHE}"_* 2>/dev/null
	printf '%s' "$SIMID" > "${STATIC_CACHE}.imsi"
fi

# ПЕРЕПОДБОР APN ПРИ СМЕНЕ СИМКИ - ПО ПЕРСИСТЕНТНОМУ КЛЮЧУ (IMSI в секции).
#
# Своего hotplug-события у смены SIM нет: модем с шины не уходит. Раньше триггер
# сравнивал IMSI с файлом в /tmp - но смена eSIM-профиля гонит модем через
# жёсткий ребут (CFUN=1,1), resolve чистит /tmp-кэш, и ПЕРВЫЙ опрос видел пустой
# prev-IMSI, принимал смену за «первый опрос после загрузки» и APN не трогал.
# Живой случай: включили eSIM Tele2, а в интерфейсе осталось "tt" от прежней
# T-Mobile. Причём сеть у обеих одна (Tele2 - хост MVNO), по коду сети смены не
# видно - видно только по IMSI самой симки.
#
# Ключ храним В СЕКЦИИ модема: переживает и ребут модема, и очистку /tmp. Пустой
# apn_imsi у уже настроенного модема - это ПЕРВАЯ встреча с симкой (обновились со
# старой версии или свежая установка): один раз подберём и запомним.
if [ -n "$SIMID" ]; then
	_apn_sec="$_hl_sec"
	[ -n "$(uci -q get "5gmodem.$_apn_sec" 2>/dev/null)" ] || _apn_sec=""
	if [ -n "$_apn_sec" ] \
	   && [ "$(uci -q get "5gmodem.$_apn_sec.apn_mode")" != "manual" ] \
	   && [ "$(uci -q get "5gmodem.$_apn_sec.apn_imsi")" != "$SIMID" ]; then
		_SIM_IF=$(uci -q get "5gmodem.$_apn_sec.network" 2>/dev/null)
		[ -n "$_SIM_IF" ] || _SIM_IF=$(uci -q get 5gmodem.@5gmodem[0].network 2>/dev/null)
		# Дебаунс: опрос идёт раз в пару секунд, а autoapn — секунды. Без метки
		# он запускался бы пачкой, пока первый не допишет apn_imsi.
		#
		# А ЕСЛИ ПРОШЛЫЙ ВЫЗОВ СДАЛСЯ - ЖДЁМ ПОЛЧАСА, А НЕ МИНУТУ. Выходы «не
		# смог» (роуминг, APN не найден, ни оператора ни IMSI) apn_imsi не пишут,
		# и с минутным дебаунсом сравнение расходилось ВЕЧНО: в логе zbt «смена
		# SIM (IMSI) на modem» шла сутками, каждый круг - AT-запросы к модему.
		_apn_stamp="/tmp/5gmodem_autoapn_$_apn_sec"
		_apn_wait=1
		[ -f "$_apn_stamp.gaveup" ] && _apn_wait=30
		if [ -n "$_SIM_IF" ] && { [ ! -f "$_apn_stamp" ] || [ -n "$(find "$_apn_stamp" -mmin +$_apn_wait 2>/dev/null)" ]; }; then
			: > "$_apn_stamp"
			logger -t 5gmodem "SIM change (IMSI) on $_SIM_IF - re-selecting the APN"
			# КАРТА ДРУГАЯ - СНИМОК СЛОТОВ УСТАРЕЛ. Кэш simslot.sh чистит только
			# ветка set, то есть переключение НАШИМИ руками. Физическая пересадка
			# карты его не трогала, и до пяти минут страница показывала прежний
			# тип SIM (живой случай: eSIM осталась подписью после установки
			# физической симки). Смена IMSI - точный признак, и мы её уже поймали.
			rm -f "/tmp/5gmodem_slots_$_POLL_AM" "/tmp/5gmodem_slots_$_POLL_AM.t" 2>/dev/null
			# unset _AT_LOCK_HELD + закрыть fd лока: этот фон ОТДЕЛЯЕТСЯ и может
			# взять at_lock уже ПОСЛЕ нашего выхода - он должен захватывать лок
			# сам, а не думать, что его держит (уже мёртвый) предок.
			( unset _AT_LOCK_HELD; eval "exec $AT_LOCK_FD>&-" 2>/dev/null
			  /usr/share/5gmodem/modemswitch.sh autoapn "$_SIM_IF" "$SIMID" ) \
				>/dev/null 2>&1 </dev/null &
		fi
	fi
fi
# at_static <key> <atcmd> [шаблон проверки] : сырой ответ из кэша, иначе запрос.
#
# ПРОВЕРЯЕМ ПЕРЕД ЗАПИСЬЮ В КЭШ. Раньше сохранялось что угодно, и один-
# единственный столкнувшийся обмен портил значение НАВСЕГДА: кэш статики не
# протухает, а в файл IMEI живьём попал ответ чужой команды -
#   5gmodem_static_1_1__imei: «at#bnd=? #BND: (0),(0-11,17,18),...»
# после чего IMEI показывался прочерком, сколько ни перезапрашивай.
# Очередь к порту (atlock.sh) делает такие столкновения редкими, но «редко» для
# вечного кэша недостаточно: одного раза хватает, чтобы сломать поле навсегда.
at_static() {
	_cf="${STATIC_CACHE}_$1"
	[ -s "$_cf" ] && { cat "$_cf"; return; }
	_out=$(sms_tool -d "$DEVICE" at "$2" 2>/dev/null)
	printf '%s' "$_out"
	# Шаблон не задан - поведение прежнее (кэшируем непустой ответ).
	if [ -n "$3" ]; then
		printf '%s' "$_out" | tr -d '\r' | grep -qE "$3" || return 0
	fi
	[ -n "$_out" ] && printf '%s' "$_out" > "$_cf"
	return 0
}

# Оба хелпера вырезают ВСЕ управляющие символы C0 (0x00-0x1F), а не только
# \r\n: у некоторых модемов (напр. DW5821e) разбор AT оставлял в значении
# сигнала «сырой» control-символ, который попадал прямо в JSON-строку и ронял
# парсер («Bad control character in string literal in JSON»). Числовые поля
# тоже эмитятся как строки в кавычках, поэтому чистить их безопасно и нужно.
# Очистка значения перед вставкой в JSON. Управляющие символы (0x00-0x1F) рвут
# JSON и приходят от модема при коллизии на AT-порту. Раньше КАЖДЫЙ вызов гонял
# внешний `tr` - а их за один опрос ~71, и это была самая дорогая часть скрипта
# (замерено: 71x tr ~0.17 c, почти как весь остальной опрос). tr нужен РЕДКО -
# только когда мусор реально есть; проверяем встроенным `case` (без fork).
# printf, а не echo: echo проглатывает значения вида "-n"/"-e" как флаги.
sanitize_string() {
	case "$1" in
		'') printf '%s\n' "-" ;;
		*[[:cntrl:]]*) printf '%s' "$1" | tr -d '\000-\037'; printf '\n' ;;
		*) printf '%s\n' "$1" ;;
	esac
}
sanitize_number() {
	case "$1" in
		'') printf '%s\n' "-" ;;
		*[[:cntrl:]]*) printf '%s' "$1" | tr -d '\000-\037'; printf '\n' ;;
		*) printf '%s\n' "$1" ;;
	esac
}

# ТА ЖЕ САНАЦИЯ, НО БЕЗ ПОДСТАНОВОК КОМАНД. В снимке ~98 полей, и каждое
# $(sanitize_string ...) - это форк; на каждый опрос выходило ~98 форков только
# ради санации. Замер на стенде 07.08.2026: сам эмиттер 134 -> 86 мс на снимок
# (снимков на холодном сборе два - частичный и финальный). Здесь имена переменных обходятся встроенными средствами: значение
# читается и кладётся В КОПИЮ _J_<имя>, оригинал НЕ трогается - частичная
# публикация идёт ДО профилей, а профили различают «пусто» и «-»
# ([ -z "$RSRP" ] перестал бы срабатывать). Форк остаётся только в редкой
# ветке с управляющими символами - как и раньше.
# eval безопасен: имена - из нашего фиксированного списка, а значение
# подставляется параметром (\$_sv) и шеллом не разбирается.
_sanv() {
	for _sv_n in "$@"; do
		eval "_sv=\$$_sv_n"
		case "$_sv" in
			'') _sv="-" ;;
			*[[:cntrl:]]*) _sv=$(printf '%s' "$_sv" | tr -d '\000-\037') ;;
		esac
		eval "_J_$_sv_n=\$_sv"
	done
}

# ЖИВОЙ СТАТУС ПОДКЛЮЧЕНИЯ ИЗ ЛОГА. Пока интерфейс не получил IP, UI показывает
# плашку «Ожидание данных…». Вместо статики отдаём последнюю ОСМЫСЛЕННУЮ строку
# netifd для этого интерфейса (прото-хендлеры туда пишут ход дозвона: «Register
# with network», «Attach», «Connected», у нашего fibocom - «холодный дозвон»,
# «no IP with IPV4, retrying IPV4V6», «IPv6 … поднят», ошибки). Читаем лог ТОЛЬКО
# когда соединения ещё нет (CONN_TIME="-"): у подключённого модема не тратимся.
conn_status_line() {   # $1 = имя интерфейса
	[ "$CONN_TIME" = "-" ] || return 0
	[ -n "$1" ] || return 0
	# Отсекаем ШУМ netifd (не статусы дозвона, а его внутренние гонки): строка
	# «Command failed: ubus call … notify_proto … (Permission denied)» пугает и
	# бессмысленна. Берём последнюю ОСМЫСЛЕННУЮ прото-строку. Фронтенд по ней (и по
	# состоянию модема) сам подбирает короткую стадию - сырьё в UI не показываем.
	logread 2>/dev/null | grep -F "netifd: $1 (" \
		| grep -vE "notify_proto|Command failed|Permission denied" \
		| tail -1 \
		| sed -e 's/.*netifd: '"$1"' ([0-9]*): *//' \
		      -e 's/^[a-zA-Z]*\[[0-9]*\] *//' \
		| tr -d '"\\' | head -c 160
}

# Снимок метрик одним куском. Вынесен в функцию, потому что печатается ДВАЖДЫ:
# частично - сразу после ядра (ниже), полностью - в конце опроса. Подстановки
# раскрываются В МОМЕНТ ВЫЗОВА: у частичного вызова профильные переменные ещё
# пусты (sanitize превратит их в "-"), финальный печатает всё.
# ВАЖНО (урок в шапке serve_cache): никаких '#'-комментариев ВНУТРИ heredoc -
# они уезжают прямо в JSON и ломают разбор.
# ЧТО МОЖНО ПОСЧИТАТЬ ДО heredoc - СЧИТАЕМ ДО НЕГО, И ОДИН РАЗ.
#
# Внутри heredoc каждая подстановка `$(...)` - это подоболочка, а `uci`/`pgrep`/
# `cat` внутри неё - ещё и процесс. Конфиг за время опроса не меняется, поэтому
# proto/apn/pdp/kind/mm_exclude/vidpid читаются ровно один раз на процесс - при
# ХОЛОДНОМ старте снимок печатается ДВАЖДЫ (частичный и полный), и без этого всё
# перечисленное считалось бы дважды.
#
# Файлы sysfs читаем `read`, а не `cat`: значение короткое, процесс не нужен.
_SNAP_PREPARED=""
_snap_prepare() {
	[ -n "$_SNAP_PREPARED" ] && return 0
	_SNAP_PREPARED=1

	_SN_VID=""; _SN_PID=""
	read -r _SN_VID 2>/dev/null < "/sys/bus/usb/devices/$_POLL_AM/idVendor"
	read -r _SN_PID 2>/dev/null < "/sys/bus/usb/devices/$_POLL_AM/idProduct"
	_SN_VIDPID="$_SN_VID:$_SN_PID"

	_SN_IFPROTO=$(uci -q get "network.$SEC.proto")
	_SN_APN=$(uci -q get "network.$SEC.apn")
	_SN_PDP="$(uci -q get "network.$SEC.pdptype")$(uci -q get "network.$SEC.pdp")$(uci -q get "network.$SEC.iptype")"
	[ "$(uci -q get "network.$SEC.allow_roaming")" = "1" ] && _SN_ROAMOK=1 || _SN_ROAMOK=0

	pgrep ModemManager >/dev/null 2>&1 && _SN_MMRUN=1 || _SN_MMRUN=0

	_SN_KIND=$(uci -q get "5gmodem.$_hl_sec.kind")
	[ "$_SN_KIND" = "hilink" ] && _SN_ATDBG=1 || _SN_ATDBG=0

	_SN_MMX=$(uci -q get "5gmodem.$_hl_sec.mm_exclude")
	case "$_SN_MMX" in
		0|1) _SN_MMHID="$_SN_MMX" ;;
		*) [ "$_SN_IFPROTO" = modemmanager ] && _SN_MMHID=0 || _SN_MMHID=1 ;;
	esac

	# СЧЁТЧИК ЖИЗНЕЙ НА USB-ШИНЕ. «Бесконечная инициализация» в двух живых
	# отчётах (L860 на Cudy TR3000: 7 переподключений за 12 минут, дважды
	# смерть через секунду после появления) - это модем, падающий с шины, а не
	# зависший дозвон. Человек видел вечное «Инициализация...» и винил
	# программу, пока счётчик ре-энумераций не всплыл в диагностике. Теперь он
	# в снимке: номер текущей энумерации - в строке стадии, а частые обрывы
	# за последние 10 минут - отдельным предупреждением про питание.
	_SN_USBENUM=0; _SN_USBFLAP=0
	if [ -n "$_POLL_AM" ]; then
		eval "$(dmesg 2>/dev/null | awk -v p="usb $_POLL_AM:" -v now="$(uptime_s)" '
			index($0, p " new ") { n++ }
			index($0, p " USB disconnect") {
				ts = $0; sub(/^\[[ \t]*/, "", ts); sub(/\..*/, "", ts)
				if (ts + 0 > now - 600) f++
			}
			END { printf "_SN_USBENUM=%d; _SN_USBFLAP=%d", n + 0, f + 0 }')"
	fi

	_SN_XMM=0
	if [ -f /lib/netifd/proto/xmm.sh ] \
	   && uci show 5gmodem 2>/dev/null | grep -qiE "vidpid='(2cb7:0007|8087:095a)'|\.model='[^']*L8[56]0"; then
		_SN_XMM=1
	fi
}

