	HOME_OP=$(awk -F';' '$1=="'"${HOME_MCC}${HOME_MNC}"'"{print $3; exit}' "$RES/mccmnc.dat" \
		| tr -d '\r')
fi
# Имя из профиля eSIM (SPN) - высший приоритет, перебивает IMSI-фолбэк.
[ -n "$SPN_NAME" ] && HOME_OP="$SPN_NAME"

