# ПОДКЛЮЧАЕМ РАНЬШЕ, чем прежде (было перед захватом AT-замка, строкой ниже 500).
# Причина не стилистическая: имя секции модема по USB-пути вычислялось инлайном
# пять раз в этом файле, а общая secname лежит именно здесь и до сих пор была
# недоступна первым из этих мест. Файл без побочных эффектов - только определения.
. "$RES/lib.sh"

# --- Кэш метрик: снимок для тех, кому не нужен свежий опрос -------------------
#
# Полный опрос стоит ~0.6 c, и ЛЮБОЙ его вызов лезет в AT-порт, за который и так
# дерутся SMS, слоты и профили (при коллизии ответы перепутываются). Виджету на
# странице статуса свежесть до секунды не нужна - ему хватит последнего снимка.
#
#   5gmodem.sh json          - полный опрос (как раньше) + запись снимка
#   5gmodem.sh cached [сек]  - отдать снимок, если он свежее <сек> (по умолчанию
#                              15); иначе сделать полный опрос. Модем не трогаем
#                              вовсе, пока снимок свежий.
#
# Снимок пишется АТОМАРНО (tmp + mv): читатель никогда не увидит полфайла.
# Возраст считаем по /proc/uptime, а не date: у busybox `find -mmin` умеет
# только минуты, а /proc/uptime не врёт при скачках системного времени
# (тот же приём, что в listmodems.sh).
# Путь активного модема: он же КЛЮЧ всех файлов снимка/замка.
_active_path() { uci -q get 5gmodem.@5gmodem[0].active_modem 2>/dev/null; }

# СНИМОК И ЗАМОК - ПО МОДЕМУ, А НЕ ОДИН НА ВСЕХ.
#
# Раньше был ОДИН файл-снимок и ОДИН замок-опросчик на всю систему. На двух
# модемах это ломало переключение: опрос модема B ждал глобальный замок за
# опросом A (хотя порты разные), а в единственном снимке несколько секунд лежали
# данные A - страница показывала ЧУЖОЙ модем и мешала IP/протоколы. Ключ по пути
# развязывает: у каждого модема свой снимок и своя очередь, опросы идут
# параллельно (AT ждёт serial, не CPU), переключение читает СВОЙ снимок мгновенно.
# Активный модем захватываем ОДИН раз на весь опрос. Раньше active_modem читался
# заново в нескольких местах (снимок, AMP_SEC, штамп IMEI), и если пользователь
# переключал вкладку МЕЖДУ этими чтениями, опрос смешивал два модема: писал IMEI
# одного в секцию другого - отсюда ложное «модем перепутан». Формат _MKEY НЕ
# трогаем (по нему именуются файлы-снимки), просто фиксируем значение.
_POLL_AM=$(_active_path)
# Кого страница считает активным - ЗАПОМИНАЕМ ОТДЕЛЬНО: ниже _POLL_AM может быть
# переопределён пиновкой, а помощники, умеющие отвечать только про активного
# (simslot.sh), должны понимать, что их спрашивать уже не о ком.
_ACT_AM="$_POLL_AM"

# ОПРОС НЕ ТОЛЬКО АКТИВНОГО: POLL_MODEM=<usb-путь> в окружении.
#
# ЗАЧЕМ. Снимок метрик заводится только у того модема, который в этот момент
# активен. У остальных его нет ВООБЩЕ, и переключение вкладки выглядит так: клик ->
# перезагрузка страницы -> peek возвращает {} -> пустая карточка -> и лишь через
# ~1 c полного опроса появляются цифры. Замерено на стенде; это же и есть «второй
# модем мёртвый» из жалоб. Лечится подогревом: сторож сессии (он и так раз в 30 c
# обходит ВСЕ модемы по реестру) опрашивает неактивные по кругу, и к моменту клика
# снимок уже лежит - peek отдаёт его за 40 мс.
#
# ПОЧЕМУ ПЕРЕОПРЕДЕЛЕНИЕ, А НЕ ОТДЕЛЬНЫЙ СБОРЩИК. Формат снимка знает только этот
# файл (десятки полей, профили модемов, разбор оператора). Собирать его на стороне
# значило бы вторую реализацию, которая разойдётся с первой.
#
# ГРАНИЦЫ. Пустое окружение = поведение в точности прежнее. Пиновка принимается
# ТОЛЬКО если модем есть в реестре. Ниже под _PINNED отключены ВСЕ откаты на
# глобальные ключи @5gmodem[0] (порт, интерфейс, устройство): они описывают
# активный модем, и подставить их цели - это ровно та подмена, от которой мы
# уходим. Записи в конфиг у опроса идут в секцию ОПРАШИВАЕМОГО ($AMP_SEC) и в его
# интерфейс, глобальных ключей опрос не пишет - проверено.
# АДРЕСНЫЙ ОПРОС ИЗ БРАУЗЕРА. Страница не может задать переменную окружения
# (fs.exec её не передаёт), поэтому путь модема принимается аргументом:
#   5gmodem.sh cached <ttl> <usb-path>   5gmodem.sh peek <usb-path>
# Так карточка ВЫБРАННОЙ вкладки показывает свой модем, а не «активного» -
# рассинхрон вкладки и active_modem больше не даёт микса данных (31.07.2026).
# Шаблон пути строгий: чужое значение просто игнорируем и ведём себя как раньше.
case "$1" in
	cached) _pm_arg="$3" ;;
	peek)   _pm_arg="$2" ;;
	*)      _pm_arg="" ;;
esac
# Страница шлёт его в виде "for=<path>" (контракт был, но бэкенд его НЕ РАЗБИРАЛ
# и молча отдавал активного - это и был источник «микса данных двух модемов»).
case "$_pm_arg" in
	for=*) _pm_arg="${_pm_arg#for=}" ;;
esac
case "$_pm_arg" in
	'' ) : ;;
	*[!0-9.:_-]*) : ;;
	*) POLL_MODEM="$_pm_arg" ;;
esac

_PINNED=""
if [ -n "$POLL_MODEM" ]; then
	case "$POLL_MODEM" in
		*[!A-Za-z0-9.:_-]*) ;;
		*)
			# Подтверждение присутствия: registry ИЛИ sysfs напрямую. Registry
			# под нагрузкой (flock, пересборка кэша) отвечает не мгновенно, и
			# закрепление МОЛЧА падало на активного - а гвард for= ниже, увидев
			# расхождение, отвечал not_active, страница перезагружалась и
			# строилась по активному. Так «обе вкладки показывали один модем»
			# (31.07.2026, Compal+Telit). sysfs детерминирован: воткнут - есть.
			if "$RES/registry.sh" paths 2>/dev/null | grep -qx "$POLL_MODEM" \
			   || [ -d "/sys/bus/usb/devices/$POLL_MODEM" ]; then
				_POLL_AM="$POLL_MODEM"
				_PINNED=1
			fi
			;;
	esac
fi

# Через общую snap_key (lib.sh): формат тот же, но формула теперь одна на всех -
# её же использует подогрев снимков в sessionwatch.sh.
_MKEY=$(snap_key "$_POLL_AM")
CACHE="/tmp/5gmodem_metrics_$_MKEY.json"
STAMP="/tmp/5gmodem_metrics_$_MKEY.stamp"
LOCKDIR="/tmp/5gmodem_poll_$_MKEY.lock"

# uptime_s - из lib.sh (builtin-версия без спавна cut; lib сорсится выше).

# 1 - активный модем сейчас на USB-шине, 0 - нет. Дёшево (sysfs, без AT-хождения).
# Нужно, чтобы отличить «модем ЗАЛИП на шине» (ребут по питанию поможет - страница
# показывает блок частот с кнопкой) от «убран СОВСЕМ» (ребутить нечего - чистый
# скелет). Кладём в ответы «модема нет», по нему решает фронт.
_active_onbus() {
	[ -n "$_POLL_AM" ] && [ -e "/sys/bus/usb/devices/$_POLL_AM" ] && echo 1 || echo 0
}

# ОДИН ПИШУЩИЙ, МНОГО ЧИТАЮЩИХ.
#
# Опрос модема стоит ~3.8 c, и это почти вся задержка: обвязка rpcd добавляет
# 0.01 c (замерено). Но КОНКУРЕНЦИЯ дорога по-настоящему: когда в порт лезут
# двое, тот же опрос занимает 13.4 c вместо 3.8 - в три с половиной раза дольше.
# Поэтому в порт ходит РОВНО ОДИН процесс, а остальные читают снимок.
#
# Блокировка на каталоге - mkdir атомарен на любой ФС, в отличие от проверки
# существования файла. Протухшую (процесс убит) снимаем по возрасту. Ключ - тот
# же путь модема (см. _MKEY выше): замок у каждого модема свой.

# Отдать снимок, подставив в него реальный возраст.
# В сам файл поле "age" пишется нулём (в момент записи он и есть ноль), а здесь
# подменяется на фактический. Потребители читают ОБЩИЙ снимок, и без возраста
# застрявший опрос выглядел бы как живые, но неверные показания.
#
# ВАЖНО: пояснения держим ЗДЕСЬ, а не рядом с полем - блок вывода JSON печатается
# как есть, и любая строка с "#" внутри него уезжает прямо в ответ и ломает
# разбор. Я допустил это дважды: оба раза симптом был один - "quoted object
# property name expected" и разом опустевшие метрики на странице.
serve_cache() {
	_a="${1:-0}"
	# ИМЯ МОДЕМА ПОДСТАВЛЯЕМ НА ВЫДАЧЕ, А НЕ ЖДЁМ НОВОГО СБОРА.
	#
	# alias - не метрика, а подпись: он меняется мгновенно по кнопке, а снимок
	# живёт до 10 c. Вкладка и карточки приоритета имя читают напрямую и
	# обновлялись сразу, а заголовок карточки «Модем» брал его из снимка и
	# отставал на целый тик (замечено владельцем 07.08.2026). Сбрасывать ради
	# подписи весь снимок нельзя - это лишний опрос модема на ровном месте,
	# поэтому просто переписываем поле при отдаче.
	# Секцию считаем ОБЩЕЙ формулой от пути модема (secname), а не из ключа
	# снимка: snap_key даёт свой формат (с хвостовым подчёркиванием) и в имя
	# секции не годится. AMP_SEC здесь ещё пуст - он вычисляется много ниже.
	_sc_al=$(alias_for_path "$_POLL_AM")
	[ -n "$_sc_al" ] || _sc_al="-"
	sed -e "s/\"age\":\"[0-9]*\"/\"age\":\"$_a\"/" \
		-e "s|\"alias\":\"[^\"]*\"|\"alias\":\"$(printf '%s' "$_sc_al" | sed 's/[&|\\]/\\&/g')\"|" \
		"$CACHE" 2>/dev/null || cat "$CACHE"
}

_snapshot_age() {   # возраст снимка в секундах, либо пусто
	[ -s "$CACHE" ] || return 1
	# Владельца проверять НЕ НУЖНО: файл снимка назван по пути активного модема
	# (_MKEY), значит это по определению снимок ИМЕННО текущего модема.
	_n=$(uptime_s); _t=$(cat "$STAMP" 2>/dev/null)
	case "$_t" in ''|*[!0-9]*) return 1 ;; esac
	_a=$((_n - _t)); [ "$_a" -ge 0 ] || return 1
	printf '%s' "$_a"
}

_take_lock() {
	if mkdir "$LOCKDIR" 2>/dev/null; then return 0; fi
	# Протухшая блокировка: опрос дольше 40 c означает, что писавший процесс умер
	# (сам опрос укладывается в 4-14 c даже на медленном железе).
	_lt=$(cat "$LOCKDIR/stamp" 2>/dev/null)
	case "$_lt" in ''|*[!0-9]*) _lt="" ;; esac
	if [ -n "$_lt" ] && [ "$(( $(uptime_s) - _lt ))" -gt 40 ]; then
		rm -rf "$LOCKDIR" 2>/dev/null
		mkdir "$LOCKDIR" 2>/dev/null && return 0
	fi
	return 1
}

# --- МОДЕМ БЕЗ AT-ПОРТОВ ------------------------------------------------------
#
# HiLink-модемы (Huawei E3372h и родня) не имеют ни AT-порта, ни cdc-wdm: весь
# код ниже к ним неприменим - опрашивать нечего и нечем. Их метрики берутся из
# HTTP-API самого модема; формат JSON тот же, поэтому страницы разницы не видят.
#
# Проверка ДО всего остального и делается по конфигу (kind=hilink), а не опросом:
# это одна строка uci, она не стоит ничего и не трогает порты.
# ВАЖНО: признака kind=hilink МАЛО. Такой модем может быть переведён в режим с
# AT-портами (debug), и тогда он обычный - у него есть всё, чего веб-API не даёт
# (TAC, диапазон, USSD). Через API идём, только если AT-порта нет.
# secname + ЗАХВАЧЕННЫЙ путь (_POLL_AM), а не повторное чтение active_modem:
# правило этого файла - фиксировать активный модем один раз на весь опрос
# (см. шапку у _POLL_AM), иначе переключение вкладки посреди опроса смешивает
# два модема. Здесь оно нарушалось.
_hl_sec=$(secname "$_POLL_AM")
_hl_at=$(uci -q get "5gmodem.$_hl_sec.at_port")
[ -n "$_hl_at" ] && [ -c "$_hl_at" ] && _hl_at="yes" || _hl_at=""

# АДРЕСНЫЙ ЗАПРОС: for=<usb-путь> - «метрики ИМЕННО ЭТОГО модема».
#
# ЗАЧЕМ. До этого вызов был безадресным (json / cached N / peek), и скрипт всегда
# обслуживал того, кто записан в active_modem. Какому модему принадлежит ответ, в
# ответе не сообщалось ВООБЩЕ - значит страница не могла ни выбрать модем, ни хотя
# бы заметить, что получила чужие данные. Пока таб и active_modem расходятся
# (переключение ещё не докоммитилось), карточка молча рисовала СОСЕДА.
#
# Живой отчёт (два T99W175 на ZBT, 30.07): активным стоял модем без SIM, который
# не отдаёт ни оператора, ни ICCID, и человек видел во втором табе симку первого.
#
# Здесь НЕ переключаем модем и НЕ опрашиваем неактивного (это дороже и меняет
# поведение опроса целиком - см. шаги 5-6 плана). Отвечаем однозначно: «сейчас
# активен другой», и фронт сам решает - подождать или переключить. Плюс каждый
# снимок теперь несёт поле path (см. emit_snapshot), так что чужие данные
# отличимы от своих даже без этого аргумента.
_WANT=""
for _a in "$@"; do
	case "$_a" in
		for=*) _WANT="${_a#for=}" ;;
	esac
done
if [ -n "$_WANT" ]; then
	# Путь уходит в JSON - пропускаем только безопасный набор символов USB-пути.
	case "$_WANT" in
		*[!A-Za-z0-9.:_-]*)
			printf '{"error":"bad path"}\n'; exit 0 ;;
	esac
	if [ "$_WANT" != "$_POLL_AM" ]; then
		printf '{"error":"not_active","path":"%s","want":"%s"}\n' "$_POLL_AM" "$_WANT"
		exit 0
	fi
fi

# peek: отдать последний снимок ЛЮБОГО возраста (честный возраст в "age") или
# {}, НЕ трогая ни порт, ни замок - ~10 мс. Нужен странице для «тёплого»
# load(): повторное открытие рисует последние известные цифры вместо прочерков,
# не дожидаясь опроса. Возраст 9999 - снимок есть, а штамп потерян (ребут):
# пусть фронт видит, что данные древние.
if [ "$1" = "peek" ]; then
	if [ "$(uci -q get "5gmodem.$_hl_sec.kind")" = "hilink" ] && [ -z "$_hl_at" ]; then
		[ -s /tmp/5gmodem_hilink_metrics ] && cat /tmp/5gmodem_hilink_metrics || echo '{}'
		exit 0
	fi
	_age=$(_snapshot_age) && { serve_cache "$_age"; exit 0; }
	[ -s "$CACHE" ] && { serve_cache 9999; exit 0; }
	echo '{}'
	exit 0
fi

# ЗАХВАТ MM (bands.sh mmtakeover): пока держится пауза инхибиции ЭТОГО модема,
# ModemManager заново пере-пробит его, а наш опрос по тому же cdc-wdm/AT-порту
# конкурировал бы и растягивал пере-пробу за таймаут (наблюдалось: при открытой
# странице MM не поднимал модем и за 60 c). На время паузы отдаём последний снимок
# и в модем НЕ лезем.
if [ -f "/var/run/5gmodem-mm-inhibit/${_POLL_AM}.pause" ]; then
	_age=$(_snapshot_age) && { serve_cache "$_age"; exit 0; }
	[ -s "$CACHE" ] && { serve_cache 9999; exit 0; }
	echo '{}'
	exit 0
fi

if [ "$(uci -q get "5gmodem.$_hl_sec.kind")" = "hilink" ] && [ -z "$_hl_at" ]; then
	# Кэш у этого пути свой: запрос по HTTP дешевле AT-опроса, но дёргать модем
	# на каждый чих всё равно не стоит - страница опрашивает метрики раз в 2 c.
	_hl_cache="/tmp/5gmodem_hilink_metrics"
	_hl_ttl="${2:-5}"
	case "$_hl_ttl" in ''|*[!0-9]*) _hl_ttl=5 ;; esac
	if [ -s "$_hl_cache" ] && [ -z "$(find "$_hl_cache" -mmin +1 2>/dev/null)" ] 	   && [ "$(( $(uptime_s) - $(cat "$_hl_cache.t" 2>/dev/null || echo 0) ))" -lt "$_hl_ttl" ]; then
		cat "$_hl_cache"
		exit 0
	fi
	# ПУТЬ ПЕРЕДАЁМ ЯВНО. Без него hilink.sh брал активный модем сам, а опрос
	# web-API длится десятки секунд: за это время активный меняется, и модель с
	# IMEI стика уезжали в секцию ДРУГОГО модема (см. _hl_path в hilink.sh).
	_hl_out=$("$RES/hilink.sh" json "$_POLL_AM" 2>/dev/null)
	case "$_hl_out" in
		'{'*)
			printf '%s\n' "$_hl_out" > "$_hl_cache.tmp" && mv "$_hl_cache.tmp" "$_hl_cache"
			cut -d. -f1 /proc/uptime > "$_hl_cache.t"
			printf '%s\n' "$_hl_out"
			;;
		# Web-API не ответил. КРАТКО (снимок свежее 30 c) - отдаём прошлый: пустой
		# экран хуже слегка устаревших цифр, модем мог на миг подвиснуть. ДОЛЬШЕ -
		# честно «модема нет» (+ onbus), иначе HiLink-цифры висели живыми ЧАСАМИ,
		# ведь этот путь всегда отдавал старый кэш (issue #2: stale часами).
		*)
			_hl_a=$(( $(uptime_s) - $(cat "$_hl_cache.t" 2>/dev/null || echo 0) ))
			if [ -s "$_hl_cache" ] && [ "$_hl_a" -lt 30 ] 2>/dev/null; then
				cat "$_hl_cache"
			else
				echo "{\"error\":\"Device not found\",\"onbus\":\"$(_active_onbus)\"}"
			fi
			;;
	esac
	exit 0
fi

if [ "$1" = "cached" ]; then
	# МАРКЕР ПРИСУТСТВИЯ СТРАНИЦЫ. Пока кто-то живой опрашивает метрики,
	# фоновый сборщик (sessionwatch) сам держит снимок свежим - и тик страницы
	# почти всегда попадает в готовый кэш, не запуская сбор. Свой же вызов
	# сборщика маркер НЕ обновляет (SW_BG=1), иначе цикл кормил бы сам себя
	# и сбор не останавливался бы никогда после закрытия страницы.
	[ -z "$SW_BG" ] && uptime_s > /tmp/5gmodem_page_active 2>/dev/null
	_ttl="${2:-15}"
	case "$_ttl" in ''|*[!0-9]*) _ttl=15 ;; esac
	_age=$(_snapshot_age)
	if [ -n "$_age" ] && [ "$_age" -lt "$_ttl" ]; then
		serve_cache "$_age"
		exit 0
	fi
	# ЗДЕСЬ БЫЛ SERVE-STALE (отдать протухший снимок сразу + опрос фоном).
	# УБРАН после проверки на живом стенде - он ХУЖЕ синхронного обновления:
	#   1) данные на странице отставали на целый цикл (агрегации при спидтесте
	#      появлялись через 3-5 c вместо мгновенно - тик отдавал ВЧЕРАШНИЙ
	#      снимок, а свежий уезжал следующему);
	#   2) фоновый опрос берёт LOCKDIR ДО at_lock: занятый порт держит его до
	#      10 c, все тики это время сыплют стейл, возраст уполз за 20 c -
	#      наблюдалось «кеш не обновлялся 22 c» при переключении модемов.
	# Синхронное обновление теперь ДЁШЕВО (~1 c: статика в кэше, atprobe по
	# маркеру) - тик с честным опросом даёт всегда свежие данные, как раньше.
	#
	# ХОЛОДНЫЙ СТАРТ (снимка нет вовсе). Раньше опрашивали синхронно - XHR
	# первого тика ждал ВЕСЬ опрос (4+ c). Теперь опрос уходит в фон, а мы ждём
	# ПОЯВЛЕНИЯ снимка: частичная публикация после ядра (см. emit_snapshot)
	# делает его доступным через ~2 c - сигнал/оператор появляются раньше,
	# детали доедут следующим тиком. Шаг ожидания 1 c: у busybox нет дробного
	# sleep. Фон завершился без снимка (модема нет/ошибка) - проваливаемся в
	# синхронный проход ниже: он покажет настоящую ошибку.
	if [ -z "$_age" ]; then
		if [ ! -d "$LOCKDIR" ]; then
			( exec 8>&- 9>&-; "$RES/5gmodem.sh" json ) >/dev/null 2>&1 </dev/null &
		fi
		_w=0
		while [ "$_w" -lt 20 ]; do
			sleep 1; _w=$((_w + 1))
			_a=$(_snapshot_age) && { serve_cache "$_a"; exit 0; }
			[ "$_w" -ge 2 ] && [ ! -d "$LOCKDIR" ] && break
		done
		# Опрос всё ещё идёт, а снимка нет 20 c - порт очень медленный. Отдаём
		# busy, НЕ проваливаясь вниз: там второе 20-секундное ожидание, а на
		# 30-й секунде rpcd убил бы вызов («ошибка XHR»).
		[ "$_w" -ge 20 ] && { echo '{"error":"busy"}'; exit 0; }
	fi
	# Снимок протух. Пробуем стать ТЕМ САМЫМ единственным опрашивающим.
	if ! _take_lock; then
		# Кто-то уже опрашивает. Ждать его бессмысленно: отдаём что есть - чуть
		# устаревшие данные лучше, чем секунды ожидания и вторая ходка в порт.
		# Возраст виден потребителю по stamp, он сам решит, показывать ли пометку.
		_a=$(_snapshot_age) && { serve_cache "$_a"; exit 0; }
		# снимка нет вовсе (первый запуск) - ждём чужой опрос, но недолго
		_w=0
		while [ "$_w" -lt 20 ]; do
			sleep 1; _w=$((_w + 1))
			_a=$(_snapshot_age) && { serve_cache "$_a"; exit 0; }
			[ -d "$LOCKDIR" ] || break
		done
		echo '{"error":"busy"}'
		exit 0
	fi
	uptime_s > "$LOCKDIR/stamp" 2>/dev/null
	trap 'rm -rf "$LOCKDIR" 2>/dev/null' EXIT INT TERM HUP
	# блокировка наша - проваливаемся в полный опрос ниже
else
	# Полный опрос по явному запросу тоже под блокировкой: иначе два таких
	# вызова столкнутся в порту ровно так же, как раньше страница с терминалом.
	if _take_lock; then
		uptime_s > "$LOCKDIR/stamp" 2>/dev/null
		trap 'rm -rf "$LOCKDIR" 2>/dev/null' EXIT INT TERM HUP
	else
		# Порт занят. Свежий снимок (моложе 3 c) - это ровно то, что сейчас
		# дописывает другой процесс; отдаём его вместо второй ходки в модем.
		_age=$(_snapshot_age)
		[ -n "$_age" ] && [ "$_age" -lt 3 ] && { serve_cache "$_age"; exit 0; }
	fi
fi

# ПОРТ ЦЕЛИ, А НЕ АКТИВНОГО. detect.sh по определению отвечает про активный модем,
# поэтому при пиновке берём порт из реестра - он там уже сверен со списком портов
# ИМЕННО этого модема (устаревшую настройку реестр гасит сам). Порта может не
# оказаться вовсе (модем под ModemManager, композиция без tty) - это не ошибка:
# ниже AT-вызовы становятся no-op, а метрики берутся из mmcli/qmicli.
if [ -n "$_PINNED" ]; then
	_pin_rec=$("$RES/registry.sh" path "$_POLL_AM" 2>/dev/null)
	DEVICE=$(printf '%s' "$_pin_rec" | jsonfilter -e '@.at_port' 2>/dev/null)
	# МОДЕМ ПОД ModemManager - AT НЕ ТРОГАЕМ ВООБЩЕ.
	#
	# Без пиновки это выходит само: detect.sh для MM-модема намеренно молчит, и
	# DEVICE остаётся пустым. Под пиновкой порт пришёл бы из секции, и опрос полез
	# бы в tty, которым владеет MM - это ломает ему enable/connect, то есть модем
	# остаётся БЕЗ IP (проверенный класс ошибок, см. detect.sh и mm-inhibit.sh).
	# Метрики такого модема берутся из mmcli - блок ниже по коду.
	# РЕШЕНИЕ ВЛАДЕЛЬЦА (01.08.2026): AT-порт MM-модема опрашиваем НАРАВНЕ с
	# остальными. Прежний запрет (owner=mm -> DEVICE="") делал адресный опрос
	# строже обычного: у Compal под MM троттлинг и температура были видны на
	# своей вкладке и пропадали в снимке соседа и в статистике. Смысла в такой
	# асимметрии нет - вендорные профили дают то, чего mmcli не умеет вовсе
	# (CEITHERM, CA_INFO, антенны), ради этого MBIM/QMI-профили и писались.
	# ЗАЩИТА ОСТАЁТСЯ ОДНА, но общая: очередь at_lock ниже - в порт ходит по
	# одному потребителю за раз. Если вернётся класс «MM не может подключиться»
	# (см. историю правила, 1.9.8.x), лечение - не запрет, а короче таймауты и
	# реже вендорные запросы.
else
	DEVICE=$($RES/detect.sh)
fi

# СЕРИАЛИЗАЦИЯ ДОСТУПА К ПОРТУ. Блокировка выше (LOCKDIR) разводит только опрос
# с опросом, но в тот же tty ходят bands.sh, simslot.sh, esim.sh, smsbridge.sh,
# collect.sh и консоль - именно на ЭТОМ наложении ответы перепутывались (на
# AT#MONI приходил +COPS чужой команды, ATI возвращал +CPIN/+CSQ).
#
# Берём ДО atprobe.sh: он тоже ходит в порт. Не дождались - отдаём снимок:
# устаревшие данные честнее перемешанных, а отличить перепутанный ответ от
# «модем молчит» потом невозможно.
. "$RES/atlock.sh"
# Дозвонщик gcom (прото xmm/atc) нашу очередь не уважает - при живом дозвоне
# уступаем порт сразу, не выстаивая at_lock (см. at_dialer_busy в lib.sh).
if [ -n "$DEVICE" ] && at_dialer_busy "$DEVICE"; then
	_age=$(_snapshot_age)
	[ -n "$_age" ] && { serve_cache "$_age"; exit 0; }
fi
if [ -n "$DEVICE" ] && ! at_lock "$DEVICE" 10; then
	_age=$(_snapshot_age)
	[ -n "$_age" ] && { serve_cache "$_age"; exit 0; }
	# Снимка нет вовсе (первый запуск) - опрашиваем без блокировки: пустая
	# страница хуже, чем данные с риском смешения.
fi

# ПОРТ ДОЛЖЕН ПРИНАДЛЕЖАТЬ ЭТОМУ МОДЕМУ.
#
# detect.sh при неудаче отдаёт ЛЮБОЙ отвечающий tty, а на роутере с двумя
# модемами это порт ЧУЖОГО. Живой случай: воткнули Huawei в режиме HiLink (своих
# AT-портов у него нет), active_modem уже переключился на него, а kind=hilink
# секция получить не успела - опрос пошёл в порт FM350, прочитал его модель и
# записал «Fibocom FM350-GL» в секцию Huawei. Дальше страница показывала чушь.
#
# Проверяем по списку портов ЭТОГО USB-пути. Осторожно: если модема нет в
# listmodems (нестандартная композиция, старый конфиг), НЕ судим - иначе
# сломаем метрики там, где раньше работало.
#
# Список портов даёт РЕЕСТР (он же сверяет at_port у всех остальных потребителей),
# а путь берём ЗАХВАЧЕННЫЙ - здесь стояло повторное чтение active_modem, хотя
# правило этого файла обратное (см. _POLL_AM): в зазор между чтениями попадает
# переключение вкладки, и проверка сверяла бы порт одного модема со списком
# другого - то есть сама делала бы то, что призвана предотвращать.
#
# РАЗЛИЧИЕ «модема нет в перечислении» и «модем есть, но портов у него нет»
# ОБЯЗАТЕЛЬНО. Первое - не судим (см. выше). Второе - судим и порт отвергаем:
# композиции без tty существуют (05c6:9025 в QMI), и как раз для них detect.sh
# особенно охотно отдаёт отвечающий порт СОСЕДА. Признак присутствия - непустое
# поле path в записи; пустой список tty сам по себе о присутствии не говорит.
if [ -n "$DEVICE" ] && [ -n "$_POLL_AM" ]; then
	# Список портов - ПРЯМО из listmodems (кэш, ~4 спавна), а не через registry:
	# тому нужен ещё и uci-слой (штук девять чтений + свой listmodems внутри),
	# а этому гварду - только путь и tty. Замер: вызов registry стоил ~150 мс
	# в КАЖДОМ опросе. Семантика не тронута: присутствие судим по полю path,
	# порт - по списку tty (включая случай «модем есть, портов нет»).
	_own_rec=$("$RES/listmodems.sh" 2>/dev/null)
	if [ -n "$(printf '%s' "$_own_rec" | jsonfilter -e "@[@.path=\"$_POLL_AM\"].path" 2>/dev/null)" ]; then
		_own_ttys=$(printf '%s' "$_own_rec" | jsonfilter -e "@[@.path=\"$_POLL_AM\"].tty[*]" 2>/dev/null | tr '\n' ' ')
		case " $_own_ttys " in
			*" $DEVICE "*) : ;;
			*) logger -t 5gmodem "port $DEVICE does not belong to modem $_POLL_AM - skipping the poll"
			   DEVICE="" ;;
		esac
	fi
fi

# Bounded probe: sms_tool has no timeout and blocks ~35s on a silent/DIAG port,
# so a wrong pinned port froze this whole page on every metrics poll (only
# fixable by editing the config by hand). If the port does not answer AT within
# a few seconds, treat it as not found - every sms_tool call below then fails
# instantly instead of hanging.
#
# МАРКЕР ЖИВОГО ПОРТА: сама проба - это лишний AT round-trip ПЕРЕД КАЖДЫМ
# опросом (а на молчащем порту - до 2 c). Порт, только что ответивший на
# ядровой батч (+CSQ), пробовать заново незачем: маркер пишется после успешного
# ядра, живёт 30 c и стирается, если ядро вылетело по сторожу - следующий
# опрос пробует честно. Ключ - тот же _MKEY, порт в маркере сверяем: после
# переперечисления USB имя tty могло уехать к другому устройству.
PORTOK="/tmp/5gmodem_portok_$_MKEY"
_pok=""
if [ -n "$DEVICE" ]; then
	read -r _pok_port _pok_t 2>/dev/null < "$PORTOK"
	case "$_pok_t" in ''|*[!0-9]*) _pok_t="" ;; esac
	if [ "$_pok_port" = "$DEVICE" ] && [ -n "$_pok_t" ] \
	   && [ "$(( $(uptime_s) - _pok_t ))" -lt 30 ] 2>/dev/null; then
		_pok=1
	fi
fi
[ -n "$DEVICE" ] && [ -z "$_pok" ] && ! "$RES/atprobe.sh" "$DEVICE" && DEVICE=""
if [ -z "$DEVICE" ]; then
	# Порт не ответил на atprobe. Это ЧАСТО ЛОЖНО: порт на миг занят/медленный
	# (особенно на слабом мобильном заходе, где всё грузится разом) или модем
	# коротко переперечислился. Если есть НЕ СЛИШКОМ старый снимок этого модема -
	# отдаём его, а не пугаем «модема нет»: пользователь видел мелькание сообщения
	# на 2-3 c при заходе на «Сеть». Снимок старше 30 c - модем, вероятно, реально
	# пропал, тогда честно сообщаем. Свежие снимки (< ttl) уже отдал cached выше.
	# ИСКЛЮЧЕНИЕ - modemmanager-модем: AT-порт ему намеренно не отдаётся (им владеет
	# MM, detect.sh молчит), но метрики есть в mmcli. НЕ пугаем «Device not found»,
	# а идём дальше: AT-вызовы станут no-op (обёртка sms_tool), а блок mmcli ниже
	# наполнит карточку. Иначе весь блок Модем висел бы на плейсхолдерах.
	_amp0=$(uci -q get 5gmodem.@5gmodem[0].active_modem)
	_amp0_if=$(uci -q get "5gmodem.$(secname "$_amp0").network")
	if [ "$(uci -q get "network.$_amp0_if.proto" 2>/dev/null)" != modemmanager ]; then
		# САМОЛЕЧЕНИЕ: АКТИВНОГО НЕТ В СПИСКЕ МОДЕМОВ - ЗОВЁМ resolve.
		#
		# Переоценку активного делает hotplug, но он срабатывает не всегда: об
		# исчезновении устройства, которое модемом НЕ является (телефон в режиме
		# USB-модема), обработчик не узнаёт вовсе. Тогда активным остаётся путь,
		# которого в списке модемов нет: метрик нет, вкладки нет, переключиться
		# нечем - страница залипает на пустой карточке (живой случай 03.08.2026).
		# resolve эту ситуацию разбирает мгновенно, поэтому зовём его сами - но не
		# чаще раза в минуту, чтобы опрос не превратился в его вызыватель.
		_sh_mark=/tmp/5gmodem_selfresolve
		_sh_now=$(cut -d. -f1 /proc/uptime)
		_sh_last=$(cat "$_sh_mark" 2>/dev/null); case "$_sh_last" in ''|*[!0-9]*) _sh_last=0 ;; esac
		if [ -n "$_POLL_AM" ] && [ "$((_sh_now - _sh_last))" -ge 60 ] \
		   && ! "$RES/listmodems.sh" | jsonfilter -e '@[*].path' 2>/dev/null | grep -qxF "$_POLL_AM"; then
			printf '%s' "$_sh_now" > "$_sh_mark" 2>/dev/null
			logger -t 5gmodem "active modem \"$_POLL_AM\" is missing from the list - re-evaluating (resolve)"
			( "$RES/modemswitch.sh" resolve >/dev/null 2>&1 & ) </dev/null
		fi
		_age=$(_snapshot_age)
		[ -n "$_age" ] && [ "$_age" -lt 30 ] && { serve_cache "$_age"; exit 0; }
		echo "{\"error\":\"Device not found\",\"onbus\":\"$(_active_onbus)\"}"
		exit 0
	fi
fi

# СТОРОЖ НА ВСЕ ВЫЗОВЫ sms_tool. У sms_tool нет таймаута: на подвисшем (или
# занятом чужим опросом) порту он блокирует ~35 c. Под сериализатором это держит
# at_lock, и ВСЯ страница ждёт за одним зависшим опросом - пользователь видел
# «данные не обновлялись 33/56 c, потом пошло». atprobe ограничивал только
# НАЧАЛЬНУЮ пробу, а сам опрос и вызовы из профиля были без предела.
#
# Переопределяем sms_tool ФУНКЦИЕЙ: любой вызов (и здесь, и в profile-файлах,
# что подключаются через "." ниже) идёт со сторожем. Не ответил за 8 c - убиваем,
# отдаём что успело. Реальный бинарь - по абсолютному пути. Счётчик в имени
# temp-файла: вызовы последовательны, но так надёжнее при вложенности.
#
# КЭШ СТАТИКИ - ЗДЕСЬ ЖЕ, ОДНОЙ ТОЧКОЙ. at_static используют 3 профиля из 61;
# остальные на каждом опросе переспрашивают модель/IMEI/IMSI/ICCID/прошивку
# отдельными round-trip'ами - у L850 это 6 лишних ходок в порт ≈ 0.5-1 c
# КАЖДЫЕ 5 секунд. Править 49 профилей - разъедется при первой же правке;
# перехватываем в обёртке: одиночная команда из белого списка отдаётся из
# кэша сырыми байтами 1:1 - парсеры профилей разницы не видят.
# Кэш вечный по ключу модема (${STATIC_CACHE}_cmd_*), сбрасывается сменой
# IMSI (существующий rm ${STATIC_CACHE}_* ниже).
#
# Что НЕ перехватываем: составные (';' - ядровой батч), вендорные ('@'),
# вызовы с -D (их формат вывода отличается: закэшированный -D-ответ пришёл бы
# потом читателю без -D) и всё до определения STATIC_CACHE.
_st_static_key() {   # $*: аргументы вызова -> имя файла кэша либо пусто
	[ -n "$STATIC_CACHE" ] || return 0
	case " $* " in *" -D "*) return 0 ;; esac
	case " $* " in *" at "*) : ;; *) return 0 ;; esac
	eval "_stq=\${$#}"
	case "$_stq" in *";"*|*"@"*) return 0 ;; esac
	_stn_c=$(printf '%s' "$_stq" | tr 'a-z' 'A-Z' | sed 's/^AT//; s/^[+#]//; s/[? ]*$//')
	case "$_stn_c" in
		CGMI|GMI|CGMM|GMM|CGMR|GMR|CGSN|GSN|CIMI|CCID|ICCID|QCCID|GTPKGVER)
			printf '%s' "${STATIC_CACHE}_cmd_$_stn_c" ;;
	esac
}
# Кэшируем ТОЛЬКО валидный ответ: один украденный на коллизии ответ портил бы
# вечный кэш (урок at_static: в файл IMEI однажды въехал ответ чужого #BND).
# Валидный = нет ERROR, есть содержательная строка (не эхо/OK/пустая); для
# идентификаторов (IMEI/IMSI/ICCID) - есть >=14 цифр подряд.
_st_static_ok() {   # $1 - файл ответа
	[ -s "$1" ] || return 1
	grep -q "ERROR" "$1" && return 1
	tr -d '\r' < "$1" | grep -qvE '^AT|^OK$|^$' || return 1
	case "$_stc" in
		*_cmd_CGSN|*_cmd_GSN|*_cmd_CIMI|*_cmd_CCID|*_cmd_ICCID|*_cmd_QCCID)
			grep -qE '[0-9]{14}' "$1" || return 1 ;;
	esac
	return 0
}
_st_n=0
sms_tool() {
	# Нет AT-порта (modemmanager-модем: им рулит MM, detect.sh для него молчит) ->
	# AT-вызовы бессмысленны и опасны (пустой -d ломает разбор аргументов). No-op;
	# метрики такого модема берутся из mmcli (см. блок ниже по коду).
	[ -n "$DEVICE" ] || return 0
	_stc=$(_st_static_key "$@")
	if [ -n "$_stc" ] && [ -s "$_stc" ]; then
		cat "$_stc"
		return 0
	fi
	_st_n=$((_st_n + 1)); _stf="/tmp/5gmodem_st.$$.$_st_n"
	# ЗАКРЫВАЕМ fd лока (8) и хотплаг-лока (9) и у sms_tool, и у сторожа: обоим
	# нужен только сам serial-порт (-d), а НЕ файл блокировки. Иначе они держат
	# его OFD, и осиротевший `sleep` сторожа продолжает держать лок ещё до 8 c
	# ПОСЛЕ выхода опроса - следующий опрос упирался в него на ~8 c (наблюдалось:
	# первый холодный опрос 1 c, каждый следующий 8-9 c).
	/usr/bin/sms_tool "$@" > "$_stf" 2>/dev/null 8>&- 9>&- &
	_stp=$!
	( exec 8>&- 9>&-; sleep 8; kill "$_stp" 2>/dev/null ) >/dev/null 2>&1 </dev/null & _stk=$!
	wait "$_stp" 2>/dev/null; kill "$_stk" 2>/dev/null; wait "$_stk" 2>/dev/null
	if [ -n "$_stc" ] && _st_static_ok "$_stf"; then
		# tmp+mv: конкурирующий читатель кэша не должен увидеть полфайла
		cp "$_stf" "$_stc.$$" 2>/dev/null && mv "$_stc.$$" "$_stc" 2>/dev/null
	fi
	cat "$_stf" 2>/dev/null; rm -f "$_stf"
}

# AT НЕ ТРОГАЕМ МОДЕМ, КОТОРЫМ ФАКТИЧЕСКИ ВЛАДЕЕТ ModemManager, даже если
# протокол интерфейса в конфиге иной (mbim/qmi/пусто - конфиг мог разойтись с
# реальностью, тогда прежние ворота «AT только не при modemmanager» молчали).
# На DW5821e/T77W968 наш AT-батч параллельно MM роняет сессию данных - связь
# падала при каждом открытии вкладки (issue #13). Порт обнуляем: обёртка
# sms_tool делает все AT no-op, карточку наполняет mmcli-блок ниже (его условие
# расширено флагом). Той же дорогой - ручной рычаг no_at в секции модема:
# полный запрет AT-опроса для хрупких прошивок.
_MM_OWNS=""
if [ "$(uci -q get "5gmodem.$_hl_sec.no_at" 2>/dev/null)" = "1" ]; then
	_MM_OWNS=1
	DEVICE=""
elif [ -n "$DEVICE" ]; then
	_mo_if=$(uci -q get "5gmodem.$_hl_sec.network")
	if [ "$(uci -q get "network.$_mo_if.proto" 2>/dev/null)" != modemmanager ] \
	   && mm_owns_path "$_POLL_AM"; then
		_MM_OWNS=1
		DEVICE=""
	fi
