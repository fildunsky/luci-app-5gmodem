isp_numws="$COPS_MCC$COPS_MNC"
# Числовой код оператора уже получен батчем (AT+COPS? формат 2 == COPS_MCC+MNC),
# отдельный round-trip к модему не нужен. Используем как ключ mccmnc.dat.
isp="$isp_numws"

case "$COPS" in
    ''|*[!0-9\ ]*)
