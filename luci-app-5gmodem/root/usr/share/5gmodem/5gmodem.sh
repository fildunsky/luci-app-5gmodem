# МЕТРИКИ modemmanager-МОДЕМА ИЗ mmcli (а НЕ по AT).
# У модема под управлением MM его AT-портом рулит сам MM: detect.sh для него молчит
# (наш AT-опрос ломал MM connect - см. detect.sh/mm-inhibit.sh). Поэтому AT-разбор
# выше даёт пустые переменные, и без этого блока вся карточка Модем висела бы на
# плейсхолдерах. Тянем основное из mmcli: оператор, сигнал %, режим (RAT),
# регистрацию и уровни через --signal-get. Заполняем ТОЛЬКО пустые - у AT-модема
# приоритет за его же данными. mmcli читает по своему каналу, AT-порт не трогает.
if { [ "$IFPROTO" = modemmanager ] || [ -n "$_MM_OWNS" ]; } && command -v mmcli >/dev/null 2>&1; then
	# ИНДЕКС ИМЕННО ОПРАШИВАЕМОГО МОДЕМА. Безадресный mmindex отдаёт индекс
	# АКТИВНОГО, и при опросе соседа (POLL_MODEM: подогрев снимков, карточка
	# другой вкладки) в его снимок и кэш оператора уезжали данные активного -
	# «оба модема показывают одного оператора» (issue #10 и живой стенд с
	# Compal+Telit под MM). Путь опрашиваемого известен всегда - передаём его.
	_MI=$(/usr/share/5gmodem/modemswitch.sh mmindex "$_POLL_AM" 2>/dev/null)
	if [ -n "$_MI" ]; then
		_MK=$(mmcli -m "$_MI" -K 2>/dev/null)
		_mmv() { _v=$(printf '%s\n' "$_MK" | grep -F "$1 " | head -1 | sed 's/^[^:]*:[[:space:]]*//'); [ "$_v" = "--" ] && _v=""; printf '%s' "$_v"; }
		[ -z "$COPS" ]    && COPS=$(_mmv "modem.3gpp.operator-name")
		# Процент из mmcli - ТОЛЬКО когда нет детальных метрик (RSRP): он у многих
		# прошивок пессимистичен (Compal: 12% при RSRP -106), а при живом RSRP
		# сигнал считает sig_percent ниже - как у всех остальных модемов.
		[ -z "$CSQ_PER" ] && [ -z "$RSRP" ] && CSQ_PER=$(_mmv "modem.generic.signal-quality.value")
		# РЕГИСТРАЦИЮ ПЕРЕВОДИМ В КОД, а не кладём словом. Поле registration в
		# нашем JSON - число по 3GPP (0 нет сети, 1 дома, 2 поиск, 3 отказ,
		# 5 роуминг, 6/7 только SMS), и страница по нему выбирает подпись. mmcli
		# отдаёт то же самое СЛОВОМ («home», «roaming»), и раньше оно уходило
		# наружу как есть: ни одно сравнение не срабатывало, и в карточке
		# оставалось сырое значение вместо короткого «В сети». Тот же перевод уже
		# делается для профильной ветки выше - здесь его просто забыли.
		if [ -z "$REG" ]; then
			case "$(_mmv "modem.3gpp.registration-state")" in
				home)             REG=1 ;;
				searching)        REG=2 ;;
				denied)           REG=3 ;;
				roaming)          REG=5 ;;
				home-sms-only)    REG=6 ;;
				roaming-sms-only) REG=7 ;;
				idle)             REG=0 ;;
			esac
		fi
		[ -z "$MODE" ]    && MODE=$(_mmv "modem.generic.access-technologies.value[1]" | tr 'a-z' 'A-Z')
		# Модель: сперва имя из НАШЕЙ секции (там «Compal RXM-G1» и прочие
		# нормализованные имена), и только потом generic из mmcli - тот отдаёт
		# сырое USB-имя («VOS_5G»), и карточка «меняла» модель при переводе в MM.
		[ -z "$MODEL" ]   && MODEL=$(uci -q get "5gmodem.$_hl_sec.model")
		# Нормализуем: mmcli отдаёт сырое имя («VOS_5G»), и оно оседало в секции,
		# перебивая человеческое название в карточке и вкладке (см. model_alias).
		[ -z "$MODEL" ]   && MODEL=$(model_alias "$(_mmv "modem.generic.model")")
		[ -z "$IMEI" ]    && IMEI=$(_mmv "modem.3gpp.imei")
		# Прошивка: её обычно читает AT+CGMR, но под ModemManager AT-порт нам не
		# принадлежит - в карточке стоял прочерк. У MM она есть готовая.
		# Прошивка из mmcli: у части модулей (Dell DW5821e) она приходит
		# РАЗОРВАННОЙ - «T77W968...GC.013\n050  1  [May 31 2021...]», где «050»
		# это ХВОСТ ВЕРСИИ, а не отдельная строка. Берём первую строку, а если
		# следующая начинается с цифр - приклеиваем её через точку.
		if [ -z "$FW" ]; then
			# ВЕРСИЯ СКЛЕИВАЕТСЯ ТОЧКОЙ - так её пишет сам модуль.
			# Эталон - ответ AT^VERSION? на живом DW5821e:
			#   ^VERSION: T77W968.F1.0.0.5.2.GC.013.050
			# А mmcli и ATI печатают ту же версию РАЗОРВАННОЙ и с соседними
			# полями:
			#   T77W968.F1.0.0.5.2.GC.013\n050  1  [May 31 2021 08:00:00]
			# «050» - хвост версии (в ^VERSION? он идёт через точку), одиночная
			# цифра за ним и дата в скобках - УЖЕ ДРУГИЕ ПОЛЯ ответа, в номер
			# они не входят. Поэтому берём первую строку и приклеиваем точкой
			# ПЕРВОЕ поле второй, если это число.
			_fwraw=$(_mmv "modem.generic.revision")
			FW=$(printf '%s' "$_fwraw" | sed 's/\\n/\n/g' | head -1 | xargs)
			_fwtail=$(printf '%s' "$_fwraw" | sed 's/\\n/\n/g' | sed -n '2p' \
				| awk '{print $1}' | grep -xE '[0-9]+' || true)
			[ -n "$_fwtail" ] && FW="$FW.$_fwtail"
		fi
		# У части прошивок mmcli-ревизии нет ВОВСЕ (Compal SG500M2-X с
		# Beeline-конфигом: revision '--', в карточке прочерк), но QMI DMS
		# версию отдаёт: --dms-get-software-version -> «ZX56_643_0.78-12».
		# Кэш по IMEI: версия не меняется, а лишний qmicli на каждый опрос -
		# заметный процесс (см. пояснение у _qmi_refresh).
		case "$FW" in ''|--) FW="" ;; esac
		if [ -z "$FW" ] && [ -n "$IMEI" ]; then
			_fwc="/tmp/5gmodem_fw_$IMEI"
			if [ -s "$_fwc" ]; then
				read -r FW < "$_fwc"
			else
				_fw_w=$(/usr/share/5gmodem/modemswitch.sh wdm "$_POLL_AM" 2>/dev/null)
				if [ -c "$_fw_w" ]; then
					FW=$(qmicli_p "$_fw_w" --dms-get-software-version 2>/dev/null \
						| sed -n "s/.*Software version: *'\{0,1\}\([^']*\)'\{0,1\}\$/\1/p" | head -1 | xargs)
					[ -n "$FW" ] && printf '%s\n' "$FW" > "$_fwc"
				fi
			fi
		fi
		# IMSI/ICCID - ИЗ SIM-ОБЪЕКТА MM. Обычно их читает AT (AT+CIMI/AT+ICCID),
		# но у modemmanager-модема AT-порт нам не принадлежит, и обе строки в
		# карточке стояли прочерками, хотя MM их прекрасно знает. Объект SIM
		# отдельный (modem.generic.sim -> /org/.../SIM/N), поэтому спрашиваем его
		# по индексу и только когда что-то из полей пусто - лишний вызов ни к чему.
		if [ -z "$NR_IMSI" ] || [ -z "$NR_ICCID" ]; then
			_mm_simp=$(_mmv "modem.generic.sim")
			if [ -n "$_mm_simp" ]; then
				_mm_simk=$(mmcli -i "${_mm_simp##*/}" -K 2>/dev/null)
				if [ -z "$NR_IMSI" ]; then
					NR_IMSI=$(printf '%s\n' "$_mm_simk" | sed -n 's/^sim\.properties\.imsi *: *//p' | head -1)
					[ "$NR_IMSI" = "--" ] && NR_IMSI=""
				fi
				if [ -z "$NR_ICCID" ]; then
					NR_ICCID=$(printf '%s\n' "$_mm_simk" | sed -n 's/^sim\.properties\.iccid *: *//p' | head -1)
					[ "$NR_ICCID" = "--" ] && NR_ICCID=""
				fi
			fi
		fi
		# БРЕНД MVNO - ПОВТОРНО, уже с известным IMSI.
		# Блок «домашний бренд поверх хост-сети» отработал ВЫШЕ, когда IMSI ещё
		# не был известен: под ModemManager он приходит только отсюда (AT-батча
		# не было). Из-за этого SIM Т-Мобайл показывалась хост-сетью оператора -
		# «Tele2 RU» вместо «T-Mobile», и иконка бралась чужая. В роуминге НЕ
		# трогаем: там гостевое имя показывается намеренно (см. блок выше).
		if [ "$IS_ROAMING" != "1" ]; then
			_ob_mm=$(opname_brand "${SIMID:-$NR_IMSI}") && COPS="$_ob_mm"
		fi
		# RSRP/RSRQ/RSSI/SINR НЕ трогаем: детальный сигнал отдаёт QMI-профиль модема
		# (modem/usb/*), а mmcli --signal-get дублировал бы ключи. signal-quality (%)
		# выше - достаточный фолбэк для generic MM-модема без профиля.
	fi
fi

# MSISDN (номер телефона) - универсальный фолбэк для ВСЕХ модемов. AT+CNUM выше
# отдаёт номер на AT-модемах; если он пуст, а модем управляется ModemManager
# (напр. Compal, который на AT+CNUM молчит), берём номер из mmcli own-numbers.
# Так номер читается везде, где SIM его хранит, независимо от типа модема.
if [ -z "$PHONE" ] && command -v mmcli >/dev/null 2>&1; then
	# ИНДЕКС ИМЕННО ОПРАШИВАЕМОГО МОДЕМА. Безадресный mmindex отдаёт индекс
	# АКТИВНОГО, и при опросе соседа (POLL_MODEM: подогрев снимков, карточка
	# другой вкладки) в его снимок и кэш оператора уезжали данные активного -
	# «оба модема показывают одного оператора» (issue #10 и живой стенд с
	# Compal+Telit под MM). Путь опрашиваемого известен всегда - передаём его.
	_MI=$(/usr/share/5gmodem/modemswitch.sh mmindex "$_POLL_AM" 2>/dev/null)
	if [ -n "$_MI" ]; then
		PHONE=$(mmcli -m "$_MI" -K 2>/dev/null \
			| sed -n 's/^modem\.generic\.own-numbers[^:]*:[[:space:]]*//p' \
			| tr -d ' ' | grep -E '^[+]?[0-9]{5,}$' | head -1)
	fi
fi

# Разрешённое имя оператора кладём в кэш, читаемый переключателем приоритета
# (netpri.sh): у MBIM/QMI-модемов оператор часто доступен только здесь (числовой
# COPS + mccmnc.dat / UCS2), а не через отдельный AT+COPS у netpri.
# Имя модели, разобранное этим опросом, запоминаем в секции модема. USB-дескриптор
# часто бесполезен (Quectel EC21 = "Android", SimCom = "SimTech, Incorporated"), а
# VID:PID у SimCom один на 7100/7600/8200 - различить их можно только по AT+CGMM.
# Табы и «Приоритет интернета» читают это поле и показывают человеческое имя.
# Пишем только когда модель осмысленная и реально поменялась.
# МОДЕЛЬ НЕ ПРОЧИТАЛАСЬ - БЕРЁМ ИЗ ПЕРЕЧИСЛЕНИЯ, А НЕ ОСТАВЛЯЕМ ПРОЧЕРК.
#
# Пустая MODEL здесь - это либо модем без профиля метрик (живой случай:
# DW5821e-eSIM 0489:e0b5, профиля не было - в карточке прочерки), либо AT-чтение
# не удалось. listmodems уже держит нормализованное имя (из дескриптора и
# таблицы vid:pid) - оно же показывается во вкладках, так что карточка и вкладка
# перестают расходиться. Такое имя может осесть и в секции (гейты _model_sane и
# сверка вендора ниже остаются) - это нормально: оно детерминированное, из
# дескриптора, а если позже AT-чтение даст более точное - перезапишет.
if [ -z "$MODEL" ] && [ -n "$_POLL_AM" ]; then
	MODEL=$("$RES/listmodems.sh" 2>/dev/null \
		| jsonfilter -e "@[@.path=\"$_POLL_AM\"].model" 2>/dev/null | head -1)
fi

AMP_SEC=""
# Из ЗАХВАЧЕННОГО значения (см. _POLL_AM выше), а не читаем active_modem заново -
# иначе AMP_SEC мог бы указывать на другой модем, чем тот, что дал NR_IMEI.
_amp="$_POLL_AM"
[ -n "$_amp" ] && AMP_SEC=$(secname "$_amp")
# Валидаторы имени модели (_model_sane / _model_vendor_ok) переехали в lib.sh:
# их использует и modemswitch.sh, дозаполняя модель НЕактивным модемам.
if [ -n "$MODEL" ] && [ -n "$AMP_SEC" ] \
   && ! _model_vendor_ok "$MODEL" "$(uci -q get "5gmodem.$AMP_SEC.vidpid")"; then
	logger -t 5gmodem "model \"$MODEL\" is not from vendor $(uci -q get "5gmodem.$AMP_SEC.vidpid") - not writing it to the profile"
	MODEL=""
fi
# УСТРОЙСТВУ БЕЗ AT-КАНАЛОВ МОДЕЛЬ НЕ ПРИПИСЫВАЕМ. У него нечем ответить на
# CGMM, значит любой «прочитанный» для него ответ - ЧУЖОЙ (пришёл с порта
# соседа: гонка портов при смене активного). Живой случай 03.08.2026: телефон
# в режиме USB-модема побыл активным, и опрос записал ему модель FM350.
if [ -n "$MODEL" ] && [ -n "$AMP" ] \
   && ! "$RES/listmodems.sh" 2>/dev/null \
	| jsonfilter -e "@[@.path=\"$AMP\"].tty[0]" -e "@[@.path=\"$AMP\"].wdm[0]" 2>/dev/null \
	| grep -q .; then
	MODEL=""
fi
# Буква варианта живёт в дескрипторе, а не в ответе ATI - дополняем (см.
# model_refine): «Quectel EP06» + product «EP06-E» -> «Quectel EP06-E».
if [ -n "$MODEL" ] && [ -n "$AMP_SEC" ]; then
	MODEL=$(model_refine "$MODEL" "$(uci -q get "5gmodem.$AMP_SEC.product")")
fi
# Нормализуем имя из ЛЮБОГО источника (AT/MM/дескриптор), а не только в MM-фолбэке
# выше: сырое "SIMCOM SIM7100E" от AT+CGMM иначе оседало в секции мимо model_alias
# и затирало нормализованное "SimCom SIM7100E".
[ -n "$MODEL" ] && MODEL=$(model_alias "$MODEL")
# ПОРТ ДОЛЖЕН ПРИНАДЛЕЖАТЬ ОПРОШЕННОМУ МОДЕМУ. Ровно такой же гвард стоит ниже
# у IMEI, а у модели его не было - и имя, прочитанное с ЧУЖОГО tty (гонка портов
# при смене активного модема), оседало в секции насовсем: проверка вендора для
# generic-идентификаторов Qualcomm (05c6) не судит по определению, а штамп
# model_vp писался тем же чужим значением, поэтому и читатели ему верили.
if [ -n "$MODEL" ] && [ -n "$DEVICE" ] \
   && [ "$(tty_usbpath "$DEVICE" 2>/dev/null)" != "$_POLL_AM" ]; then
	logger -t 5gmodem "port $DEVICE does not belong to the polled modem ${_POLL_AM:-?} - model \"$MODEL\" not recorded"
	MODEL=""
fi
if [ -n "$MODEL" ] && [ -n "$AMP_SEC" ] && _model_sane "$MODEL"; then
	[ "$(uci -q get "5gmodem.$AMP_SEC.model")" = "$MODEL" ] \
	&& [ "$(uci -q get "5gmodem.$AMP_SEC.model_vp")" = "$(uci -q get "5gmodem.$AMP_SEC.vidpid")" ] || {
		uci -q set "5gmodem.$AMP_SEC.model=$MODEL"
		# Штамп железа рядом с именем - см. пояснение в modemswitch.sh (resolve).
		uci -q set "5gmodem.$AMP_SEC.model_vp=$(uci -q get "5gmodem.$AMP_SEC.vidpid")"
		uci -q commit 5gmodem
	}
fi

# ПОДМЕНА МОДЕМА, КОТОРУЮ НЕ ВИДНО ПО vid:pid.
#
# modemswitch.sh ловит замену сравнением vid:pid на USB-пути. Но два ОДИНАКОВЫХ
# модема (один вид, одна модель) при перестановке между разъёмами так не
# различаются: vid:pid совпадает, и секция продолжает считать, что железо то же.
# В итоге интерфейс и APN остаются привязаны к разъёму и достаются ЧУЖОЙ SIM.
#
# IMEI уникален для каждого устройства и уже прочитан этим опросом - значит
# различить их можно без единой лишней AT-команды. Запоминаем его в секции и
# сверяем: разошёлся - настройки относятся к прежнему модему и заведомо неверны.
#
# Сами НИЧЕГО НЕ УДАЛЯЕМ: опрос идёт в фоне, а тихо снести чужой APN и интерфейс -
# именно тот неочевидный сюрприз, которого быть не должно. Ставим метку и пишем
# в журнал; страница настроек модема покажет её и предложит пересоздать.
# IMEI читаем сами, если профиль модема его не дал (у части профилей запроса
# нет вовсе - например у MeigLink). Идём через кэш статики: команда уходит в
# порт ОДИН раз на модем, дальше берётся из файла, поэтому на стоимость опроса
# это не влияет.
if [ -z "$NR_IMEI" ] || [ "$NR_IMEI" = "-" ]; then
	# Шаблон обязателен: IMEI - это 14-16 цифр отдельной строкой, и всё, что на
	# него не похоже, в кэш попасть не должно (см. at_static).
	NR_IMEI=$(at_static imei "AT+CGSN" '^[0-9]{14,16}$' 2>/dev/null | tr -d '\r' \
		| grep -oE '^[0-9]{14,16}$' | head -1)
fi
# IMEI - та же дыра с эхом (AT+CGSN), просто выстреливает реже: на IMEI модем
# отвечает и без карты. Правило то же (одни цифры), и стоять оно должно ДО
# фолбэка: сброшенное эхо тогда подхватит $IMEI от ModemManager, а не оставит
# карточку с прочерком.
case "$NR_IMEI" in
	''|*[!0-9]*) NR_IMEI="" ;;
esac
# ФОЛБЭК НА ModemManager. Выше по коду mmcli-блок кладёт IMEI в переменную $IMEI,
# но наружу и в профиль уходит $NR_IMEI - и связи между ними не было, то есть
# фолбэк не работал вовсе. У модема под MM AT-порт нам не принадлежит: команда
# то проходит, то упирается в занятый порт, - и в карточке «Модем» IMEI то был,
# то показывался прочерком. У MM он есть всегда и берётся по пути АКТИВНОГО
# модема (mm_index_for_path), то есть заведомо про этот модем.
if [ -z "$NR_IMEI" ] || [ "$NR_IMEI" = "-" ]; then
	case "$IMEI" in
		''|*[!0-9]*) : ;;
		*) NR_IMEI="$IMEI" ;;
	esac
fi

# ЭХО КОМАНДЫ ВМЕСТО ЗНАЧЕНИЯ. Профили достают IMSI/IMEI «отрезанием эха»:
#   O=$(sms_tool -d $DEVICE at "AT+CIMI" | xargs); NR_C=${O#AT+CIMI }
# Пока модем отвечает, всё честно. Но БЕЗ SIM-КАРТЫ он отдаёт ровно эхо и больше
# ничего - без цифр и без хвостового пробела, поэтому отрезание не срабатывает и
# в поле уезжает сама команда. Человек наводится на иконку SIM и читает
# «IMSI SIM-карты: AT+CIMI» (живой случай 04.08.2026 на MV31-W без карты).
# Профилей с этим приёмом восемнадцать, и правило у всех одно, поэтому чиним
# ЗДЕСЬ, на входе в снимок: IMSI - это 14-16 цифр и ничего кроме. Всё, что не
# похоже, сбрасываем - следом отработает штатный фолбэк на SIMID из батча.
case "$NR_IMSI" in
	''|*[!0-9]*) NR_IMSI="" ;;
esac

# IMSI - БЕСПЛАТНО, из общего батча. Присваивать его должен профиль модема, но
# делают это не все (у Telit LM960 запроса нет вовсе), и в карточке SIM стоял
# прочерк при том, что +CIMI в батче честно отвечал. Ни одной лишней команды:
# SIMID уже разобран выше из того же ответа.
if [ -z "$NR_IMSI" ] || [ "$NR_IMSI" = "-" ]; then
	case "$SIMID" in
		''|*[!0-9]*) : ;;
		*) NR_IMSI="$SIMID" ;;
	esac
fi

# ICCID - через кэш статики, одна команда на модем. Команда РАЗНАЯ у вендоров:
# Telit отвечает только на AT+ICCID (на AT+CCID и AT#CCID молчит), большинство
# остальных - на AT+CCID. Пробуем по очереди; шаблон не пускает в кэш чужой
# ответ (см. at_static).
if [ -z "$NR_ICCID" ] || [ "$NR_ICCID" = "-" ]; then
	NR_ICCID=$(at_static iccid "AT+ICCID" '[0-9]{18,22}' 2>/dev/null | tr -d '\r' \
		| grep -oE '[0-9]{18,22}' | head -1)
	[ -n "$NR_ICCID" ] || NR_ICCID=$(at_static ccid "AT+CCID" '[0-9]{18,22}' 2>/dev/null \
		| tr -d '\r' | grep -oE '[0-9]{18,22}' | head -1)
fi

# ХВОСТОВЫЕ F - ЗАПОЛНИТЕЛЬ, А НЕ ЧАСТЬ НОМЕРА. Поле ICCID на карте занимает
# ровно 20 полубайт, и номер короче дополняется до конца буквами F. Показывать
# их пользователю нельзя: номер не совпадёт с напечатанным на пластике.
#
# ЧИСТИМ ЗДЕСЬ, А НЕ В ПРОФИЛЕ МОДЕМА. Раньше обрезка стояла только в профилях
# Dell, но ICCID приходит ТРЕМЯ путями - из профиля, из mmcli и через общий
# AT-фолбэк, - и два последних её не делали. Отсюда и «то с F, то без»: пока
# отвечает AT-порт, работает профиль и номер чистый; занял порт ModemManager -
# значение берётся из mmcli как есть, вместе с заполнителем. Тем же переключением
# источника объясняется и оператор «250 11» рядом с ним: обе странности - признак
# того, что данные в этот момент пришли не по AT.
case "$NR_ICCID" in
	*[Ff]) NR_ICCID=$(printf '%s' "$NR_ICCID" | sed 's/[Ff]*$//') ;;
esac

# АКТИВНЫЙ SIM-СЛОТ, если профиль модема его не дал. Заполняют это поле только
# профили Quectel (AT+QUIMSLOT?), а слоты есть и у других: у Telit LM960 их два,
# simslot.sh их видит, но в метрики значение не попадало - в карточке стоял
# прочерк при двух живых слотах.
#
# ЧЕРЕЗ КЭШ. simslot.sh спрашивает QMI (qmicli --uim-get-slot-status) и стоит
# ~1 c - при опросе в 2 c это половина сверху на каждом тике. Слот же меняется
# только когда его переключает пользователь, поэтому держим ответ минуту, а
# simslot.sh при переключении сбрасывает кэш сам - иначе UI минуту показывал бы
# старый слот сразу после переключения.
if [ -z "$SSIM" ] || [ "$SSIM" = "-" ]; then
	_slot_c="/tmp/5gmodem_slot_$_STKEY"
	_slot_age=""
	if [ -s "$_slot_c" ]; then
		_slot_t=$(cat "${_slot_c}.t" 2>/dev/null)
		case "$_slot_t" in
			''|*[!0-9]*) : ;;
			*) _slot_age=$(( $(uptime_s) - _slot_t )) ;;
		esac
	fi
	if [ -n "$_slot_age" ] && [ "$_slot_age" -ge 0 ] && [ "$_slot_age" -lt 60 ]; then
		SSIM=$(cat "$_slot_c" 2>/dev/null)
	elif [ "$_POLL_AM" != "$_ACT_AM" ]; then
		# ОПРАШИВАЕМ НЕ АКТИВНОГО - СЛОТ НЕ СПРАШИВАЕМ ВОВСЕ.
		#
		# simslot.sh знает ровно одного модема - активного (active_modem,
		# registry active, свой кэш по тому же ключу), POLL_MODEM он не
		# принимает. При подогреве снимка соседа это давало сразу две беды:
		#   - в снимок СОСЕДА ложился слот АКТИВНОГО (та самая примесь чужих
		#     данных в карточке, за которой мы гоняемся);
		#   - лок: опрос уже держит порт соседа (ttyUSB4), а simslot просит порт
		#     активного (ttyUSB2) - «at_lock: отказ» на каждом втором круге
		#     подогрева, ровно как в логе zbt.
		# Ждать лока тут нечего: ответ был бы про чужой модем. Поле остаётся
		# пустым до открытия вкладки этого модема - он тогда сам станет активным.
		:
	else
		_slot_v=$("$RES/simslot.sh" status 2>/dev/null \
			| jsonfilter -e '@.active' 2>/dev/null)
		case "$_slot_v" in
			''|*[!0-9]*) : ;;
			*) SSIM="$_slot_v"
			   printf '%s' "$_slot_v" > "$_slot_c" 2>/dev/null
			   uptime_s > "${_slot_c}.t" 2>/dev/null ;;
		esac
	fi
fi

# ГЕЙТ ПРОТИВ РАСЫ: штампуем IMEI, только если active_modem НЕ сменился за время
# опроса. Иначе NR_IMEI (снят с DEVICE в начале) мог бы уйти в секцию модема, на
# который переключились в процессе, - и родить ложное «модем перепутан».
#
# ВТОРОЕ УСЛОВИЕ - ПОРТ ДОЛЖЕН ПРИНАДЛЕЖАТЬ ЭТОМУ ЖЕ МОДЕМУ. Одной проверки
# active_modem мало: он мог не меняться вовсе, а DEVICE - остаться от прошлого
# модема (закреплённый at_port протухает при переэнумерации, а два одинаковых
# модема отличаются только путём). Тогда в секцию уходил ЧУЖОЙ IMEI, и приложение
# считало, что модем подменили: у пользователя с двумя Thales MV31-W оба профиля
# показывали один номер, а лог сыпал «миграцию профиля отменяю».
_STAMP_PATH=$(tty_usbpath "$DEVICE" 2>/dev/null)
if [ -n "$DEVICE" ] && [ "$_STAMP_PATH" != "$_POLL_AM" ]; then
	# ПУСТОЙ ОТВЕТ - ТОЖЕ ОТКАЗ. Раньше условие требовало НЕПУСТОГО владельца, и
	# ровно в момент переэнумерации (порт уже исчез, tty_usbpath молчит) гвард
	# пропускал - а значение к этому моменту могло быть прочитано с ЧУЖОГО tty.
	# Живой случай 01.08.2026: во время флапа Compal при спидтесте секция 2-1.4
	# получила IMEI соседа («modem swap on 2-1.4: 016133312319966 ->
	# 016133311799572»), и следом тот же чужой номер уехал в штамп интерфейса.
	# Не смогли доказать принадлежность порта - не штампуем: следующий круг
	# опроса сделает это спокойно.
	logger -t 5gmodem "port $DEVICE belongs to ${_STAMP_PATH:-an unknown device}, not to the polled modem ${_POLL_AM:-?} - IMEI not recorded"
	NR_IMEI=""
fi
if [ -n "$AMP_SEC" ] && [ -n "$NR_IMEI" ] && [ "$(_active_path)" = "$_POLL_AM" ]; then
	case "$NR_IMEI" in
		*[!0-9]*|'') : ;;                      # не IMEI - молчим
		*)
			# ЭТОТ IMEI УЖЕ ЧИСЛИТСЯ ЗА ДРУГИМ ПРИСУТСТВУЮЩИМ МОДЕМОМ?
			# Тогда мы прочитали чужой: один и тот же аппарат не может стоять в
			# двух портах сразу. Такое же правило уже стоит в ensure_section, а
			# здесь его не было - и именно этим путём портилась секция.
			_foreign=""
			for _fs in $(uci show 5gmodem 2>/dev/null | sed -n "s/^5gmodem\.\(m_[^.]*\)\.imei='$NR_IMEI'\$/\1/p"); do
				[ "$_fs" = "$AMP_SEC" ] && continue
				_fsp=$(uci -q get "5gmodem.$_fs.path")
				[ -n "$_fsp" ] && [ -e "/sys/bus/usb/devices/$_fsp" ] && { _foreign="$_fsp"; break; }
			done
			if [ -n "$_foreign" ]; then
				logger -t 5gmodem "IMEI $NR_IMEI belongs to present modem $_foreign - not writing it into section $AMP_SEC"
				NR_IMEI=""
			fi
			_old_imei=$(uci -q get "5gmodem.$AMP_SEC.imei")
			if [ -z "$NR_IMEI" ]; then
				:
			elif [ -z "$_old_imei" ]; then
				uci -q set "5gmodem.$AMP_SEC.imei=$NR_IMEI"
				uci -q commit 5gmodem
			elif [ "$_old_imei" != "$NR_IMEI" ]; then
				logger -t 5gmodem "modem swap on $(uci -q get 5gmodem.@5gmodem[0].active_modem): IMEI $_old_imei -> $NR_IMEI, settings may belong to the previous modem"
				uci -q set "5gmodem.$AMP_SEC.imei=$NR_IMEI"
				uci -q set "5gmodem.$AMP_SEC.imei_changed=1"
				uci -q commit 5gmodem
			fi
			# ЧИНИМ ШТАМП ВЛАДЕНИЯ НА ИНТЕРФЕЙСЕ. modem_imei проставляется из
			# секции (stamp_iface_owner), поэтому испорченная секция уводила в
			# интерфейс чужой номер - у пострадавшего оба Thales значились одним
			# IMEI, и владение перестало различать модемы. Правим ТОЛЬКО когда
			# интерфейс сам указывает на наш путь: тогда запись заведомо про нас,
			# и защита «интерфейс принадлежит другому модему» не задета.
			# NR_IMEI мог быть обнулён гвардом выше (чужой номер) - тогда чинить
			# нечем: пустой штамп хуже старого, владение по нему не работает.
			_own_if=$(uci -q get "5gmodem.$AMP_SEC.network")
			if [ -n "$NR_IMEI" ] && [ -n "$_own_if" ] \
			   && [ "$(uci -q get "network.$_own_if.modem_path")" = "$_POLL_AM" ] \
			   && [ "$(uci -q get "network.$_own_if.modem_imei")" != "$NR_IMEI" ]; then
				logger -t 5gmodem "interface $_own_if was owned by IMEI $(uci -q get "network.$_own_if.modem_imei") - correcting to $NR_IMEI"
				note_foreign_uci network "опрос: штамп IMEI"
				uci -q set "network.$_own_if.modem_imei=$NR_IMEI"
				uci -q commit network
			fi
			;;
	esac
fi

# ЗАЩИТА ОТ ОТРАВЛЕНИЯ КЭША: $SEC берётся из 5gmodem.network, а $DEVICE - из
# 5gmodem.device/at_port. Если эти два поля разъехались по модемам (см. инвариант
# в modemswitch.sh), COPS прочитан с порта СОСЕДА, и запись в кэш этого
# интерфейса показала бы его оператора у обоих модемов. Пишем, только если порт
# действительно принадлежит модему интерфейса $SEC; иначе молчим - netpri.sh
# сделает собственный probe по стабильному USB-пути.
op_cache_iface() {
	# БЕЗ AT-ПОРТА (MM-модем) сверка по sysfs невозможна - но и фолбэк на $SEC
	# ядовит: при адресном опросе СОСЕДА (POLL_MODEM, подогрев снимков) $SEC
	# указывает на интерфейс АКТИВНОГО, и оператор соседа записывался в чужой
	# файл. Живой случай (issue #10): два EM7455 под MM - обе карточки
	# «Приоритета интернета» показывали оператора активной вкладки. Резолвим
	# интерфейс по ПУТИ опрошенного модема; путь неизвестен - кэш не пишем
	# вовсе (netpri probe заполнит честно, он адресный).
	if [ -z "$DEVICE" ]; then
		_oci_p="${_POLL_AM:-$(uci -q get 5gmodem.@5gmodem[0].active_modem)}"
		[ -n "$_oci_p" ] || return 0
		_oci_s="m_$(echo "$_oci_p" | sed 's/[^A-Za-z0-9]/_/g')"
		uci -q get "5gmodem.$_oci_s.network"
		return
	fi
	_n=$(readlink -f "/sys/class/tty/$(basename "$DEVICE")/device" 2>/dev/null)
	while [ -n "$_n" ] && [ "$_n" != "/" ] && [ ! -f "$_n/idVendor" ]; do _n="${_n%/*}"; done
	[ -f "$_n/idVendor" ] || { printf '%s' "$SEC"; return; }
	_s=$(uci -q show 5gmodem 2>/dev/null \
		| sed -n "s/^5gmodem\.\(m_[^.]*\)\.path='$(basename "$_n")'\$/\1/p" | head -1)
	[ -n "$_s" ] || { printf '%s' "$SEC"; return; }
	uci -q get "5gmodem.$_s.network"
}
# Имя для «Приоритета интернета»: этот виджет опознаёт УПЛИНК/симку, а не текущую
# сеть, поэтому в роуминге пишем ДОМАШНЕГО оператора (бренд симки/eSIM-профиля,
# напр. "GigSky"), а не гостевую сеть (Tele2) - иначе там висели бы «местные»
# оператор и иконка. Дома HOME_OP пуст -> обычный COPS.
_OPNAME="$COPS"
[ "$IS_ROAMING" = "1" ] && [ -n "$HOME_OP" ] && _OPNAME="$HOME_OP"
# Тот же страновой хвост, что и в метриках: файл читает «Приоритет интернета»
# (netpri operator_cached), и без чистки в его карточке оставалось «MegaFon RUS».
_OPNAME=$(operator_clean "$_OPNAME")
if [ -n "$SEC" ] && [ -n "$_OPNAME" ] && ! echo "$_OPNAME" | grep -qE '^[0-9 ]*$'; then
	OPIF=$(op_cache_iface)
	[ -n "$OPIF" ] && printf '%s' "$_OPNAME" > "/tmp/5gmodem_op_$OPIF" 2>/dev/null
fi

# ПРОЦЕНТ СИГНАЛА ИЗ RSRP/SINR/RSRQ, КОГДА +CSQ БЕСПОЛЕЗЕН.
#
# На LTE ряд модемов (SIMCOM SIM7600E - по отчёту) отдаёт "+CSQ: 99,99" -
# «неизвестно», и процент выходил пустым: шкала CSQ рассчитана на 0..31.
# Но RSRP/SINR/RSRQ профиль к этому моменту уже прочитал - это честный уровень.
#
# ЗАПАСНОЙ, НЕ ЗАМЕНА. Срабатывает ТОЛЬКО когда CSQ_PER пуст (валидного +CSQ
# нет): валидный CSQ (0..31) модема мы не перебиваем - у большинства он корректен,
# «умничать» с ним нельзя. FM350 - сознательное исключение: он занижает +CSQ и
# перекрывает его этой же взвешенной формулой прямо в своём профиле (0e8d7127).
#
# Взвешенная оценка вместо голой линейки по RSRP: RSRP один плохо отражает
# «толщину» канала - при хорошем RSRP, но низком SINR (интерференция/край соты)
# линейка рисовала 80 %, а связь ели тянулась. Веса и шкалы - те же, что у FM350
# (выверены на живом железе): RSRP .5, SINR .3, RSRQ .2. Отсутствующие
# компоненты выпадают из среднего, поэтому «только RSRP» тоже даёт результат.
# Считаем через awk: busybox $(( )) не тянет дробное/отрицательное, а метрики
# приходят со знаком.
# CSQ ИЗ RSSI, КОГДА AT-БАТЧА НЕ БЫЛО (modemmanager-модем: +CSQ спросить не у
# кого, а RSSI профиль прочитал по QMI). Обратная формула той же шкалы 3GPP:
# CSQ = (RSSI + 113) / 2, валидный диапазон RSSI -113..-51 -> CSQ 0..31.
# Процент из него - тем же путём CSQ*100/31, что и у валидного +CSQ: прошивка
# в +CSQ кладёт ровно этот RSSI, и один и тот же модем в MBIM (AT жив) и в MM
# должен показывать ОДИНАКОВЫЙ уровень (проверено на Compal: 22 против 19 при
# реальной разнице RSSI -70/-74). Дробный RSSI усекаем: busybox $(( )) дробь
# не переваривает. Взвешенная оценка ниже остаётся фолбэком, когда нет и RSSI.
if [ -z "$CSQ" ] && [ -n "$RSSI" ]; then
	_csq_r=${RSSI%%.*}
	case "$_csq_r" in
		-[0-9]*)
			if [ "$_csq_r" -ge -113 ] 2>/dev/null && [ "$_csq_r" -le -51 ] 2>/dev/null; then
				CSQ=$(( (_csq_r + 113) / 2 ))
				[ -z "$CSQ_PER" ] && CSQ_PER=$(( CSQ * 100 / 31 ))
			fi ;;
	esac
fi

# ПРОЦЕНТ СИГНАЛА: МЕТРИКИ СВОЕЙ ТЕХНОЛОГИИ ГЛАВНЕЕ CSQ.
#
# Раньше очередь была обратной - валидный +CSQ побеждал, а разбор по
# RSRP/RSRQ/SINR включался только когда CSQ пуст. Из-за этого карточка врала
# ровно там, где это больнее всего: RSSI громкий, сота далёкая. Живой стенд
# 25.08.2026 - CSQ 23 рисовал 74 % при RSRP -109, RSRQ -19, SINR 0.0 и реальном
# 1 Мбит/с; по порогам своей технологии те же цифры дают 27 %. Разбор и пороги -
# в sig_percent (lib.sh). CSQ остаётся там, где он законен: 2G и модемы, не
# отдающие ничего кроме него.
_sig_pct=$(sig_percent "$MODE" "$RSRP" "$RSRQ" "$SINR" "$RSCP" "$ECIO" "$RSSI")
[ -n "$_sig_pct" ] && CSQ_PER="$_sig_pct"

_TMP="$CACHE.$$"
emit_snapshot > "$_TMP"

# БЕЗ ПАЙПЛАЙНА. Первая версия писала снимок через `( cat <<EOF ) | tee файл` -
# и вызов через rpcd намертво упирался в его 30-секундный таймаут (проверено:
# 4 из 4), хотя напрямую в консоли отрабатывал за 0.64 c. rpcd ждёт EOF на
# stdout, а лишний процесс в пайплайне держал дескриптор. Пишем в файл, потом
# отдаём его - ни подоболочки, ни tee.
#
# Снимок публикуем, только если он ВАЛИДЕН: полуживой ответ (модем отвалился на
# середине опроса) не должен затирать последний хороший - виджеты читают кэш.
if [ -s "$_TMP" ] && jsonfilter -i "$_TMP" -e '@.modem' >/dev/null 2>&1; then
	cat "$_TMP"
	mv "$_TMP" "$CACHE"      # атомарно: читатель видит либо старый снимок, либо новый
	uptime_s > "$STAMP"
	# OWNER не нужен: имя $CACHE закодировано путём модема (_MKEY), снимок по
	# определению принадлежит текущему модему - чужого не прочитаешь.
else
	cat "$_TMP" 2>/dev/null  # ответ отдаём в любом случае, но в кэш не кладём
	rm -f "$_TMP"
fi
exit 0

