# --- ДОЗАПОЛНЕНИЕ ПО QMI (generic, для любого модема с cdc-wdm) --------------
#
# Часть сведений вендорные AT-команды не отдают вовсе, и прежде всего это
# СОСЕДНИЕ СОТЫ. Реализованы они были только в профиле Compal, хотя сам запрос
# generic (QMI NAS) и у разных вендоров отвечает ОДИНАКОВО: проверено на Compal
# RXM-G1 и Telit LM960A18 - вывод у них одного формата, один и тот же разбор
# прошёл на обоих без единой правки. Поэтому логика переехала сюда, и её
# получают все профили сразу, а не по одному.
#
# Работает НЕЗАВИСИМО от протокола интерфейса: qmicli ходит по cdc-wdm напрямую,
# а когда каналом владеет ModemManager - через прокси (-p). Переводить модем в
# modemmanager ради этих полей НЕ нужно.
#
# ПРОФИЛЬ ГЛАВНЕЕ: заполняем только то, что он оставил пустым. Вендорная команда
# знает про свой модем больше generic-запроса, и перебивать её нельзя.
# Модемы без QMI (напр. FM350 в композиции RNDIS) сюда просто не заходят.
# Сбор QMI-дополнений (соседние соты, ширина канала, мощность передатчика) в
# ФАЙЛЫ - задуман для запуска В ФОНЕ. Три вызова qmicli стоят ~700 мс, и держать
# их в опросе метрик нельзя: тогда каждый опрос, и особенно холодный после
# переключения вкладки, ждал бы эти 700 мс, а карточка показывала прочерки.
# $1 - ключ модема (_MKEY), $2 - его cdc-wdm. Оба ПЕРЕДАЮТСЯ, а не резолвятся
# заново: иначе за время сбора active_modem мог бы смениться, и мы записали бы
# данные другого модема под этим ключом.
_qmi_refresh() {
	_qr_k="$1"; _qr_w="$2"
	_qr_p="/tmp/5gmodem_qmi_$_qr_k"
	[ -c "$_qr_w" ] || return 0

	# Один вызов rf-band-info на всё: полоса, а в 3G ещё и активный диапазон
	# (класс wcdma-*) с каналом (UARFCN). В 3G полоса приходит НЕ числом, а
	# классом 'wcdma-5' (= 5 МГц) - разбираем оба формата.
	_qr_rf=$(qmicli_p "$_qr_w" --nas-get-rf-band-info 2>/dev/null)
	_qr_bw=$(printf '%s\n' "$_qr_rf" | sed -n "s/.*Bandwidth: *'\([0-9]*\)'.*/\1/p" | head -1)
	[ -z "$_qr_bw" ] && _qr_bw=$(printf '%s\n' "$_qr_rf" | sed -n "s/.*Bandwidth: *'wcdma-\([0-9]*\)'.*/\1/p" | head -1)
	[ -n "$_qr_bw" ] && _qr_bw="$_qr_bw MHz"
	_qr_b3=$(printf '%s\n' "$_qr_rf" | sed -n "s/.*Active Band Class: *'\(wcdma-[a-z0-9-]*\)'.*/\1/p" | head -1)
	_qr_u3=""
	[ -n "$_qr_b3" ] && _qr_u3=$(printf '%s\n' "$_qr_rf" | sed -n "s/.*Active Channel: *'\([0-9]*\)'.*/\1/p" | head -1)
	# Мощность передатчика есть ТОЛЬКО пока модем передаёт ("In traffic: 'no'" в
	# покое), поэтому в простое поле законно пустует.
	_qr_txraw=$(qmicli_p "$_qr_w" --nas-get-tx-rx-info=lte 2>/dev/null)
	_qr_tx=$(printf '%s\n' "$_qr_txraw" \
		| awk '/^TX:/{f=1} f && /Power:/ {gsub(/[^0-9.-]/,"",$2); print $2; exit}')
	# АНТЕННЫЕ ПОРТЫ из той же выдачи (RX Chain 0..3). Формат - как у AT-профиля
	# (#LAPS): "порт:rsrp:rsrq ...". Под ModemManager AT-профиль молчит, и
	# таблица антенн у Telit пустовала, хотя QMI цепочки отдаёт (31.07.2026).
	# Знаки прошивка теряет (RSRP '100.3 dBm', ECIO '9.6') - возвращаем минус.
	# «-256.0 dBm» - ЗАГЛУШКА «ИЗМЕРЕНИЯ НЕТ», А НЕ УРОВЕНЬ. Цепь числится
	# включённой ("Radio tuned: yes"), но в этот момент ничего не мерила.
	# Живой Compal RXM-G1 25.08.2026: цепи 0 и 1 дают -106/-104, а 2 и 3 -
	# ровно -256.0 при ECIO -3.0. На AT-пути мы это отсекаем давно (см. фильтр
	# в профиле 05c690d5), а на QMI-пути фильтра не было: в таблице антенн у
	# человека висели два порта с «-256 дБм», то есть нарисованные мёртвые
	# антенны там, где просто нет данных. Оставляем только физичный диапазон.
	_qr_ant=$(printf '%s\n' "$_qr_txraw" | awk '
		/^RX Chain/ { if (t == "yes" && r != "") emit(); n = 0 + substr($3, 1, 1); t = ""; r = ""; q = "" }
		/Radio tuned:/ { t = ($0 ~ /yes/) ? "yes" : "" }
		/RSRP:/ { gsub(/[^0-9.-]/, "", $2); r = $2; if (r + 0 > 0) r = -r }
		/ECIO:/ { gsub(/[^0-9.-]/, "", $2); q = $2; if (q + 0 > 0) q = -q }
		function emit() { if (r + 0 > -160 && r + 0 < -20) { out = out (out == "" ? "" : " ") n ":" r ":" q; ok++ } }
		END { if (t == "yes" && r != "") emit(); printf "%s", out }
	')
	# ВЕРДИКТ РАЗНЕСЁННОГО ПРИЁМА - по числу ЖИВЫХ цепей, как на AT-пути.
	# Меньше двух измеренных уровней - вердикта не даём вовсе: отличить
	# «цепи не мерили» от «цепи мертвы» по одному значению нельзя.
	_qr_rxd=""
	_qr_an=$(printf '%s' "$_qr_ant" | wc -w)
	case "$_qr_an" in
		2)   _qr_rxd="2rx" ;;
		3|4) _qr_rxd="4rx" ;;
	esac
	[ -n "$_qr_tx" ] && _qr_tx="$_qr_tx dBm"

	# Соседние соты. Две секции: "Intrafrequency" - соты на ТОЙ ЖЕ частоте (там же
	# Serving Cell ID, поэтому служебную помечаем флагом, иначе её не отличить от
	# самого сильного соседа), и "Interfrequency" - соты на других частотах,
	# сгруппированные по "Frequency [N]" со своим EARFCN и бендом.
	# Кавычки в awk намеренно не разбираем: значения достаём по цифрам, иначе
	# программу пришлось бы утыкать экранированием, которое в busybox awk
	# ломается молча.
	# СИГНАЛ И СОТА ПО QMI - generic, для модема БЕЗ доступного AT-порта.
	# Под ModemManager AT-порт нам не принадлежит, вендорный профиль (он у
	# большинства модемов AT-овый) молчит, и в карточке оставались прочерки:
	# RSRP/RSRQ/SINR/RSSI, диапазон, EARFCN, TAC, Cell ID. Всё это QMI отдаёт
	# теми же запросами, что мы и так делаем для соседей - через прокси (-p),
	# то есть канал у MM не отбираем. Заполняем ТОЛЬКО пустое (см. _qmi_supplement):
	# вендорный профиль знает про свой модем больше и остаётся главнее.
	_qr_si=$(qmicli_p "$_qr_w" --nas-get-signal-info 2>/dev/null)
	_qr_sig=$(printf '%s\n' "$_qr_si" | awk '
		/^LTE:/ { f=1; next }
		/^[A-Z0-9]+:/ { f=0 }
		f && /RSSI:/ { if (match($0, /-?[0-9.]+/)) rssi = substr($0, RSTART, RLENGTH) }
		f && /RSRQ:/ { if (match($0, /-?[0-9.]+/)) rsrq = substr($0, RSTART, RLENGTH) }
		f && /RSRP:/ { if (match($0, /-?[0-9.]+/)) rsrp = substr($0, RSTART, RLENGTH) }
		f && /SNR:/  { if (match($0, /-?[0-9.]+/)) snr  = substr($0, RSTART, RLENGTH) }
		END { if (rsrp != "" || rssi != "") printf "%s|%s|%s|%s", rssi, rsrq, rsrp, snr }
	')
	# LTE-диапазон и канал из той же rf-band-info (3G-ветка выше берёт wcdma-*)
	_qr_lte=$(printf '%s\n' "$_qr_rf" | awk "
		/Active Band Class: *'eutran-/ { if (match(\$0, /eutran-[0-9]+/)) b = substr(\$0, RSTART + 7, RLENGTH - 7) }
		/Active Channel:/ { if (b != \"\" && c == \"\") { if (match(\$0, /[0-9]+/)) c = substr(\$0, RSTART, RLENGTH) } }
		END { if (b != \"\") printf \"%s|%s\", b, c }
	")
	# АГРЕГАЦИЯ ИЗ QMI. У модема под ModemManager AT-порт не наш, поэтому
	# вендорный профиль (AT^CA_INFO? и родня) не выполняется, и в карточке была
	# одна PCC (issue #11, Telit LN960A16 под MM/QMI: qmicli агрегацию показывал,
	# страница - нет). rf-band-info при активной CA перечисляет ВСЕ несущие
	# отдельными блоками «Band Information»; первая - PCC, остальные - SCC.
	# Пишем в файл, snapshot подставит их только там, где профиль промолчал.
	# АГРЕГАЦИЯ - из nas-get-lte-cphy-ca-info (правильный источник: там PCC и
	# SCC с состоянием). Первый вариант парсил rf-band-info и давал мусор,
	# который делал карточки разных модемов близнецами - см. гвард формата у
	# читателя. SCC берём только активные (deactivated = сконфигурирована, но
	# спит - показывать её как агрегацию значит врать).
	_qr_cai=$(qmicli_p "$_qr_w" --nas-get-lte-cphy-ca-info 2>/dev/null)
	_qr_ca=$(printf '%s\n' "$_qr_cai" | awk '
		function flushs() {
			if (m == "P" && b != "") out = b "," ch
			else if (m == "S" && b != "" && st == "a") out = out "|" b "," ch
			b = ""; ch = ""; st = ""
		}
		/^Primary Cell Info/  { flushs(); m = "P"; next }
		/^Secondary Cell/     { flushs(); m = "S"; next }
		/RX Channel:/  { if (match($0, /[0-9]+/)) ch = substr($0, RSTART, RLENGTH); next }
		/LTE Band:/    { if (match($0, /eutran-[0-9]+/)) b = substr($0, RSTART + 7, RLENGTH - 7); next }
		/State:/       { if ($0 ~ /\047activated/) st = "a"; next }
		END { flushs(); printf "%s", out }
	')
	_qr_cl=$(qmicli_p "$_qr_w" --nas-get-cell-location-info 2>/dev/null)
	# РАССТОЯНИЕ ДО БС по Timing Advance. QMI отдаёт TA обслуживающей соты в
	# микросекундах (round-trip задержка, которую UE компенсирует); дистанция ~
	# TA*c/2 = TA_us*150 м. Оценка грубая: прошивка округляет TA до целых мкс
	# (~150 м на шаг), значение есть только в RRC-connected при активном обмене.
	# Пишем метры; пусто, если поля нет (не-LTE, простой).
	_qr_ta=$(printf '%s\n' "$_qr_cl" | sed -n "s/.*LTE Timing Advance: *'\([0-9]*\)'.*/\1/p" | head -1)
	_qr_dist=""
	[ -n "$_qr_ta" ] && _qr_dist=$((_qr_ta * 150))
	# TAC и Cell ID обслуживающей соты (секция Intrafrequency LTE Info)
	_qr_cell=$(printf '%s\n' "$_qr_cl" | awk '
		/^Intrafrequency LTE Info/ { f=1; next }
		/^[^ \t]/ { f=0 }
		f && /Tracking Area Code:/ { if (match($0, /[0-9]+/)) tac = substr($0, RSTART, RLENGTH) }
		f && /Global Cell ID:/     { if (match($0, /[0-9]+/)) cid = substr($0, RSTART, RLENGTH) }
		END { if (tac != "" || cid != "") printf "%s|%s", tac, cid }
	')
	# 3G serving cell из той же выдачи (секция "UMTS Info"): RSCP/ECIO/PSC/LAC.
	# В LTE секции нет - файл пустеет сам, стейл не живёт дольше цикла.
	_qr_3g=$(printf '%s\n' "$_qr_cl" | awk '
		/^UMTS Info/ { f=1; next }
		/^[^ \t]/    { f=0 }
		f && /Location Area Code:/    { if (match($0, /[0-9]+/)) lac = substr($0, RSTART, RLENGTH) }
		f && /Primary Scrambling Code:/ { if (match($0, /[0-9]+/)) psc = substr($0, RSTART, RLENGTH) }
		f && /RSCP:/ { if (match($0, /-?[0-9.]+/)) rscp = substr($0, RSTART, RLENGTH) }
		f && /ECIO:/ { if (match($0, /-?[0-9.]+/)) ecio = substr($0, RSTART, RLENGTH) }
		END { if (rscp != "" || psc != "") printf "%s|%s|%s|%s", rscp, ecio, psc, lac }
	')
	_qr_nb=$(printf '%s\n' "$_qr_cl" | awk '
		function emit() {
			if (pci == "") return
			printf "%s{\"band\":\"%s\",\"earfcn\":\"%s\",\"pci\":\"%s\",\"rsrp\":\"%s\",\"rsrq\":\"%s\",\"rssi\":\"%s\",\"serving\":%s}",
				(n++ ? "," : ""), band, earfcn, pci, rsrp, rsrq, rssi,
				((sec == "intra" && pci == serv) ? "1" : "0")
			pci = ""
		}
		/^Intrafrequency LTE Info/ { emit(); sec = "intra"; next }
		/^Interfrequency LTE Info/ { emit(); sec = "inter"; next }
		/^[^ \t]/               { emit(); sec = "" }
		sec == ""               { next }
		/EUTRA Absolute RF Channel Number/ {
			emit()
			if (match($0, /[0-9]+/)) earfcn = substr($0, RSTART, RLENGTH)
			band = ""
			if (match($0, /E-UTRA band [0-9]+/)) band = substr($0, RSTART + 12, RLENGTH - 12)
			next
		}
		/Serving Cell ID/  { if (match($0, /[0-9]+/)) serv = substr($0, RSTART, RLENGTH); next }
		/Physical Cell ID/ {
			emit()
			if (match($0, /[0-9]+/)) pci = substr($0, RSTART, RLENGTH)
			rsrp = ""; rsrq = ""; rssi = ""
			next
		}
		/RSRQ:/ { if (match($0, /-?[0-9.]+/)) rsrq = substr($0, RSTART, RLENGTH); next }
		/RSRP:/ { if (match($0, /-?[0-9.]+/)) rsrp = substr($0, RSTART, RLENGTH); next }
		/RSSI:/ { if (match($0, /-?[0-9.]+/)) rssi = substr($0, RSTART, RLENGTH); next }
		END { emit() }
	')

	# Атомарно (mv), чтобы читатель не поймал полузапись.
	printf '%s' "$_qr_ca" > "$_qr_p.ca.tmp" && mv "$_qr_p.ca.tmp" "$_qr_p.ca"
	printf '%s' "$_qr_nb" > "$_qr_p.nb.tmp" && mv "$_qr_p.nb.tmp" "$_qr_p.nb"
	printf '%s' "$_qr_bw" > "$_qr_p.bw.tmp" && mv "$_qr_p.bw.tmp" "$_qr_p.bw"
	printf '%s' "$_qr_tx" > "$_qr_p.tx.tmp" && mv "$_qr_p.tx.tmp" "$_qr_p.tx"
	printf '%s' "$_qr_ant" > "$_qr_p.ant.tmp" && mv "$_qr_p.ant.tmp" "$_qr_p.ant"
	printf '%s' "$_qr_rxd" > "$_qr_p.rxd.tmp" && mv "$_qr_p.rxd.tmp" "$_qr_p.rxd"
	printf '%s' "$_qr_b3" > "$_qr_p.b3g.tmp" && mv "$_qr_p.b3g.tmp" "$_qr_p.b3g"
	printf '%s' "$_qr_u3" > "$_qr_p.u3g.tmp" && mv "$_qr_p.u3g.tmp" "$_qr_p.u3g"
	printf '%s' "$_qr_3g" > "$_qr_p.c3g.tmp" && mv "$_qr_p.c3g.tmp" "$_qr_p.c3g"
	printf '%s' "$_qr_sig" > "$_qr_p.sig.tmp" && mv "$_qr_p.sig.tmp" "$_qr_p.sig"
	printf '%s' "$_qr_lte" > "$_qr_p.lte.tmp" && mv "$_qr_p.lte.tmp" "$_qr_p.lte"
	printf '%s' "$_qr_cell" > "$_qr_p.cell.tmp" && mv "$_qr_p.cell.tmp" "$_qr_p.cell"
	printf '%s' "$_qr_dist" > "$_qr_p.dist.tmp" && mv "$_qr_p.dist.tmp" "$_qr_p.dist"
	cut -d. -f1 /proc/uptime > "$_qr_p.t"
}

# CACHE-FIRST + ФОНОВОЕ ОБНОВЛЕНИЕ. Снимок берёт последние известные QMI-данные
# МГНОВЕННО (заполняя лишь поля, которые профиль оставил пустыми), а свежие
# досчитывает в фоне к следующему опросу. Так карточка на переключении вкладки
# показывает инфо сразу, а не ждёт qmicli.
_QS_TTL=25
_qmi_supplement() {
	command -v qmicli >/dev/null 2>&1 || return 0
	# cdc-wdm активного модема, БЕЗ фолбэка на /dev/cdc-wdm0. Фолбэк был багом на
	# мультимодеме: у модема без своего cdc-wdm (напр. FM350 в RNDIS) он подсовывал
	# канал СОСЕДА, и соседние соты Telit писались в файл FM350. modemswitch.sh wdm
	# и так отдаёт пусто для такого модема - нет своего wdm, QMI-дополнений нет.
	_QS_WDM=$(/usr/share/5gmodem/modemswitch.sh wdm "$_POLL_AM" 2>/dev/null)
	[ -c "$_QS_WDM" ] || return 0

	# КАНАЛ cdc-wdm ЧУЖОЙ, ЕСЛИ ИНТЕРФЕЙС НА proto=qmi.
	#
	# Дополнения (полоса, соседние соты, мощность передатчика) мы читаем через
	# `qmicli -p`, а он поднимает qmi-proxy - тот открывает /dev/cdc-wdm и держит
	# его. Штатный протокол qmi у netifd ходит в то же устройство НАПРЯМУЮ, через
	# uqmi, прокси он не знает. Два владельца на одном канале путают ответы: у
	# пользователя netifd вис на «Waiting for network registration» с «Failed to
	# parse message data», интерфейс оставался pending, а в ядре сыпался
	# NETDEV WATCHDOG с ресетом устройства. Симптом со стороны: после установки
	# всё работает, а после первой ПЕРЕЗАГРУЗКИ соединение больше не поднимается,
	# и лечится только удалением пакета - то есть исчезновением нашего опроса.
	#
	# Отказываемся от дополнений: связь дороже пары полей в карточке. Под
	# ModemManager этого гейта НЕТ и он не нужен - там прокси общий, MM сам через
	# него и работает.
	qmi_channel_free || return 0
	_QS_P="/tmp/5gmodem_qmi_$_MKEY"

	# 0) Кэш ЧУЖОЙ RAT-эры. Модем вернулся из 3G в LTE, а файлы ещё 3G (TTL до
	#    25 c): непустой .b3g при не-3G режиме = стейл. Гасим 3G-файлы, полосу
	#    «5 MHz» не даём протечь в LTE-строку и сбрасываем штамп - фон обновит
	#    данные уже к следующему тику.
	case "$MODE" in
		UMTS*|WCDMA*|HSDPA*|HSUPA*|HSPA*|3G*) : ;;
		*)
			if [ -s "$_QS_P.b3g" ]; then
				: > "$_QS_P.b3g"; : > "$_QS_P.u3g"; : > "$_QS_P.bw"; : > "$_QS_P.c3g"
				rm -f "$_QS_P.t" 2>/dev/null
			fi ;;
	esac

	# 1) Последнее известное - мгновенно. Профиль главнее: не перебиваем непустое.
	[ -z "$NEIGHBORS" ] && [ -s "$_QS_P.nb" ] && NEIGHBORS=$(cat "$_QS_P.nb")
	# Антенные порты из QMI - когда AT-профиль их не дал (MM-модем).
	[ -z "$ANTPORTS" ] && [ -s "$_QS_P.ant" ] && ANTPORTS=$(cat "$_QS_P.ant")
	[ -z "$RXDIV" ] && [ -s "$_QS_P.rxd" ] && RXDIV=$(cat "$_QS_P.rxd")
	# АГРЕГАЦИЯ ИЗ QMI (issue #11): у модема под ModemManager вендорный AT-профиль
	# не выполняется, и SCC оставались пустыми, хотя qmicli их видит. Формат файла:
	# "band,earfcn|band,earfcn|..." - первая пара PCC, дальше SCC1..4. Заполняем
	# ТОЛЬКО пустые поля: профиль (там, где он отработал) знает про модем больше.
	if [ -s "$_QS_P.ca" ]; then
		_qs_ca=$(cat "$_QS_P.ca")
		# Только валидный формат «цифры,цифры|...»: кривой разбор (пойман живьём
		# 31.07: «,|1,100» у ОБОИХ модемов) затирал pband/EARFCN одинаковым
		# мусором - карточки разных модемов становились близнецами.
		case "$_qs_ca" in
			[0-9]*) : ;;
			*) _qs_ca="" ;;
		esac
		_qs_i=0
		IFS='|'
		for _qs_cc in $_qs_ca; do
			_qs_b="${_qs_cc%%,*}"; _qs_c="${_qs_cc#*,}"
			[ -n "$_qs_b" ] || continue
			if [ "$_qs_i" = 0 ]; then
				case "$PBAND" in ''|-) PBAND="B$_qs_b" ;; esac
				case "$EARFCN" in ''|-) EARFCN="$_qs_c" ;; esac
			else
				case "$_qs_i" in
					1) case "$S1BAND" in ''|-) S1BAND="B$_qs_b"; S1EARFCN="$_qs_c" ;; esac ;;
					2) case "$S2BAND" in ''|-) S2BAND="B$_qs_b"; S2EARFCN="$_qs_c" ;; esac ;;
					3) case "$S3BAND" in ''|-) S3BAND="B$_qs_b"; S3EARFCN="$_qs_c" ;; esac ;;
					4) case "$S4BAND" in ''|-) S4BAND="B$_qs_b"; S4EARFCN="$_qs_c" ;; esac ;;
				esac
			fi
			_qs_i=$((_qs_i + 1))
		done
		unset IFS
	fi
	# PCI обслуживающей соты - из той же выдачи соседей (serving:1). Профиль его
	# заполняет не на всех путях: в 5G-NSA-ветке Compal источник (lte-cphy-ca-info)
	# отвечает 'InformationUnavailable', и строка PCI в карточке пустовала, хотя
	# в списке соседей обслуживающая сота есть.
	case "$PCI" in ''|-)
		[ -n "$NEIGHBORS" ] && PCI=$(printf '%s' "$NEIGHBORS" \
			| sed -n 's/.*"pci":"\([0-9]*\)"[^}]*"serving":1.*/\1/p' | head -1)
		;;
	esac
	# СИГНАЛ ПО ВТОРИЧНЫМ НЕСУЩИМ - ИЗ ТЕХ ЖЕ СОСЕДЕЙ, БЕЗ ЛИШНИХ ЗАПРОСОВ.
	#
	# Прямого источника нет: nas-get-lte-cphy-ca-info отдаёт по SCC только
	# PCI/EARFCN/полосу/состояние, а nas-get-signal-info - лишь serving-соту.
	# Но вторичная несущая физически ЕСТЬ в выдаче cell-location-info: она
	# лежит в Interfrequency-секции как сота с тем же PCI и тем же EARFCN
	# (живой пример: SCC1 B40 PCI 378 EARFCN 38950 -> Cell[0] с RSRP -119.9,
	# RSRQ -15.6, RSSI -92.1). Эти данные мы уже собрали в NEIGHBORS, поэтому
	# сопоставление стоит ноль запросов. SINR по SCC не отдаёт никто - остаётся
	# прочерком честно.
	if [ -n "$NEIGHBORS" ]; then
		for _sc_i in 1 2 3 4; do
			eval _sc_pci=\$S${_sc_i}PCI
			eval _sc_ear=\$S${_sc_i}EARFCN
			eval _sc_rsrp=\$S${_sc_i}RSRP
			[ -n "$_sc_pci" ] && [ -n "$_sc_ear" ] || continue
			case "$_sc_rsrp" in ''|-) : ;; *) continue ;; esac
			_sc_rec=$(printf '%s' "$NEIGHBORS" | tr '}' '\n' \
				| grep "\"earfcn\":\"$_sc_ear\"" | grep "\"pci\":\"$_sc_pci\"" | head -1)
			[ -n "$_sc_rec" ] || continue
			_sc_p=$(printf '%s' "$_sc_rec" | sed -n 's/.*"rsrp":"\([^"]*\)".*/\1/p')
			_sc_q=$(printf '%s' "$_sc_rec" | sed -n 's/.*"rsrq":"\([^"]*\)".*/\1/p')
			[ -n "$_sc_p" ] && eval S${_sc_i}RSRP=\$_sc_p
			[ -n "$_sc_q" ] && eval S${_sc_i}RSRQ=\$_sc_q
		done
	fi
	# СИГНАЛ/ДИАПАЗОН/СОТА ИЗ QMI - только то, что осталось пустым.
	# Нужно модему под ModemManager: его AT-порт занят, вендорный AT-профиль
	# ничего не заполнил (Telit LM960 под MM показывал одни прочерки), а QMI
	# те же цифры отдаёт через прокси. У AT-модемов эти поля уже заполнены
	# профилем, и сюда просто не доходит.
	if [ -s "$_QS_P.sig" ]; then
		_QS_S=$(cat "$_QS_P.sig")
		_s_rssi=${_QS_S%%|*}; _s_r=${_QS_S#*|}
		_s_rsrq=${_s_r%%|*};  _s_r=${_s_r#*|}
		_s_rsrp=${_s_r%%|*};  _s_snr=${_s_r##*|}
		case "$RSSI" in ''|-) [ -n "$_s_rssi" ] && RSSI="$_s_rssi" ;; esac
		case "$RSRQ" in ''|-) [ -n "$_s_rsrq" ] && RSRQ="$_s_rsrq" ;; esac
		case "$RSRP" in ''|-) [ -n "$_s_rsrp" ] && RSRP="$_s_rsrp" ;; esac
		case "$SINR" in ''|-) [ -n "$_s_snr" ] && SINR="$_s_snr" ;; esac
		# SINR У QUECTEL БЕРЁМ ИЗ QMI, ДАЖЕ ЕСЛИ AT УЖЕ ЧТО-ТО ДАЛ.
		#
		# Живой опыт с перестановкой SIM 07.08.2026 (EP06-E, две точки на разных
		# сотах): сырое поле SINR в `+QENG` пересчитывается в дБ по формуле,
		# которая завышает на 2-7 дБ - 24 -> 30 при QMI 21.4 и 8 -> -4 при QMI
		# -6.2. Прежняя формула (x*0.2-20) промахивалась ещё сильнее, а `+QCSQ`
		# при RSRQ -15 показывал 9.5 дБ, чего быть не может. Единственное
		# значение, которое сходится с физикой (RSRP/RSRQ и реальной скоростью),
		# приходит из QMI - его и предпочитаем на модемах с живым каналом.
		# RSRP/RSRQ у AT-разбора точны (сверено на одной соте двумя модемами) -
		# их не трогаем.
		# ВЕНДОР ЗДЕСЬ НИ ПРИ ЧЁМ - QMI ОДИН НА ВСЕХ.
		#
		# Изначально предпочтение стояло только для Quectel, но сверка на трёх
		# модемах (07.08.2026) показала: QMI-значение и есть общая точка отсчёта,
		# по которой мы выверяли вендорные AT-формулы у Quectel и SIMCOM. Где
		# канал свободен - берём его; где нет (proto=qmi с живой сессией, модемы
		# без cdc-wdm вроде FM350) - остаётся вендорный разбор, теперь выверенный
		# по документации.
		[ -n "$_s_snr" ] && SINR="$_s_snr"
	fi
	if [ -s "$_QS_P.lte" ]; then
		_QS_L=$(cat "$_QS_P.lte")
		_l_band=${_QS_L%%|*}; _l_earfcn=${_QS_L##*|}
		case "$PBAND" in ''|-)
			[ -n "$_l_band" ] && PBAND=$(band4g "$_l_band")
			;;
		esac
		case "$EARFCN" in ''|-) [ -n "$_l_earfcn" ] && EARFCN="$_l_earfcn" ;; esac
		# Строка режима у generic-модема - голое «LTE» без диапазона; дополняем.
		case "$MODE" in
			LTE|LTE-A|4G) [ -n "$PBAND" ] && MODE="$MODE | $PBAND" ;;
		esac
	fi
	if [ -s "$_QS_P.cell" ]; then
		_QS_C=$(cat "$_QS_P.cell")
		_c_tac=${_QS_C%%|*}; _c_cid=${_QS_C##*|}
		case "$TAC_DEC" in ''|-)
			if [ -n "$_c_tac" ]; then
				TAC_DEC="$_c_tac"; TAC_HEX=$(printf '%X' "$_c_tac" 2>/dev/null)
			fi ;;
		esac
		# НОЛЬ - ЭТО «НЕ ЗАПОЛНЕНО», А НЕ ИДЕНТИФИКАТОР.
		#
		# Часть модемов (живой SIM7100E) кладёт в `+CREG`/`+CEREG` нулевой CID:
		# «+CREG: 2,1,E936,0». Прежняя проверка на пусто/прочерк такой ответ
		# пропускала, и в карточке оставался «ID соты 0», а кнопка карты сот не
		# появлялась вовсе - ей нужен настоящий идентификатор. Ноль лечится
		# ровно теми же путями, что и пустота: QMI ниже или вендорный профиль.
		case "$CID_DEC" in ''|-|0)
			if [ -n "$_c_cid" ]; then
				CID_DEC="$_c_cid"; CID_HEX=$(printf '%X' "$_c_cid" 2>/dev/null)
			fi ;;
		esac
	fi
	case "$BANDWIDTH" in ''|-) [ -s "$_QS_P.bw" ] && BANDWIDTH=$(cat "$_QS_P.bw") ;; esac
	case "$TXPOWER"  in ''|-) [ -s "$_QS_P.tx" ] && TXPOWER=$(cat "$_QS_P.tx") ;; esac
	# Расстояние до БС по TA - только из QMI (вендорный AT его не отдаёт).
	[ -s "$_QS_P.dist" ] && BS_DIST=$(cat "$_QS_P.dist")
	# 3G-диапазон - как у 4G: «UMTS | B1 (2100 MHz)» вместо голого «UMTS».
	# Применяем ТОЛЬКО когда режим сейчас 3G: файлы обновляются раз в TTL, и
	# после возврата в LTE в них ещё до 25 c лежит 3G-запись - гейт по MODE
	# не даёт ей протечь в LTE-строку (и наоборот, в 3G старый LTE-бенд
	# профиля не трогаем: PBAND заполняем только пустой).
	case "$MODE" in
		UMTS*|WCDMA*|HSDPA*|HSUPA*|HSPA*|3G*)
			_QS_B3C=$(cat "$_QS_P.b3g" 2>/dev/null)
			_QS_U3C=$(cat "$_QS_P.u3g" 2>/dev/null)
			# Окно 3G бывает КОРОЧЕ TTL кэша (CS-fallback на USSD ~10 c): фоновое
			# обновление не успевает, файл ещё LTE-эры (пустой) - и строка
			# оставалась голым «UMTS». При таком рассинхроне делаем ОДИН
			# синхронный rf-band-info (~0.2 c) прямо здесь: только в момент
			# смены RAT, устоявшийся LTE/3G этот вызов не платит. Результат
			# кладём в кэш-файлы - соседние тики qmicli не дёргают.
			if [ -z "$_QS_B3C" ] && qmi_channel_free; then
				_QS_RF=$(qmicli_p "$_QS_WDM" --nas-get-rf-band-info 2>/dev/null)
				_QS_B3C=$(printf '%s\n' "$_QS_RF" | sed -n "s/.*Active Band Class: *'\(wcdma-[a-z0-9-]*\)'.*/\1/p" | head -1)
				if [ -n "$_QS_B3C" ]; then
					_QS_U3C=$(printf '%s\n' "$_QS_RF" | sed -n "s/.*Active Channel: *'\([0-9]*\)'.*/\1/p" | head -1)
					_QS_BW3=$(printf '%s\n' "$_QS_RF" | sed -n "s/.*Bandwidth: *'wcdma-\([0-9]*\)'.*/\1 MHz/p" | head -1)
					[ -n "$_QS_BW3" ] && BANDWIDTH="$_QS_BW3"
					printf '%s' "$_QS_B3C" > "$_QS_P.b3g" 2>/dev/null
					printf '%s' "$_QS_U3C" > "$_QS_P.u3g" 2>/dev/null
					[ -n "$_QS_BW3" ] && printf '%s' "$_QS_BW3" > "$_QS_P.bw" 2>/dev/null
				fi
			fi
			if [ -n "$_QS_B3C" ]; then
				_QS_B3=$(band3g "$_QS_B3C")
				if [ -n "$_QS_B3" ]; then
					case "$PBAND" in ''|-) PBAND="$_QS_B3" ;; esac
					case "$MODE" in *"|"*) : ;; *) MODE="$MODE | $_QS_B3" ;; esac
				fi
			fi
			case "$EARFCN" in ''|-) [ -n "$_QS_U3C" ] && EARFCN="$_QS_U3C" ;; esac
			# 3G serving cell (RSCP/ECIO/PSC/LAC) - «Информация о соте» в 3G
			# раньше пустовала: AT-разбора нет, а LTE-поля в UMTS не приходят.
			# Файл пишет фон (_qmi_refresh из той же cell-location-выдачи);
			# в короткое окно CS-fallback догоняем синхронно - только в момент
			# смены RAT, как и диапазон выше.
			_QS_C3=$(cat "$_QS_P.c3g" 2>/dev/null)
			if [ -z "$_QS_C3" ] && [ -n "$_QS_B3C" ]; then
				_QS_C3=$(qmicli_p "$_QS_WDM" --nas-get-cell-location-info 2>/dev/null | awk '
					/^UMTS Info/ { f=1; next }
					/^[^ \t]/    { f=0 }
					f && /Location Area Code:/      { if (match($0, /[0-9]+/)) lac = substr($0, RSTART, RLENGTH) }
					f && /Primary Scrambling Code:/ { if (match($0, /[0-9]+/)) psc = substr($0, RSTART, RLENGTH) }
					f && /RSCP:/ { if (match($0, /-?[0-9.]+/)) rscp = substr($0, RSTART, RLENGTH) }
					f && /ECIO:/ { if (match($0, /-?[0-9.]+/)) ecio = substr($0, RSTART, RLENGTH) }
					END { if (rscp != "" || psc != "") printf "%s|%s|%s|%s", rscp, ecio, psc, lac }
				')
				[ -n "$_QS_C3" ] && printf '%s' "$_QS_C3" > "$_QS_P.c3g" 2>/dev/null
			fi
			if [ -n "$_QS_C3" ]; then
				_c3_rscp=${_QS_C3%%|*}; _c3_r=${_QS_C3#*|}
				_c3_ecio=${_c3_r%%|*};  _c3_r=${_c3_r#*|}
				_c3_psc=${_c3_r%%|*};   _c3_lac=${_c3_r##*|}
				case "$RSCP" in ''|-) [ -n "$_c3_rscp" ] && RSCP="$_c3_rscp" ;; esac
				case "$ECIO" in ''|-) [ -n "$_c3_ecio" ] && ECIO="$_c3_ecio" ;; esac
				case "$PCI"  in ''|-) [ -n "$_c3_psc" ] && PCI="$_c3_psc" ;; esac
				case "$LAC_DEC" in ''|-)
					if [ -n "$_c3_lac" ]; then
						LAC_DEC="$_c3_lac"
						LAC_HEX=$(printf '%X' "$_c3_lac" 2>/dev/null)
					fi ;;
				esac
				# в 3G «RSSI» из LTE-блока не приходит - честный уровень это RSCP
				case "$RSSI" in ''|-) [ -n "$_c3_rscp" ] && RSSI="$_c3_rscp" ;; esac
			fi
			;;
	esac

	# 2) Свежо (< TTL) - обновлять не нужно.
	_QS_MT=$(cat "$_QS_P.t" 2>/dev/null)
	case "$_QS_MT" in ''|*[!0-9]*) _QS_MT=0 ;; esac
	_QS_NOW=$(uptime_s)
	[ "$(( _QS_NOW - _QS_MT ))" -lt "$_QS_TTL" ] && return 0

	# 3) Анти-бёрст: не плодим сборщиков чаще раза в 5 c (несколько опросов могут
	#    прийти подряд). Замок-по-времени, а не флаг: умер сборщик - через 5 c
	#    просто стартует новый, застрять нечему.
	_QS_LS=$(cat "$_QS_P.q" 2>/dev/null)
	case "$_QS_LS" in ''|*[!0-9]*) _QS_LS=0 ;; esac
	[ "$(( _QS_NOW - _QS_LS ))" -lt 5 ] && return 0
	echo "$_QS_NOW" > "$_QS_P.q"

	# 4) Обновляем В ФОНЕ и НЕ ЖДЁМ. Дескрипторы закрываем НА подоболочке (иначе
	#    rpcd висит до таймаута - правило fd-detach), плюс fd 8/9 (замок/хотплуг),
	#    доставшиеся в наследство от опроса. _MKEY и WDM передаём (см. _qmi_refresh).
	( _qmi_refresh "$_MKEY" "$_QS_WDM" >/dev/null 2>&1 </dev/null 8>&- 9>&- & ) >/dev/null 2>&1
	return 0
}

# eNB ID выводится АРИФМЕТИЧЕСКИ и отдельного запроса не требует: у LTE
# 28-битный идентификатор соты склеен из номера базовой станции (старшие 20 бит)
# и номера сектора (младшие 8), т.е. eNB = CID / 256. Проверено на живых данных:
# Telit cid_dec=92686855 -> 362058, сектор 7. Ровно это же число давно
# подставляет в ссылку на карту вышек cell4cellsUrl (num = CID >> 8) - это не
# две разные сущности, а старшая часть ОДНОГО идентификатора.
# Считаем ДО обращения к QMI: тогда поле появляется и у модемов БЕЗ QMI
# (напр. FM350 в композиции RNDIS), а запрос к cdc-wdm остаётся лишь фолбэком
# на случай, когда сам CID неизвестен.
# ТОЛЬКО для LTE/5G-NSA: у UMTS и GSM идентификатор устроен иначе, там деление
# на 256 дало бы правдоподобное, но выдуманное число.
case "$ENBID" in
	''|-)
		case "$MODE" in
			*LTE*|*5G*)
				case "$CID_DEC" in
					''|0|*[!0-9]*) ;;
					*) [ "$CID_DEC" -gt 255 ] && ENBID=$((CID_DEC / 256)) ;;
				esac
				;;
		esac
		;;
esac

