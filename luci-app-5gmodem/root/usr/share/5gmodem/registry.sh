#!/bin/sh
#
# РЕЕСТР МОДЕМОВ - ОДИН ОТВЕТ НА ВОПРОС «КАКОЙ МОДЕМ, КАКОЙ ПОРТ, ЧЕЙ ОН».
#
# ЗАЧЕМ. Сейчас этот вопрос каждый решает сам, и ответы расходятся. Измерено по
# дереву: `active_modem` упоминается 127 раз, чтений глобальных
# `@5gmodem[0].at_port/device/network` - 65, точек записи активного модема - 5.
# Каждая пара «читатель + писатель» - потенциальная гонка, и это не теория:
#
#   - USSD ушёл НЕ ТОМУ модему: порт брался «у активного», а страница определяет
#     свой модем по sms.ussdport, и они разошлись (поймано 30.07);
#   - сторож сессии сравнивал адрес ОДНОГО модема с интерфейсом ДРУГОГО - в его
#     коде до сих пор стоит оговорка «глобальные network и at_port при
#     переключении вкладок меняются НЕ ОДНОВРЕМЕННО»;
#   - смена диапазонов ушла соседнему модему, потому что bands.sh работает с
#     активным, а порт пришёл от другого;
#   - сторож видит ОДИН модем из четырёх: связка «путь -> секция -> интерфейс +
#     AT-порт» готова только у активного, а собирать её для всех было дорого.
#
# Отдельного демона это ещё не делает (см. docs/AUDIT-2026-07-30.md, раздел 5) -
# это первый шаг: единственное место, где связка собирается, и одинаковый ответ
# для всех потребителей.
#
# ЦЕНА. Реестр строится на listmodems.sh (у него свой кэш: 0.01 c тёплый против
# 0.17 c холодного) плюс чтения uci. Своего кэша не держим намеренно: состав
# полей меняется при переключении модема и правке настроек, а лишний слой кэша -
# это лишний способ отдать устаревшую связку, ровно ту беду, от которой уходим.
#
# Usage: registry.sh                 - все модемы, JSON-массив
#        registry.sh path <usb-путь> - один модем
#        registry.sh port <tty>      - модем, которому принадлежит порт
#        registry.sh active          - активный модем
#        registry.sh paths           - только пути, по одному на строку
#        registry.sh flat            - строка на модем, поля через пробел:
#                                      путь секция интерфейс прото at_port владелец
#                                      (пустое поле = «-»)

RES=/usr/share/5gmodem
CFG=5gmodem

. "$RES/lib.sh" 2>/dev/null

# ПЕРЕЧИСЛЕНИЕ БЕРЁМ ОДИН РАЗ, ДО ВСЕГО.
#
# Раньше здесь была «ленивая мемоизация»: _lm() заполнял _LM при первом
# обращении. Она НЕ РАБОТАЛА ни разу - _jq зовут из подстановки `$(...)`, то есть
# в подоболочке, и присваивание _LM умирало вместе с ней. По замеру на стенде это
# и было главной ценой реестра: 9 обращений к полям на запись = 9 запусков
# listmodems.sh (10 мс каждый) вместо одного, `registry.sh` целиком - 260-410 мс
# на двух модемах.
_LM=$("$RES/listmodems.sh" 2>/dev/null)

# СНИМКИ КОНФИГА - ДА, И ЭТО ПЕРЕМЕРЯНО.
#
# Прежняя редакция запрещала их здесь со ссылкой на замер «одна запись 153 -> 179
# мс». Тот замер был снят поверх бага выше: на фоне девяти listmodems.sh на запись
# разница в пару uci тонула в шуме. Реальные цифры на стенде (25.12.5, WH3000):
# `uci show 5gmodem` = 3.5 мс, `uci show network` = 3.5 мс, точечный `uci get` -
# те же 3.5 мс. Конфиги маленькие (87 и 59 строк), поэтому два дампа окупаются уже
# на третьем чтении, а запись реестра делает их восемь.
#
# Реестр ТОЛЬКО ЧИТАЕТ и живёт один вызов - условие из lib.sh соблюдено.
#
# Глаголу `paths` конфиг не нужен вовсе (он отвечает по перечислению), и платить за
# два дампа там не за что - его зовут в циклах подогрева.
# Активный путь - один раз на вызов, а не в каждой записи (он одинаков для всех).
_ACTIVE=""
case "$1" in
	paths) ;;
	*) uci5g_snapshot; ucinet_snapshot; _ACTIVE=$(active_path) ;;
esac

_jq() {   # выражения jsonfilter по данным listmodems (можно несколько -e)
	printf '%s' "$_LM" | jsonfilter "$@" 2>/dev/null
}

# ВЛАДЕЛЕЦ КАНАЛА УПРАВЛЕНИЯ. Отвечает на вопрос «кому можно ходить в этот
# модем»: если им управляет ModemManager, наши AT-запросы мешают ему поднимать
# соединение (проверено: опрос метрик ломал MM-коннект), и метрики надо брать
# через mmcli. Раньше это правило жило оговоркой в четырёх местах - здесь оно
# становится свойством записи.
#   us  - модем наш: MM инхибирован или прото не modemmanager
#   mm  - модемом управляет ModemManager
#   none - интерфейса нет вовсе, управлять нечем
_owner() {   # $1 - секция, $2 - интерфейс, $3 - прото интерфейса
	[ -n "$2" ] || { echo none; return; }
	if [ "$3" = "modemmanager" ] && [ "$(uci5g_get "$1" mm_exclude)" != "1" ]; then
		echo mm
	else
		echo us
	fi
}

# Одна запись реестра. Печатает JSON-объект без внешних скобок массива.
_record() {   # $1 - usb-путь
	_r_p="$1"
	_r_s=$(secname "$_r_p")

	# ДВА ОБРАЩЕНИЯ К jsonfilter НА ЗАПИСЬ ВМЕСТО ДЕВЯТИ.
	# Скаляры - одним вызовом в фиксированном порядке: listmodems печатает эти три
	# ключа ВСЕГДА, а пустое значение даёт пустую строку и порядок не рвёт (в
	# отличие от отсутствующего ключа, который не печатается вовсе - поэтому в один
	# вызов со скалярами массивы не мешаем).
	_r_vp=""; _r_prod=""; _r_ser=""; _r_i=0
	while IFS= read -r _r_l; do
		_r_i=$((_r_i + 1))
		case "$_r_i" in
			1) _r_vp="$_r_l" ;;
			2) _r_prod="$_r_l" ;;
			3) _r_ser="$_r_l" ;;
		esac
	done <<EOF
$(_jq -e "@[@.path=\"$_r_p\"].vidpid" -e "@[@.path=\"$_r_p\"].product" -e "@[@.path=\"$_r_p\"].serial")
EOF
	# Порты - вторым вызовом, все три списка разом. Разложить обратно можно по виду
	# имени: ровно по нему listmodems и раскладывал (tty/ACM - последовательные,
	# прочие /dev - управляющие каналы, без /dev - сетевые имена HiLink).
	_r_tty=""; _r_wdm=""; _r_net=""
	while IFS= read -r _r_l; do
		case "$_r_l" in
			'') ;;
			/dev/tty*) _r_tty="$_r_tty$_r_l " ;;
			/dev/*)    _r_wdm="$_r_wdm$_r_l " ;;
			*)         _r_net="$_r_net$_r_l " ;;
		esac
	done <<EOF
$(_jq -e "@[@.path=\"$_r_p\"].tty[*]" -e "@[@.path=\"$_r_p\"].wdm[*]" -e "@[@.path=\"$_r_p\"].net[*]")
EOF
	_r_if=$(uci5g_get "$_r_s" network)
	_r_proto=""
	[ -n "$_r_if" ] && _r_proto=$(ucinet_get "$_r_if" proto)
	# AT-порт: сохранённый в секции годится только если он ЕСТЬ у этого модема.
	# Настройка устаревает (модем переставили, композиция сменилась), и именно на
	# этом строились ошибки «не тот модем» - поэтому сверяем со списком портов.
	_r_at=$(uci5g_get "$_r_s" at_port)
	if [ -n "$_r_at" ]; then
		case " $_r_tty " in
			*" $_r_at "*) : ;;
			*) _r_at="" ;;
		esac
	fi
	_r_json_list() {   # $1 - список через пробел -> JSON-массив
		_l=""
		for _e in $1; do
			[ -n "$_l" ] && _l="$_l,"
			_l="$_l\"$_e\""
		done
		printf '[%s]' "$_l"
	}
	# product - строка USB-дескриптора. Нужна тем, кто ищет файл профиля по
	# «<vidpid><Product>» (bands.sh): модель из uci для этого не годится, там
	# нормализованное имя.
	#
	# VIDPID - ЖИВОЙ, ИЗ ПЕРЕЧИСЛЕНИЯ, А НЕ ИЗ uci.
	#
	# Сначала он брался из секции, и это давало ту же болезнь, от которой реестр
	# и создан. Секция названа по USB-ПУТИ, поэтому другой модем в том же разъёме
	# наследует её целиком, и до следующего resolve в ней лежит vidpid ПРЕЖНЕГО
	# модема. По этому полю bands.sh выбирает файл профиля (modem/usb/<vidpid>) -
	# то есть команды диапазонов пошли бы по правилам чужого вендора. Заметно это
	# было тем более, что рядом в той же записи product брался живым, из
	# перечисления: одна запись описывала два разных модема.
	# uci оставляем фолбэком: модем мог пропасть с шины, а секция и её настройки
	# ещё нужны (парковка профиля, «Сохранённые профили»).
	[ -n "$_r_vp" ] || _r_vp=$(uci5g_get "$_r_s" vidpid)
	# serial - ЖИВОЙ, из перечисления, и только годный (см. serial_of в lib.sh:
	# заглушки вроде 0123456789ABCDEF и пустые отброшены там). Пусто - нормально:
	# у FM350 серийника нет вовсе, опознание тогда идёт по IMEI и пути, как раньше.
	printf '{"path":"%s","section":"%s","model":"%s","product":"%s","vidpid":"%s","serial":"%s","imei":"%s",' \
		"$_r_p" "$_r_s" \
		"$(uci5g_get "$_r_s" model)" \
		"$_r_prod" \
		"$_r_vp" \
		"$_r_ser" \
		"$(uci5g_get "$_r_s" imei)"
	printf '"iface":"%s","proto":"%s","at_port":"%s","owner":"%s","active":%s,' \
		"$_r_if" \
		"$_r_proto" \
		"$_r_at" "$(_owner "$_r_s" "$_r_if" "$_r_proto")" \
		"$([ "$_r_p" = "$_ACTIVE" ] && echo true || echo false)"
	printf '"tty":%s,"wdm":%s,"net":%s}' \
		"$(_r_json_list "$_r_tty")" \
		"$(_r_json_list "$_r_wdm")" \
		"$(_r_json_list "$_r_net")"
}

_all_paths() { _jq -e '@[*].path'; }

# ПЛОСКАЯ ФОРМА - ДЛЯ ЧИТАТЕЛЕЙ НА ОБОЛОЧКЕ.
#
# JSON удобен странице, но потребителю на shell он стоит по вызову jsonfilter на
# ПОЛЕ: сторож сессии спрашивал owner/iface/proto/at_port у каждого модема и
# тратил на разбор больше, чем на саму проверку. Здесь те же поля уже разложены,
# читаются `while read` без единого подпроцесса.
#
# Пустое поле печатается как «-»: позиционный read на пустом значении съехал бы
# на соседнее поле. В путях, интерфейсах, прото и именах устройств пробелов не
# бывает (их даёт ядро и наш же конфиг), поэтому разделитель - пробел.
_flat() {
	for _f_p in $(_all_paths); do
		_f_s=$(secname "$_f_p")
		_f_if=$(uci5g_get "$_f_s" network)
		_f_pr=""
		[ -n "$_f_if" ] && _f_pr=$(ucinet_get "$_f_if" proto)
		_f_at=$(uci5g_get "$_f_s" at_port)
		if [ -n "$_f_at" ]; then
			_f_t=$(_jq -e "@[@.path=\"$_f_p\"].tty[*]" | tr '\n' ' ')
			case " $_f_t " in
				*" $_f_at "*) : ;;
				*) _f_at="" ;;
			esac
		fi
		printf '%s %s %s %s %s %s\n' \
			"$_f_p" "$_f_s" "${_f_if:--}" "${_f_pr:--}" "${_f_at:--}" \
			"$(_owner "$_f_s" "$_f_if" "$_f_pr")"
	done
}

case "$1" in
paths)
	_all_paths ;;
flat)
	_flat ;;
path)
	[ -n "$2" ] || { echo '{"error":"no path"}'; exit 2; }
	# Модема нет на шине - отвечаем пустым объектом, а не молчанием: вызывающий
	# должен различать «нет такого» и «скрипт не сработал».
	_all_paths | grep -qx "$2" || { echo '{}'; exit 0; }
	_record "$2"; echo ;;
port)
	[ -n "$2" ] || { echo '{"error":"no port"}'; exit 2; }
	for _p in $(_all_paths); do
		_t=$(_jq -e "@[@.path=\"$_p\"].tty[*]" | tr '\n' ' ')
		case " $_t " in
			*" $2 "*) _record "$_p"; echo; exit 0 ;;
		esac
	done
	echo '{}' ;;
active)
	_a="$_ACTIVE"
	[ -n "$_a" ] || { echo '{}'; exit 0; }
	_all_paths | grep -qx "$_a" || { echo '{}'; exit 0; }
	_record "$_a"; echo ;;
''|all)
	_first=1
	printf '['
	for _p in $(_all_paths); do
		[ "$_first" = 1 ] || printf ','
		_first=0
		_record "$_p"
	done
	printf ']\n' ;;
*)
	echo '{"error":"usage: [all] | paths | flat | path <usb> | port <tty> | active"}'
	exit 2 ;;
esac
exit 0
