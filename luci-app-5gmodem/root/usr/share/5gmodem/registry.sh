#!/bin/sh
#
# РЕЕСТР МОДЕМОВ - ОДИН ОТВЕТ НА ВОПРОС «КАКОЙ МОДЕМ, КАКОЙ ПОРТ, ЧЕЙ ОН».
#
# ЗАЧЕМ. Сейчас этот вопрос каждый решает сам, и ответы расходятся. Измерено по
# дереву: `active_modem` упоминается 127 раз, чтений глобальных
# `@5gmodem[0].at_port/device/network` - 65, точек записи активного модема - 5.
# Каждая пара «читатель + писатель» - потенциальная гонка, и это не теория:
#
#   - USSD ушёл НЕ ТОМУ модему: порт брался «у активного», а страница определяет
#     свой модем по sms.ussdport, и они разошлись (поймано 30.07);
#   - сторож сессии сравнивал адрес ОДНОГО модема с интерфейсом ДРУГОГО - в его
#     коде до сих пор стоит оговорка «глобальные network и at_port при
#     переключении вкладок меняются НЕ ОДНОВРЕМЕННО»;
#   - смена диапазонов ушла соседнему модему, потому что bands.sh работает с
#     активным, а порт пришёл от другого;
#   - сторож видит ОДИН модем из четырёх: связка «путь -> секция -> интерфейс +
#     AT-порт» готова только у активного, а собирать её для всех было дорого.
#
# Отдельного демона это ещё не делает (см. docs/AUDIT-2026-07-30.md, раздел 5) -
# это первый шаг: единственное место, где связка собирается, и одинаковый ответ
# для всех потребителей.
#
# ЦЕНА. Реестр строится на listmodems.sh (у него свой кэш: 0.01 c тёплый против
# 0.17 c холодного) плюс чтения uci. Своего кэша не держим намеренно: состав
# полей меняется при переключении модема и правке настроек, а лишний слой кэша -
# это лишний способ отдать устаревшую связку, ровно ту беду, от которой уходим.
#
# Usage: registry.sh                 - все модемы, JSON-массив
#        registry.sh path <usb-путь> - один модем
#        registry.sh port <tty>      - модем, которому принадлежит порт
#        registry.sh active          - активный модем
#        registry.sh paths           - только пути, по одному на строку

RES=/usr/share/5gmodem
CFG=5gmodem

. "$RES/lib.sh" 2>/dev/null

# СНИМКОВ КОНФИГА ЗДЕСЬ НЕТ - И ЭТО ИЗМЕРЕНО, А НЕ ВЫБРАНО.
#
# Приём со снимками (uci5g_snapshot + чтение подстановками, без спавнов) дал в
# netpri.sh заметный выигрыш - там 24+ чтения на вызов. Здесь я применил его же и
# сделал ХУЖЕ: одна запись реестра подорожала со 153 до 179 мс, весь реестр - с
# 215 до 300. Причина простая: снимок - это два ПОЛНЫХ дампа (`uci show 5gmodem` и
# `uci show network`), а экономят они восемь-девять точечных `uci get`. При таком
# числе чтений дампы дороже.
#
# Поэтому геттеры (uci5g_get/ucinet_get) остались - без взятого снимка они
# прозрачно ходят в обычный uci, то есть код един, а цена прежняя. Правило на
# будущее: снимок оправдан от ~15-20 чтений одного конфига за вызов.

_LM=""
_lm() {
	[ -n "$_LM" ] || _LM=$("$RES/listmodems.sh" 2>/dev/null)
	printf '%s' "$_LM"
}

_jq() {   # $1 - выражение jsonfilter по данным listmodems
	_lm | jsonfilter -e "$1" 2>/dev/null
}

# ВЛАДЕЛЕЦ КАНАЛА УПРАВЛЕНИЯ. Отвечает на вопрос «кому можно ходить в этот
# модем»: если им управляет ModemManager, наши AT-запросы мешают ему поднимать
# соединение (проверено: опрос метрик ломал MM-коннект), и метрики надо брать
# через mmcli. Раньше это правило жило оговоркой в четырёх местах - здесь оно
# становится свойством записи.
#   us  - модем наш: MM инхибирован или прото не modemmanager
#   mm  - модемом управляет ModemManager
#   none - интерфейса нет вовсе, управлять нечем
_owner() {   # $1 - секция
	_ow_if=$(uci5g_get "$1" network)
	[ -n "$_ow_if" ] || { echo none; return; }
	_ow_p=$(ucinet_get "$_ow_if" proto)
	if [ "$_ow_p" = "modemmanager" ] && [ "$(uci5g_get "$1" mm_exclude)" != "1" ]; then
		echo mm
	else
		echo us
	fi
}

# Одна запись реестра. Печатает JSON-объект без внешних скобок массива.
_record() {   # $1 - usb-путь
	_r_p="$1"
	_r_s=$(secname "$_r_p")
	_r_tty=$(_jq "@[@.path=\"$_r_p\"].tty[*]" | tr '\n' ' ')
	_r_wdm=$(_jq "@[@.path=\"$_r_p\"].wdm[*]" | tr '\n' ' ')
	_r_net=$(_jq "@[@.path=\"$_r_p\"].net[*]" | tr '\n' ' ')
	_r_if=$(uci5g_get "$_r_s" network)
	# AT-порт: сохранённый в секции годится только если он ЕСТЬ у этого модема.
	# Настройка устаревает (модем переставили, композиция сменилась), и именно на
	# этом строились ошибки «не тот модем» - поэтому сверяем со списком портов.
	_r_at=$(uci5g_get "$_r_s" at_port)
	if [ -n "$_r_at" ]; then
		case " $_r_tty " in
			*" $_r_at "*) : ;;
			*) _r_at="" ;;
		esac
	fi
	_r_json_list() {   # $1 - список через пробел -> JSON-массив
		_l=""
		for _e in $1; do
			[ -n "$_l" ] && _l="$_l,"
			_l="$_l\"$_e\""
		done
		printf '[%s]' "$_l"
	}
	# product - строка USB-дескриптора. Нужна тем, кто ищет файл профиля по
	# «<vidpid><Product>» (bands.sh): модель из uci для этого не годится, там
	# нормализованное имя.
	#
	# VIDPID - ЖИВОЙ, ИЗ ПЕРЕЧИСЛЕНИЯ, А НЕ ИЗ uci.
	#
	# Сначала он брался из секции, и это давало ту же болезнь, от которой реестр
	# и создан. Секция названа по USB-ПУТИ, поэтому другой модем в том же разъёме
	# наследует её целиком, и до следующего resolve в ней лежит vidpid ПРЕЖНЕГО
	# модема. По этому полю bands.sh выбирает файл профиля (modem/usb/<vidpid>) -
	# то есть команды диапазонов пошли бы по правилам чужого вендора. Заметно это
	# было тем более, что рядом в той же записи product брался живым, из
	# перечисления: одна запись описывала два разных модема.
	# uci оставляем фолбэком: модем мог пропасть с шины, а секция и её настройки
	# ещё нужны (парковка профиля, «Сохранённые профили»).
	_r_vp=$(_jq "@[@.path=\"$_r_p\"].vidpid" | head -1)
	[ -n "$_r_vp" ] || _r_vp=$(uci5g_get "$_r_s" vidpid)
	# serial - ЖИВОЙ, из перечисления, и только годный (см. serial_of в lib.sh:
	# заглушки вроде 0123456789ABCDEF и пустые отброшены там). Пусто - нормально:
	# у FM350 серийника нет вовсе, опознание тогда идёт по IMEI и пути, как раньше.
	printf '{"path":"%s","section":"%s","model":"%s","product":"%s","vidpid":"%s","serial":"%s","imei":"%s",' \
		"$_r_p" "$_r_s" \
		"$(uci5g_get "$_r_s" model)" \
		"$(_jq "@[@.path=\"$_r_p\"].product" | head -1)" \
		"$_r_vp" \
		"$(_jq "@[@.path=\"$_r_p\"].serial" | head -1)" \
		"$(uci5g_get "$_r_s" imei)"
	printf '"iface":"%s","proto":"%s","at_port":"%s","owner":"%s","active":%s,' \
		"$_r_if" \
		"$([ -n "$_r_if" ] && ucinet_get "$_r_if" proto)" \
		"$_r_at" "$(_owner "$_r_s")" \
		"$([ "$_r_p" = "$(active_path)" ] && echo true || echo false)"
	printf '"tty":%s,"wdm":%s,"net":%s}' \
		"$(_r_json_list "$_r_tty")" \
		"$(_r_json_list "$_r_wdm")" \
		"$(_r_json_list "$_r_net")"
}

_all_paths() { _jq '@[*].path'; }

case "$1" in
paths)
	_all_paths ;;
path)
	[ -n "$2" ] || { echo '{"error":"no path"}'; exit 2; }
	# Модема нет на шине - отвечаем пустым объектом, а не молчанием: вызывающий
	# должен различать «нет такого» и «скрипт не сработал».
	_all_paths | grep -qx "$2" || { echo '{}'; exit 0; }
	_record "$2"; echo ;;
port)
	[ -n "$2" ] || { echo '{"error":"no port"}'; exit 2; }
	for _p in $(_all_paths); do
		_t=$(_jq "@[@.path=\"$_p\"].tty[*]" | tr '\n' ' ')
		case " $_t " in
			*" $2 "*) _record "$_p"; echo; exit 0 ;;
		esac
	done
	echo '{}' ;;
active)
	_a=$(active_path)
	[ -n "$_a" ] || { echo '{}'; exit 0; }
	_all_paths | grep -qx "$_a" || { echo '{}'; exit 0; }
	_record "$_a"; echo ;;
''|all)
	_first=1
	printf '['
	for _p in $(_all_paths); do
		[ "$_first" = 1 ] || printf ','
		_first=0
		_record "$_p"
	done
	printf ']\n' ;;
*)
	echo '{"error":"usage: [all] | paths | path <usb> | port <tty> | active"}'
	exit 2 ;;
esac
exit 0
