#!/bin/sh
#
# Засев AT-портов для вкладок SMS / USSD / AT-команды.
#
# Эти вкладки читают ПОРТ ИЗ ОТДЕЛЬНОГО конфига (sms_tool_js: readport, sendport,
# atport), который обычно заполняет hotplug при появлении модема. Если модем был
# подключён ДО установки пакета, события не происходит: значения остаются
# пустыми, и вкладки встречают пользователя «выберите порт», хотя модем найден и
# метрики уже читаются.
#
# Здесь мы находим рабочий порт тем же путём, что и всё остальное (detect.sh -
# он сверяет принадлежность tty активному модему), и подставляем ТОЛЬКО в пустые
# опции: осознанный выбор пользователя не перетираем.
#
# Usage: ensureports.sh          -> заполнить пустые, вернуть JSON с итогом
#        ensureports.sh <порт>   -> использовать указанный порт

RES="/usr/share/5gmodem"
PORT="$1"

# ОТДЕЛЬНЫЙ ПОРТ ДЛЯ SMS, ЕСЛИ МОДЕМ ЕГО ДАЁТ.
#
# Вкладки SMS/USSD/AT и основной опрос метрик - независимые потоки, и когда они
# сидят на ОДНОМ tty, они мешают друг другу: sms_tool открывает порт на каждый
# вызов, и если в этот момент идёт опрос (а он идёт каждые несколько секунд с
# открытой страницы «Сеть»), чтение возвращает пустоту. Снаружи это выглядит как
# «список сообщений то загружается, то нет» - ровно та жалоба, ради которой это
# и написано. Замерено на Telit LM960A18: подряд 2 чтения из 5 пустые, с паузами
# 8 из 8 успешные.
#
# У большинства модемов AT-портов несколько (у Telit - три: ttyUSB9/10/11), и
# развести потоки ничего не стоит. Берём первый отвечающий порт, КРОМЕ занятого
# метриками; если другого нет - работаем как раньше, на общем.
pick_sms_port() {
	_at=$(uci -q get 5gmodem.@5gmodem[0].at_port)
	_path=$(uci -q get 5gmodem.@5gmodem[0].active_modem)
	[ -n "$_path" ] || return 1

	for _t in $("$RES/listmodems.sh" 2>/dev/null | jsonfilter -e "@[@.path=\"$_path\"].tty[*]" 2>/dev/null); do
		[ -e "$_t" ] || continue
		[ "$_t" = "$_at" ] && continue
		if "$RES/atprobe.sh" "$_t" >/dev/null 2>&1; then echo "$_t"; return 0; fi
	done
	return 1
}

[ -n "$PORT" ] || PORT=$(pick_sms_port)
[ -n "$PORT" ] || PORT=$("$RES/detect.sh" 2>/dev/null)

if [ -z "$PORT" ] || [ ! -e "$PORT" ]; then
	echo '{"ok":0,"reason":"no port"}'
	exit 0
fi

_ATP=$(uci -q get 5gmodem.@5gmodem[0].at_port)

CHANGED=0
for _opt in readport sendport ussdport atport; do
	_cur=$(uci -q get "sms_tool_js.@sms_tool_js[0].$_opt")
	# Перезаписываем в трёх случаях:
	#   - пусто (модем подключили до установки пакета);
	#   - порт УЖЕ НЕ СУЩЕСТВУЕТ: после переподключения номера tty сдвигаются, и
	#     старое значение указывает в пустоту - для пользователя это выглядит так
	#     же, как незаданный порт;
	#   - порт СОВПАДАЕТ с портом метрик, а мы нашли свободный: это и есть та
	#     самая конкуренция (см. pick_sms_port выше).
	if [ -z "$_cur" ] || [ ! -e "$_cur" ] || \
	   { [ -n "$_ATP" ] && [ "$_cur" = "$_ATP" ] && [ "$PORT" != "$_ATP" ]; }; then
		uci -q set "sms_tool_js.@sms_tool_js[0].$_opt=$PORT"
		CHANGED=1
	fi
done

[ "$CHANGED" = 1 ] && uci -q commit sms_tool_js

printf '{"ok":1,"port":"%s","changed":%s}\n' "$PORT" "$CHANGED"
