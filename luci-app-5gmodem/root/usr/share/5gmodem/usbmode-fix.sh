#!/bin/sh
#
# СНЯТИЕ ВРЕДНЫХ ПРАВИЛ usb_modeswitch.
#
# ЗАЧЕМ. В базе /etc/usb-mode.json встречаются записи вида
#   "413c:81d7": { "*": { "msg": [ ], "config": 0 } }
# то есть «перевести устройство в конфигурацию 0». Для модема, который и так
# приходит в рабочей композиции, это РАЗРУШИТЕЛЬНО: конфигурация 0 - это
# «не сконфигурировано», ядро снимает уже привязанные драйверы
# (в логе: «cdc_mbim wwan0: unregister»), а сам usbmode при этом держит
# интерфейс через usbfs («interface 1 claimed by usbfs while 'usbmode' sets
# config #0»), из-за чего cdc_mbim не может привязаться обратно.
#
# Итог у пользователя (Dell DW5821e / Foxconn T77W968, 413c:81d7 на Radxa
# ROCK 5T): cdc-wdm и wwan0 исчезают, остаются только AT-порты, mbim/qmi
# настроить не на чем - «модем застревает на установке соединения», autosetup
# отвечает «не удалось». Само по себе это не проходит: usbmode запускается на
# каждое hotplug-событие и ломает композицию снова.
#
# ЧТО ДЕЛАЕМ. Убираем запись целиком - для этих модемов переключать нечего,
# они и так стартуют в нужной композиции. Файл принадлежит пакету
# usb-modeswitch, поэтому: (1) правим только известные ID, (2) кладём рядом
# резервную копию, (3) действуем идемпотентно - повторный запуск ничего не
# меняет. При обновлении usb-modeswitch запись вернётся, поэтому скрипт
# вызывается и из postinst, и из hotplug при появлении такого модема.
#
# Usage: usbmode-fix.sh [vid:pid]   (без аргумента - проверить весь список)

JSON=/etc/usb-mode.json
RES=/usr/share/5gmodem

# Модемы, которым правило usb_modeswitch ВРЕДИТ. Только проверенное:
#   413c:81d7 - Dell DW5821e / Foxconn T77W968 (Snapdragon X20), отчёт 28.07:
#               config 0 сносит cdc_mbim, модем остаётся без канала данных.
#   413c:81e0 - тот же DW5821e-eSIM в другой композиции, отчёт 29.07: правило
#               ровно такое же, и пользователь чинил это, руками вырезая запись
#               из usb-mode.json.
# СПИСОК НУЖЕН ОТДЕЛЬНО ОТ ПРОВЕРКИ НИЖЕ: если правило уже сломало композицию,
# у модема не осталось ни tty, ни cdc-wdm, он не опознаётся как модем - и
# динамическая ветка его не увидит. То есть список вытаскивает из ямы, а
# проверка ниже не даёт в неё попасть.
BAD_IDS="413c:81d7 413c:81e0"

[ -f "$JSON" ] || exit 0

_fix_one() {   # $1 - vid:pid
	grep -q "\"$1\"" "$JSON" 2>/dev/null || return 1   # записи нет - нечего делать
	[ -f "$JSON.5gmodem-bak" ] || cp "$JSON" "$JSON.5gmodem-bak" 2>/dev/null
	sed -e "/\"$1\": {/,/},/d" "$JSON" > "$JSON.tmp" 2>/dev/null || { rm -f "$JSON.tmp"; return 1; }
	# Правку принимаем ТОЛЬКО если файл остался валидным JSON и не опустел:
	# сломанная база лишила бы modeswitch'а все остальные модемы.
	if [ -s "$JSON.tmp" ] && jsonfilter -i "$JSON.tmp" -e '@.devices' >/dev/null 2>&1; then
		mv "$JSON.tmp" "$JSON"
		logger -t 5gmodem "usb_modeswitch: removed a harmful rule for $1 (it was breaking the modem composition)"
		return 0
	fi
	rm -f "$JSON.tmp"
	return 1
}

# ПРАВИЛО ВРЕДНО ТОМУ, КОМУ ПЕРЕКЛЮЧАТЬ УЖЕ НЕЧЕГО.
#
# Записей с «config: 0» в базе три десятка (HP, Huawei, Dell), и для устройства,
# пришедшего ФЛЕШКОЙ, сброс конфигурации - штатный способ разбудить модемный
# режим. Поэтому снимаем правило не по факту «config 0», а только у тех, кто
# УЖЕ отдал модемные интерфейсы: если у устройства есть tty или cdc-wdm, оно в
# рабочей композиции, переключать его не нужно, а сброс конфигурации отнимет
# драйвер данных. Модем в режиме накопителя в listmodems не попадает - его
# правило остаётся нетронутым.
_scan_present() {
	command -v jsonfilter >/dev/null 2>&1 || return 0
	[ -x "$RES/listmodems.sh" ] || return 0
	for _pid in $("$RES/listmodems.sh" 2>/dev/null \
		| jsonfilter -e '@[*].vidpid' 2>/dev/null | sort -u); do
		case "$_pid" in
			[0-9a-f]*:[0-9a-f]*) : ;;
			*) continue ;;
		esac
		# Именно «config: 0» и пустой msg - правило ничего не пересылает
		# устройству, только сбрасывает конфигурацию.
		[ "$(jsonfilter -i "$JSON" -e "@.devices[\"$_pid\"][\"*\"].config" 2>/dev/null)" = "0" ] \
			|| continue
		_fix_one "$_pid" && { _changed=1; _reprobe "$_pid"; }
	done
}

# ПОДНЯТЬ УЖЕ СЛОМАННЫЙ МОДЕМ, А НЕ ТОЛЬКО УБРАТЬ ГРАБЛИ.
#
# Снять правило мало: устройство, которому usbmode УЖЕ выставил config 0,
# так и остаётся без драйвера данных - ядро сняло cdc_mbim и обратно его не
# привязывает. Живой отчёт 26.08.2026 (Cudy TR3000, DW5821e 413c:81e0):
#   06:45:55  cdc_mbim wwan0: register        - композиция рабочая
#   06:46:15  usbmode sets config #0          - драйвер снят
#   06:46:20  наше правило снято              - но модем уже лежит
# и дальше девять минут ни cdc-wdm, ни wwan0: человеку оставалось выдернуть
# модем руками. Перезапись bConfigurationValue заставляет ядро сконфигурировать
# устройство заново и заново раздать драйверы - то же, что физическое
# переподключение, только без рук.
#
# ТОЛЬКО ПО ФАКТУ ПОЛОМКИ. Трогаем устройство, лишь когда у него НЕТ ни
# cdc-wdm, ни сетевого интерфейса: у здорового модема пересборка конфигурации
# оборвала бы соединение на ровном месте.
_reprobe() {   # $1 - vid:pid
	_rp_v=${1%%:*}; _rp_p=${1##*:}
	for _rp_d in /sys/bus/usb/devices/*; do
		[ -f "$_rp_d/idVendor" ] || continue
		[ "$(cat "$_rp_d/idVendor" 2>/dev/null)" = "$_rp_v" ] || continue
		[ "$(cat "$_rp_d/idProduct" 2>/dev/null)" = "$_rp_p" ] || continue
		# Канал данных на месте - значит ломать нечего. Перебираем маски
		# НАПРЯМУЮ: `set --` затирает позиционные параметры, и $1 (vid:pid)
		# после него превращался в путь - в журнал уходил мусор вместо ID.
		_rp_mem="/tmp/5gmodem_lastcfg_$(echo "$1" | tr -d ':')"
		for _rp_x in "$_rp_d"/*/net/* "$_rp_d"/*/usbmisc/cdc-wdm* "$_rp_d"/*/cdc-wdm*; do
			# ЗАПОМИНАЕМ РАБОЧУЮ КОНФИГУРАЦИЮ, пока модем здоров. Восстанавливать
			# «последнюю по номеру» неверно в общем случае: у DW5821e рабочая
			# действительно последняя (2 из 2), а у Compal RXM-G1 их всего одна,
			# и у трёхконфигурационных модулей рабочая бывает средней. Помнить
			# точное значение надёжнее любой догадки.
			[ -e "$_rp_x" ] && { cat "$_rp_d/bConfigurationValue" > "$_rp_mem" 2>/dev/null; return 0; }
		done
		_rp_cfg=$(cat "$_rp_d/bConfigurationValue" 2>/dev/null | tr -cd '0-9')
		# НЕСКОНФИГУРИРОВАННОЕ УСТРОЙСТВО ЛЕЧИМ БЕЗУСЛОВНО.
		#
		# Ровно это делает usbmode: после «config 0» ядро снимает конфигурацию,
		# и в sysfs у устройства НЕ ОСТАЁТСЯ КАТАЛОГОВ ИНТЕРФЕЙСОВ ВООБЩЕ.
		# Проверка «а есть ли у него MBIM-интерфейс» здесь не проходит никогда -
		# смотреть просто не на что, и первая редакция этой функции молча
		# отказывалась чинить именно тот случай, ради которого написана
		# (поймано на живом стенде 26.08.2026: конфигурация пуста, канала нет,
		# фикс не сработал). Пустое значение и есть признак поломки.
		if [ -z "$_rp_cfg" ] || [ "$_rp_cfg" = 0 ]; then
			:
		else
			# Устройство сконфигурировано, но канала данных нет. Тут проверка
			# уместна: у модема-«только AT» его не бывает по устройству, и
			# пересобирать ему конфигурацию незачем. Признак - интерфейс класса
			# 02 подкласса 0e (CDC MBIM) или вендорский ff: именно на них
			# садятся cdc_mbim и qmi_wwan.
			_rp_has=0
			for _rp_i in "$_rp_d"/*:*/bInterfaceClass; do
				[ -f "$_rp_i" ] || continue
				case "$(cat "$_rp_i" 2>/dev/null)" in
					02) [ "$(cat "${_rp_i%Class}SubClass" 2>/dev/null)" = "0e" ] && _rp_has=1 ;;
					ff) _rp_has=1 ;;
				esac
			done
			[ "$_rp_has" = 1 ] || return 0
		fi
		# НЕ ЧАЩЕ РАЗА В 5 МИНУТ. hotplug дёргается на каждое событие шины, а
		# пересборка конфигурации - операция заметная: без ограничителя мы бы
		# устроили модему карусель.
		_rp_st="/tmp/5gmodem_reprobe_$(echo "$1" | tr -d ':')"
		if [ -f "$_rp_st" ] && [ -z "$(find "$_rp_st" -mmin +5 2>/dev/null)" ]; then
			return 0
		fi
		: > "$_rp_st" 2>/dev/null
		_rp_cur="$_rp_cfg"
		_rp_num=$(cat "$_rp_d/bNumConfigurations" 2>/dev/null)
		case "$_rp_num" in ''|*[!0-9]*) return 0 ;; esac
		# config 0 = «не сконфигурировано»: берём последнюю доступную,
		# у этих модемов именно в ней живут MBIM и AT-порты.
		# config 0 = «не сконфигурировано»: берём запомненную рабочую, а если
		# её нет (первый запуск после перезагрузки) - последнюю доступную.
		_rp_last=$(cat "$_rp_mem" 2>/dev/null | tr -cd '0-9')
		case "$_rp_cur" in
			''|0) _rp_set="${_rp_last:-$_rp_num}" ;;
			*)    _rp_set="$_rp_cur" ;;
		esac
		case "$_rp_set" in ''|0|*[!0-9]*) _rp_set="$_rp_num" ;; esac
		echo "$_rp_set" > "$_rp_d/bConfigurationValue" 2>/dev/null \
			&& logger -t 5gmodem "usb_modeswitch: $1 was left without a data channel - re-applied USB configuration $_rp_set to make the kernel bind drivers again"
		return 0
	done
}

_changed=0
for _id in ${1:-$BAD_IDS}; do
	_fix_one "$_id" && _changed=1
done
# Аргументом задан конкретный ID - значит вызвали точечно, сканировать не надо.
[ -n "$1" ] || _scan_present

# ЛЕЧЕНИЕ ОТВЯЗАНО ОТ СНЯТИЯ ПРАВИЛА.
#
# Сначала _reprobe звался только когда правило снято ПРЯМО СЕЙЧАС - и до
# пострадавших не доходил вовсе: у них правило снято прошлым запуском, файл
# уже чист, снимать нечего, а модем всё так же лежит без канала данных.
# Ровно этот случай в отчёте 26.08.2026: правило убрано в 06:46:20, а в 06:55
# по-прежнему ни cdc-wdm, ни wwan0. Обновление приложения человеку бы не
# помогло - он бы снова дёргал модем руками. Теперь проверяем состояние
# независимо: правило это или его последствия, лечим по факту поломки.
for _id in ${1:-$BAD_IDS}; do
	_reprobe "$_id"
done
exit 0
