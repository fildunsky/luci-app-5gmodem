# Общие помощники. Подключается через "." (не запускается).
#
# ЗАЧЕМ. Две операции повторялись по всему коду и уже начали расходиться:
#
# 1) Имя секции модема из USB-пути - 22 копии в 12 файлах.
# 2) Поиск секции по имени интерфейса - ДЕВЯТЬ вариантов одной регулярки,
#    отличавшихся тремя способами сразу:
#      m_[^.]*        против  m_[A-Za-z0-9_]*
#      '\?$1'\?       против  '$1'        (терпит вывод uci без кавычек или нет)
#      с head -1      против  без
#    Расхождение не косметическое: строгие варианты не находят секцию там, где
#    находят мягкие, и поведение зависит от того, какой файл спросил.
#
# Держим по одной реализации: расходиться станет нечему.

# --- SERIAL ИЗ SYSFS: ТРЕТИЙ ПРИЗНАК ЛИЧНОСТИ МОДЕМА -------------------------
#
# ЗАЧЕМ. Личность модема мы храним по IMEI, а IMEI надо ПРОЧИТАТЬ - командой в
# AT-порт. Пока он не прочитан (или прочитан не из того порта), два одинаковых
# модема неразличимы, и именно там случались подмены: у пользователя с двумя
# Thales MV31-W (05c6:90d5) оба профиля показывали один номер. Serial доступен
# СРАЗУ, из sysfs, без AT-порта, без очереди к нему и независимо от того,
# отвечает ли модем вообще - то есть отвечает на вопрос «тот же это аппарат?»
# в тот самый момент, когда все остальные способы ещё молчат.
#
# НО КЛЮЧОМ ОН БЫТЬ НЕ МОЖЕТ. Замер по реальному железу (стенд + собранные
# диагностики пользователей):
#
#   05c6:90d5  d383e5d6 / 1afc7c2d   два MV31-W различимы
#   05c6:9025  c7f2a76c / 72f642f6   два T99W175 различимы
#   05c6:90d6  2e6172c9              уникален
#   05c6:9063  81e6896d              уникален
#   0489:e0b5  0123456789ABCDEF      ЗАГЛУШКА на всю партию
#   413c:81d7  0123456789ABCDEF      ЗАГЛУШКА
#   0e8d:7127  (пусто)               НЕТ ВООБЩЕ (FM350, проверено на стенде)
#
# То есть serial уникален ровно там, где живёт проблема «два одинаковых модема»,
# но у части железа его нет или он одинаков у всей партии. Заглушка ХУЖЕ
# отсутствия: по ней два разных модема слились бы в один. Поэтому - фильтр.
#
# serial_valid <строка> - годится ли как признак личности
serial_valid() {
	_sv="$1"
	[ -n "$_sv" ] || return 1
	case "$_sv" in
		-|0|none|None|N/A) return 1 ;;
		# Заводские заглушки, встреченные живьём.
		0123456789ABCDEF|0123456789abcdef) return 1 ;;
		*[!A-Za-z0-9._:-]*) return 1 ;;
	esac
	# Слишком короткий - не идентификатор.
	[ "${#_sv}" -ge 6 ] || return 1
	# Один символ, повторённый целиком (000000, FFFFFFFF): тоже заглушка.
	_sv1=$(printf '%s' "$_sv" | cut -c1)
	case "$_sv" in
		*[!"$_sv1"]*) ;;
		*) return 1 ;;
	esac
	return 0
}

# ПАРТИЙНЫЕ SERIAL - ЗАПОМИНАЕМ НАВСЕГДА, А НЕ ТОЛЬКО В МОМЕНТ ВСТРЕЧИ.
#
# Проверка «serial не должен встречаться на шине дважды» мгновенна, и в этом её
# дыра: два аппарата редко видны одновременно. Один воткнут раньше другого, один
# переэнумерируется, у одного шторм сбросов - и в эту секунду партийный номер
# выглядит уникальным. Живой случай 01.08.2026: два Compal (VOS_5G и SG500M2-X,
# IMEI 016133312319966 и 016133311799572) оба отдают serial 2e6172c9. Пока сосед
# отваливался, номер записался в секцию, а дальше sec_by_serial посчитал их ОДНИМ
# аппаратом и migrate_profile перенёс чужой профиль вместе с IMEI и интерфейсом.
#
# Поэтому: увидели номер у двух устройств хоть раз - он партийный ВСЕГДА. Список
# живёт в конфиге (переживает перезагрузку), формат - через пробел.
stub_serial_known() {   # $1 - serial
	[ -n "$1" ] || return 1
	case " $(uci -q get "5gmodem.@5gmodem[0].stub_serials" 2>/dev/null) " in
		*" $1 "*) return 0 ;;
	esac
	return 1
}

stub_serial_add() {   # $1 - serial
	[ -n "$1" ] || return 0
	stub_serial_known "$1" && return 0
	_ssa_l=$(uci -q get "5gmodem.@5gmodem[0].stub_serials" 2>/dev/null)
	uci -q set "5gmodem.@5gmodem[0].stub_serials=${_ssa_l:+$_ssa_l }$1"
	# ВЫЧИЩАЕМ УЖЕ ПОСТАВЛЕННЫЕ ШТАМПЫ. Номер мог разойтись по секциям ДО того,
	# как мы поняли, что он партийный (соседа не было на шине). Оставить его -
	# значит оставить заряженным sec_by_serial: на следующем круге он снова
	# признает два аппарата одним и перенесёт чужой профиль.
	uci -q show 5gmodem 2>/dev/null | grep -F ".serial='$1'" \
		| sed -n "s/^5gmodem\.\(m_[^.]*\)\.serial=.*/\1/p" \
		| while read -r _ssa_s; do
			[ -n "$_ssa_s" ] && uci -q delete "5gmodem.$_ssa_s.serial"
		done
	uci -q commit 5gmodem
	logger -t 5gmodem "serial $1 is a batch value (seen on two devices) - no longer used as a modem identity"
	return 0
}

# serial_of <путь к usb-устройству в sysfs> -> годный serial или пусто
#
# ВТОРАЯ ПРОВЕРКА - РАНТАЙМОВАЯ, И ОНА ВАЖНЕЕ СПИСКА ЗАГЛУШЕК: если тот же serial
# СЕЙЧАС рапортуют два устройства на шине, он партийный, каким бы правдоподобным
# ни выглядел. Так мы ловим заглушки, которых нет в списке выше, не заводя
# картотеку вендоров. Результат ЗАПОМИНАЕМ (stub_serial_add): в следующий раз
# сосед может быть не виден, а номер от этого уникальным не станет.
serial_of() {
	_so_s=$(cat "$1/serial" 2>/dev/null | tr -d '\r\n')
	serial_valid "$_so_s" || { printf ''; return 1; }
	stub_serial_known "$_so_s" && { printf ''; return 1; }
	_so_n=0
	for _so_d in /sys/bus/usb/devices/*; do
		[ -f "$_so_d/serial" ] || continue
		[ "$(cat "$_so_d/serial" 2>/dev/null | tr -d '\r\n')" = "$_so_s" ] && _so_n=$((_so_n + 1))
	done
	[ "$_so_n" = 1 ] || { stub_serial_add "$_so_s"; printf ''; return 1; }
	printf '%s' "$_so_s"
}

# КЭШИ, ПРИВЯЗАННЫЕ К USB-ПУТИ, ПЕРЕЖИВАЮТ СМЕНУ МОДЕМА В ПОРТУ.
#
# Мы кэшируем по пути почти всё: снимок метрик, статику AT (IMEI, модель,
# ICCID), SIM-слоты, диапазоны, QMI-дополнения. Ключ - физический разъём, а он
# при замене модема тот же. Итог: в новый модем приезжает чужое. Живой случай
# 01.08.2026: в порт вместо eSIM-модема воткнули SIM7100E, и карточка показывала
# у него ДВЕ симки и eSIM - из файла `/tmp/5gmodem_slots_1-1.3`, оставшегося от
# предшественника (свежий опрос честно отвечал «слотов нет»). Тем же путём
# приходили чужие диапазоны, пока кэш bands не сбросишь руками.
#
# Чистим ВСЁ по этому пути разом - на смене модема (swap_cleanup) и на смене
# композиции (номера портов там другие, а часть кэшей ключуется портом).
purge_path_caches() {   # $1 - usb-путь
	[ -n "$1" ] || return 0
	# ДВА ФОРМАТА КЛЮЧА, И ОБА ЖИВЫЕ. snap_key даёт "1_1_3_" (с хвостовым
	# подчёркиванием - см. пояснение над ним), а кэш статики ключуется от
	# tty_usbpath и даёт "1_1_3". Чистить надо оба, иначе IMEI и ICCID прежнего
	# модема остаются лежать: файл `5gmodem_static_1_1_3.imsi` под первый glob
	# не попадает.
	_ppc_k=$(snap_key "$1" 2>/dev/null)
	_ppc_k2=$(printf '%s' "$1" | tr -c 'A-Za-z0-9' '_')
	rm -f "/tmp/5gmodem_slots_$1" "/tmp/5gmodem_slots_$1.t" \
	      "/tmp/5gmodem_bands_$1" "/tmp/5gmodem_bands_$1.t" "/tmp/5gmodem_bands_$1.p" \
	      "/tmp/5gmodem_qmirecover_$(printf '%s' "$1" | tr -c 'A-Za-z0-9' _)" \
	      "/tmp/5gmodem_autoapn_m_$(printf '%s' "$1" | tr -c 'A-Za-z0-9' _)"* \
	      "/tmp/5gmodem_portok_$(snap_key "$1" 2>/dev/null)" 2>/dev/null
	[ -n "$_ppc_k" ] && rm -f \
		"/tmp/5gmodem_metrics_$_ppc_k.json" "/tmp/5gmodem_metrics_$_ppc_k.stamp" \
		"/tmp/5gmodem_slot_$_ppc_k" "/tmp/5gmodem_slot_$_ppc_k.t" \
		"/tmp/5gmodem_imei_none_$_ppc_k" \
		"/tmp/5gmodem_static_$_ppc_k"* "/tmp/5gmodem_qmi_$_ppc_k".* 2>/dev/null
	[ -n "$_ppc_k2" ] && rm -f \
		"/tmp/5gmodem_metrics_$_ppc_k2.json" "/tmp/5gmodem_metrics_$_ppc_k2.stamp" \
		"/tmp/5gmodem_slot_$_ppc_k2" "/tmp/5gmodem_slot_$_ppc_k2.t" \
		"/tmp/5gmodem_imei_none_$_ppc_k2" \
		"/tmp/5gmodem_static_$_ppc_k2"* "/tmp/5gmodem_qmi_$_ppc_k2".* 2>/dev/null
	logger -t 5gmodem "caches for path $1 purged (a different modem is in the port)"
	return 0
}

# ПОЧИНКА КОДИРОВКИ ТЕКСТА ИЗ МОДЕМА.
#
# sms_tool отдаёт неразрывный пробел и кавычки-ёлочки (U+00A0, U+00AB, U+00BB)
# ОДНИМ байтом, по-latin1, вместо двухбайтовой последовательности UTF-8. Для
# Telegram это фатально - он отвергает ВЕСЬ запрос ("strings must be encoded in
# UTF-8"), а страница «Входящие» рисует на их месте ромбы с вопросом.
#
# Чиним ровно такие байты: всё, что не складывается в корректную
# последовательность UTF-8, считаем latin1 и перекодируем. Валидные
# последовательности (кириллица, стрелки, эмодзи) не трогаем - функция
# идемпотентна, второй проход ничего не меняет.
#
# iconv в OpenWrt по умолчанию нет, поэтому awk побайтно: busybox awk работает
# с байтами, что здесь и нужно.
utf8_fix() {
	awk '
		BEGIN { for (n = 1; n < 256; n++) o[sprintf("%c", n)] = n
			MK = sprintf("%c%cffff", 195, 191)     # маркер мусора: ÿ + "ffff"
			MKJ = sprintf("%cu00ffffff", 92) }     # он же в JSON-экранировке: ÿ + "ffff"
		function cont(str, i,   b) { b = o[substr(str, i, 1)]; return (b >= 128 && b < 192) }
		function hx(s,   i, c, v, d) {
			v = 0
			for (i = 1; i <= length(s); i++) {
				d = index("0123456789abcdef", tolower(substr(s, i, 1))) - 1
				if (d < 0) return -1
				v = v * 16 + d
			}
			return v
		}
		{
			out = ""; i = 1; n = length($0)
			while (i <= n) {
				b = o[substr($0, i, 1)]
				if (b < 128)                       { out = out substr($0, i, 1); i += 1 }
				else if (b >= 194 && b <= 223 && i + 1 <= n && cont($0, i + 1)) { out = out substr($0, i, 2); i += 2 }
				else if (b >= 224 && b <= 239 && i + 2 <= n && cont($0, i + 1) && cont($0, i + 2)) { out = out substr($0, i, 3); i += 3 }
				else if (b >= 240 && b <= 244 && i + 3 <= n && cont($0, i + 1) && cont($0, i + 2) && cont($0, i + 3)) { out = out substr($0, i, 4); i += 4 }
				else { out = out sprintf("%c%c", 192 + int(b / 64), 128 + (b % 64)); i += 1 }
			}
			# ВТОРОЙ МУСОР sms_tool (версии 2025.08.x): неразрывный пробел и
			# ёлочки (U+00A0/AB/BB и подобные latin1) приходят как "ÿffffHH" -
			# ÿ (U+00FF) + буквальное "ffff" + hex-код latin1-байта. Проход выше
			# это НЕ ловит (там валидный UTF-8 ÿ и ASCII "ffff..."). Возвращаем
			# правильный символ U+00HH (двухбайтный UTF-8). index() побайтный.
			st = 1; p = index(substr(out, st), MK)
			while (p > 0) {
				ap = st + p - 1
				code = hx(substr(out, ap + 6, 2))
				if (code >= 128 && code <= 255) {
					out = substr(out, 1, ap - 1) sprintf("%c%c", 192 + int(code / 64), 128 + (code % 64)) substr(out, ap + 8)
					st = 1
				} else {
					st = ap + 6
				}
				p = index(substr(out, st), MK)
			}
			# ТОТ ЖЕ МУСОР, НО В JSON-ВЫВОДЕ sms_tool -j. Там ÿ экранирован как
			# "ÿ", то есть маркер выглядит как "ÿffffHH" (ASCII), и проход
			# выше по байтам его не ловит - именно поэтому recv отдавал битьё, а
			# newdump чинил уже ПОСЛЕ декода jsonfilter. Возвращаем правильный символ
			# тем же JSON-escape "\u00HH" - вывод остаётся валидным JSON.
			st = 1; p = index(substr(out, st), MKJ)
			while (p > 0) {
				ap = st + p - 1
				code = hx(substr(out, ap + 10, 2))
				if (code >= 128 && code <= 255) {
					out = substr(out, 1, ap - 1) sprintf("%cu00%02x", 92, code) substr(out, ap + 12)
					st = 1
				} else {
					st = ap + 10
				}
				p = index(substr(out, st), MKJ)
			}
			print out
		}
	'
}

# ЧУЖИЕ НЕЗАКОММИЧЕННЫЕ ПРАВКИ UCI - ЗАПИСАТЬ В ЖУРНАЛ ДО НАШЕГО КОММИТА.
#
# ЗАЧЕМ. Дельты uci лежат в ОБЩЕМ /tmp/.uci до коммита, и `uci commit network`
# коммитит ВСЁ скопом - и своё, и чужое. Кнопка «Сохранить» (без «Применить») в
# LuCI, скрипт, умерший между set и commit, ручной uci set в консоли - всё это
# оставляет мину, которую взводит первый же чужой коммит. Наш код коммитит
# network из netpri (переключение приоритета) и mkiface - то есть детонатором
# можем оказаться мы, а взрыв (например, смена lan.ipaddr) выглядит как наш баг.
# Живой случай 30.07: wwGate, «пинга до роутера нет, инет есть» - точный симптом
# слетевшего lan-адреса; кто его менял - улик не осталось.
#
# Отменять чужое нельзя (это может быть настоящая незасейвленная работа
# пользователя) - но МОЛЧА закоммитить тоже нельзя. Пишем в журнал, ЧТО именно
# ждало в очереди: если после нашего коммита что-то сломается, в логе будет
# видно, чья это правка была.
# note_foreign_uci <конфиг> <метка вызывающего>
note_foreign_uci() {
	_nf=$(uci changes "$1" 2>/dev/null | head -20)
	[ -n "$_nf" ] || return 0
	logger -t 5gmodem "$2: FOREIGN staged uci changes in $1 - committing them along: $(printf '%s' "$_nf" | tr '\n' '; ' | head -c 400)"
}

# КЛЮЧ ФАЙЛОВ-СНИМКОВ МЕТРИК по USB-пути.
#
# Формула повторена буква в букву из 5gmodem.sh, включая `printf '%s\n'`: перевод
# строки тоже попадает под `tr` и даёт ЗАВЕРШАЮЩЕЕ подчёркивание, поэтому файлы
# зовутся `5gmodem_metrics_1_1_3_.json`, а не `..._1_1_3.json`. Я на этом уже
# ошибся: написал ключ «как логично» и подогрев искал несуществующий файл, считая
# снимок отсутствующим всегда. Держим одну реализацию - расходиться станет нечему.
# Менять формат НЕЛЬЗЯ: по нему названы уже лежащие снимки.
snap_key() {   # $1 - usb-путь
	_sk=$(printf '%s\n' "$1" | tr -c 'A-Za-z0-9' '_')
	[ -n "$_sk" ] || _sk="none"
	printf '%s' "$_sk"
}

# Секунды аптайма БЕЗ подпроцесса. Раньше повсюду звался `cut -d. -f1
# /proc/uptime` - по замеру это 21 спавн на ОДИН опрос метрик (циклы, штампы
# кэшей). read из /proc + подстановка делают то же ядерными средствами.
uptime_s() {
	read -r _us _ < /proc/uptime
	printf '%s\n' "${_us%%.*}"
}

# secname <usb-путь> -> имя секции (m_1_1_3)
# Секции uci допускают только [A-Za-z0-9_], а в пути есть точки и дефисы.
# МЕМО НА ПОСЛЕДНИЙ ОТВЕТ: за один опрос метрик secname спрашивают ~10 раз и
# почти всегда ПРО ОДИН И ТОТ ЖЕ путь (_POLL_AM) - это 10 спавнов sed за то,
# что уже посчитано. Кэш из одной пары «вход-выход» снимает их все.
# БЕЗ sed. Путь короткий (1-1.3, 2-1.4 - до десятка символов), поэтому замена
# посимвольно средствами оболочки делает ту же работу без спавна: 4 мс на вызов на
# стенде против 0. Мемо ниже снимает повторы, но у реестра и перечисления пути
# каждый раз РАЗНЫЕ, там мемо не спасало.
_SN_IN=""; _SN_OUT=""
secname() {
	if [ -n "$1" ] && [ "$1" = "$_SN_IN" ]; then
		printf '%s\n' "$_SN_OUT"
		return
	fi
	_SN_IN="$1"
	_sn_rest="$1"; _sn_acc=""
	while [ -n "$_sn_rest" ]; do
		_sn_tail="${_sn_rest#?}"
		_sn_ch="${_sn_rest%"$_sn_tail"}"
		case "$_sn_ch" in
			[A-Za-z0-9]) _sn_acc="$_sn_acc$_sn_ch" ;;
			*) _sn_acc="${_sn_acc}_" ;;
		esac
		_sn_rest="$_sn_tail"
	done
	_SN_OUT="m_$_sn_acc"
	printf '%s\n' "$_SN_OUT"
}

# СНИМОК КОНФИГА ДЛЯ ЧИТАЮЩИХ ЦИКЛОВ.
#
# ЗАЧЕМ. `uci show 5gmodem` - это отдельный процесс, и по нему работает
# sec_for_iface, которую в цикле по интерфейсам зовут по цепочке is_modem ->
# iface_type -> modem_path_for -> model_for. Замер netpri.sh list на стенде:
# 690 мс на вызов и ~145 подпроцессов, из них 70 - uci. А зовётся он КАЖДЫЕ 5 c,
# пока открыта страница метрик, то есть роутер тратит на список аплинков больше
# полусекунды из каждых пяти.
#
# ПРАВИЛО: снимок берёт только тот, кто ТОЛЬКО ЧИТАЕТ и живёт недолго (netpri
# list). Писателям он не нужен и опасен: после `uci set` снимок устареет молча.
# Поэтому это не автоматический кэш, а явное включение - и явный сброс.
_UCI_NL='
'
# ЦЕНА ЧТЕНИЯ ИЗ СНИМКА - ИЗМЕРЕНА, И ОНА НЕ НУЛЕВАЯ (стенд, 25.12.5, aarch64):
#
#   `uci -q get <ключ>`                          2.8-3.0 мс
#   вырезание из ПОЛНОГО дампа (${x#*"pat"})     4.8 мс
#   то же через ${x##*"pat"}                     2.8 мс
#   проверка наличия одним `case`                0.2 мс
#   вырезание из снимка ОДНОЙ СЕКЦИИ (289 байт)  0.8 мс
#
# Причина: busybox разворачивает `${x#*шаблон}` перебором префиксов, то есть цена
# растёт с ДЛИНОЙ строки, а полный дамп - это три килобайта. На точечных чтениях
# полный снимок не выигрывает у обычного `uci get` вовсе (и в первой редакции
# health.sh замедлил его на 30 мс из 50).
#
# ПРАВИЛО, переписанное по замеру:
#   - полный снимок берут только те, кто заменяет им ПАЙПЛАЙНЫ (`uci show | sed |
#     head`, как netpri/sec_for_iface): там экономятся процессы, а не сравнения;
#   - для десятка чтений ОДНОЙ секции есть uci5g_sec_snapshot (см. ниже);
#   - для трёх-четырёх разрозненных ключей правильный ответ - обычный `uci get`.

# ЧТЕНИЕ ЗНАЧЕНИЯ ИЗ СНИМКА - БЕЗ ЕДИНОГО ПОДПРОЦЕССА.
#
# Подстановки ${x#...} и ${x%...} - это встроенные операции оболочки, то есть
# поиск идёт в C и не стоит ни fork, ни exec. Именно этим снимок и полезен: иначе
# он экономил бы один `uci show`, но каждое чтение всё равно спавнило бы `uci get`
# или `sed`.
#
# РАЗДЕЛИТЕЛЬ - ПЕРЕВОД СТРОКИ, и это не деталь: `uci show` печатает по одной
# опции на строку, поэтому ЗНАЧЕНИЕ содержать перевод строки не может, и
# сопоставление не может ошибиться на данных пользователя. Любой другой
# разделитель (пробел, вертикальная черта) в значении встретиться мог бы.
#
# eval здесь НЕ используется намеренно: превращать конфиг в переменные оболочки
# (`eval $(uci show ... | sed ...)`) - это исполнение пользовательских данных,
# ровно тот приём, который в аудите помечен к удалению из listmodems.sh.
# ВЫРЕЗАЕМ ЧЕРЕЗ ##, А НЕ #. Ключ в дампе uci уникален (строка «конфиг.секция.опция=»
# встречается ровно раз), поэтому «самый длинный префикс» даёт то же значение, что
# и «самый короткий», - но busybox доходит до него вдвое быстрее: 2.8 мс против
# 4.8 мс на трёхкилобайтном дампе (замер на стенде).
_uci_snap_get() {   # $1 - снимок (с ведущим переводом строки), $2 - полный ключ
	case "$1" in
		*"$_UCI_NL$2="*)
			# ПЕРВОЕ вхождение (#), не последнее (##): ключ в uci show уникален,
			# а жадный поиск сканирует дамп до конца на КАЖДОЙ выборке - на
			# 5-КБ конфиге это ~5 мс против ~2 мс (замер 06.08.2026, netpri list
			# делал ~120 выборок за вызов).
			_usv="${1#*"$_UCI_NL$2="}"
			_usv="${_usv%%"$_UCI_NL"*}"
			# uci show заключает значение в одиночные кавычки
			_usv="${_usv#\'}"
			printf '%s' "${_usv%\'}" ;;
	esac
}

_UCI5G_SNAP=""
uci5g_snapshot() { _UCI5G_SNAP="$_UCI_NL$(uci -q show 5gmodem 2>/dev/null)"; }
_uci5g_dump() {
	[ -n "$_UCI5G_SNAP" ] && { printf '%s\n' "$_UCI5G_SNAP"; return; }
	uci -q show 5gmodem 2>/dev/null
}
# uci5g_get <секция> <опция> - значение из снимка, иначе обычным uci.
uci5g_get() {
	if [ -n "$_UCI5G_SNAP" ]; then
		_uci_snap_get "$_UCI5G_SNAP" "5gmodem.$1.$2"
		return
	fi
	uci -q get "5gmodem.$1.$2" 2>/dev/null
}

# СНИМОК ОДНОЙ СЕКЦИИ - для тех, кто читает десяток ключей ИЗ НЕЁ ОДНОЙ
# (health.sh: одиннадцать настроек health.*). Строка короткая, поэтому вырезание
# стоит 0.8 мс против 3 мс у `uci get`, а спавн ровно один на всё.
# Читатель обязан быть только читателем: после своего же `uci set` снимок врёт.
uci_sec_snap() {   # $1 - конфиг, $2 - секция; печатает снимок для uci_sec_val
	printf '%s%s' "$_UCI_NL" "$(uci -q show "$1.$2" 2>/dev/null)"
}
uci_sec_val() {   # $1 - снимок, $2 - конфиг.секция, $3 - опция
	_usv_p="$_UCI_NL$2.$3="
	case "$1" in
		*"$_usv_p"*)
			_usv_v="${1##*"$_usv_p"}"
			_usv_v="${_usv_v%%"$_UCI_NL"*}"
			_usv_v="${_usv_v#\'}"
			printf '%s' "${_usv_v%\'}" ;;
	esac
}

_USEC_SEC=""; _USEC_SNAP=""
uci5g_sec_snapshot() {   # $1 - секция (health, m_1_1_3, @5gmodem[0])
	_USEC_SEC="$1"
	_USEC_SNAP=$(uci_sec_snap 5gmodem "$1")
}
uci5g_sec_get() {   # $1 - опция
	uci_sec_val "$_USEC_SNAP" "5gmodem.$_USEC_SEC" "$1"
}

_UCINET_SNAP=""
ucinet_snapshot() { _UCINET_SNAP="$_UCI_NL$(uci -q show network 2>/dev/null)"; }
# ucinet_get <интерфейс> <опция> - значение из снимка, иначе обычным uci.
ucinet_get() {
	if [ -n "$_UCINET_SNAP" ]; then
		_uci_snap_get "$_UCINET_SNAP" "network.$1.$2"
		return
	fi
	uci -q get "network.$1.$2" 2>/dev/null
}
# Существует ли секция интерфейса (замена `uci -q get network.$1 >/dev/null`).
ucinet_has() {
	if [ -n "$_UCINET_SNAP" ]; then
		case "$_UCINET_SNAP" in
			*"$_UCI_NL"network."$1"=*) return 0 ;;
			*) return 1 ;;
		esac
	fi
	uci -q get "network.$1" >/dev/null 2>&1
}

# sec_for_iface <имя интерфейса> -> имя секции модема, который им владеет
# Кавычки вокруг значения НЕОБЯЗАТЕЛЬНЫ: разные версии uci выводят по-разному,
# и строгий вариант молча не находил секцию.
sec_for_iface() {
	[ -n "$1" ] || return 1
	_uci5g_dump \
		| sed -n "s/^5gmodem\.\(m_[^.]*\)\.network='\?$1'\?\$/\1/p" \
		| head -1
}

# ВЛАДЕНИЕ ИНТЕРФЕЙСОМ - ПО ЖЕЛЕЗУ (IMEI), А НЕ ПО ПОРТУ.
#
# Штамп network.<if>.modem_path (usb-путь) НЕ различал два РАЗНЫХ модема в одном
# разъёме: путь у них один, и при подмене интерфейс прежнего сносился - у
# пользователя с двумя модемами по очереди в одном порту (issue #2) переподключение
# каждый раз шло через пересоздание. IMEI - настоящая личность железа, он и есть
# первичный ключ владения. modem_path продолжаем писать: он нужен для диагностики
# и как запасной признак для старых конфигов и модемов без читаемого IMEI.

# IMEI из секции модема по usb-пути (пусто, если неизвестен).
imei_for_path() {   # $1 - usb-путь
	[ -n "$1" ] || return 1
	uci -q get "5gmodem.$(secname "$1").imei"
}

# Интерфейс, принадлежащий модему с таким IMEI (пусто - такого нет).
iface_for_imei() {   # $1 - imei
	[ -n "$1" ] || return 1
	uci -q show network 2>/dev/null | grep -F ".modem_imei='$1'" \
		| sed -n "s/^network\.\([^.]*\)\.modem_imei=.*/\1/p" \
		| head -1
}

# Принадлежит ли интерфейс $1 модему (путь $2, IMEI $3)?
# IMEI-first: есть штамп IMEI и знаем IMEI модема - решает ТОЛЬКО он (два модема
# в одном порту различаются). Иначе - прежнее поведение по modem_path. Штампа нет
# вовсе = интерфейс из старых версий, считаем своим (миграция проставит).
iface_owned_by() {   # $1 - iface, $2 - usb-путь, $3 - imei (может быть пуст)
	[ -n "$1" ] || return 1
	_ow_i=$(uci -q get "network.$1.modem_imei")
	if [ -n "$_ow_i" ]; then
		# Интерфейс ЗАКРЕПЛЁН за конкретным железом. Совпал IMEI - наш. Не совпал
		# ИЛИ мы своего IMEI не знаем - ЧУЖОЙ: по пути его забирать нельзя, там
		# может ждать возвращения вытесненный из этого же разъёма модем.
		#
		# НО IMEI НЕ ВСЕГДА ПОСТОЯНЕН. Часть свистков (живой случай: Huawei
		# E3372 с рандомизатором IMEI, отчёт 24.08.2026) выдаёт НОВЫЙ валидный
		# IMEI после каждого переподключения. Для нас это выглядело как «в
		# разъём воткнули другой модем», и на каждый новый IMEI заводился ещё
		# один интерфейс: у пользователя накопились modem, modem2, modem3,
		# modem4 - все на одной eth2, с одним адресом, и все в зоне wan.
		# Поэтому у интерфейса есть ВТОРОЙ якорь железа - MAC его сетевой
		# карты (штамп modem_mac). MAC у свистка постоянен, а у другого
		# физического модема он другой, так что подмену железа в разъёме
		# якорь по-прежнему различает.
		if [ -n "$3" ] && [ "$_ow_i" = "$3" ]; then
			:
		else
			_ow_m=$(uci -q get "network.$1.modem_mac")
			# Нулевой штамп мог остаться от устройства с пустым MAC (ZTE-свисток
			# отдаёт 00:00:00:00:00:00): якорем он быть не может, иначе два таких
			# модема считались бы одним железом. Нет якоря - решает IMEI.
			case "$_ow_m" in
				''|00:00:00:00:00:00|ff:ff:ff:ff:ff:ff) return 1 ;;
			esac
			_ow_cm=$(iface_hw_mac "$2")
			[ -n "$_ow_cm" ] && [ "$_ow_m" = "$_ow_cm" ] || return 1
			# железо то же, сменился только IMEI - переставляем штамп
			[ -n "$3" ] && uci -q set "network.$1.modem_imei=$3" && uci -q commit network
			logger -t 5gmodem "iface $1: IMEI changed ($_ow_i -> $3) but the network card is the same ($_ow_m) - keeping the interface"
		fi
		# IMEI СОВПАЛ - но он не всегда уникален. У пользователя с четырьмя
		# модемами два одинаковых Thales MV31-W отдают ОДИН И ТОТ ЖЕ IMEI
		# (клонированный на восстановленных модулях): по IMEI каждый из них
		# считал бы своим и чужой интерфейс, и первый же resolve перенастроил бы
		# соседу device/APN. Если штамп пути указывает на ДРУГОЕ устройство,
		# которое СЕЙЧАС на шине, - IMEI неуникален, решаем по пути.
		_ow_p=$(uci -q get "network.$1.modem_path")
		if [ -n "$_ow_p" ] && [ "$_ow_p" != "$2" ] && [ -e "/sys/bus/usb/devices/$_ow_p" ]; then
			return 1
		fi
		return 0
	fi
	_ow_p=$(uci -q get "network.$1.modem_path")
	[ -n "$_ow_p" ] || return 0
	[ "$_ow_p" = "$2" ]
}

# Проставить ОБА штампа владельца. IMEI берём из секции, если не передан явно.
stamp_iface_owner() {   # $1 - iface, $2 - usb-путь, [$3 - imei]
	[ -n "$1" ] && [ -n "$2" ] || return 0
	note_foreign_uci network "stamp_iface_owner"
	uci -q set "network.$1.modem_path=$2"
	_si_i="$3"
	[ -n "$_si_i" ] || _si_i=$(imei_for_path "$2")
	[ -n "$_si_i" ] && uci -q set "network.$1.modem_imei=$_si_i"
	# MAC сетевой карты модема - второй якорь железа (см. iface_owned_by):
	# он переживает смену IMEI, которую устраивают свистки с рандомизатором.
	_si_m=$(iface_hw_mac "$2")
	[ -n "$_si_m" ] && uci -q set "network.$1.modem_mac=$_si_m"
	uci -q commit network
}

# MAC сетевой карты модема по USB-пути (у кого её нет - пусто).
#
# НУЛЕВОЙ И ПУСТОЙ MAC НЕ ГОДЯТСЯ В ЯКОРЬ. У raw-ip модемов (qmi_wwan)
# сетевая карта существует, но адреса у неё нет - файл пуст либо содержит
# 00:00:00:00:00:00 (проверено на EP06-E). Отдать такой «якорь» нельзя: по
# нему ЛЮБЫЕ два таких модема выглядели бы одним железом, и владение
# интерфейсом досталось бы соседу. Пусто = якоря нет, владение решает IMEI,
# как и раньше.
iface_hw_mac() {   # $1 - usb-путь
	[ -n "$1" ] || return 1
	for _hm in /sys/bus/usb/devices/"$1":*/net/*/address; do
		[ -f "$_hm" ] || continue
		_hm_v=$(cat "$_hm" 2>/dev/null | tr -d " \t\n")
		case "$_hm_v" in
			''|00:00:00:00:00:00|ff:ff:ff:ff:ff:ff) continue ;;
		esac
		printf '%s' "$_hm_v"
		return 0
	done
	return 1
}

# ПОДНЯТЬ ОДИН ИНТЕРФЕЙС БЕЗ ПЕРЕЧИТЫВАНИЯ КОНФИГА - ДЛЯ СТОРОЖЕЙ.
#
# `/sbin/ifup` в OpenWrt 25.12 перед своим down/up делает
# `ubus call network reload` (строка [ "$modes" = "down up" ] && ...). ЗАМЕРЕНО
# на стенде, чтобы не гадать: в спокойном состоянии этот reload безвреден -
# `ifup modem2` не тронул ни modem (uptime шёл непрерывно), ни wwan; даже
# committed-правка чужой секции (network.modem.mtu) соседа не уронила. То есть
# «ifup роняет всё» - неверно, netifd пересобирает только то, что реально
# изменилось.
#
# Отличие этой функции одно: она НЕ перечитывает конфиг вовсе, а значит не
# применяет чужие незакоммиченные/накопленные правки сети заодно с нашим
# подъёмом. Сторожа (sessionwatch, health) дёргают интерфейс по таймеру, конфиг
# при этом не меняют - им побочные эффекты reload не нужны ни в каком виде.
#
# ГДЕ ЕЁ НЕЛЬЗЯ: если мы только что ПОМЕНЯЛИ секцию интерфейса (APN, devpath,
# proto, пересоздание) - netifd держит конфиг в памяти и без reload поднимет
# СТАРУЮ версию. Там остаётся обычный ifup или явный reload рядом с ним.
iface_up() {   # $1 - интерфейс
	[ -n "$1" ] || return 1
	# МАРКЕР ВОССТАНОВЛЕНИЯ. Сюда приходят ТОЛЬКО сторожа - «связи нет, поднимаем
	# заново». Обычный ifup (переключение приоритета, ручной подъём) идёт мимо.
	# Разница принципиальна для fibocom-прото: при обычном подъёме он
	# переиспользует активную сессию, и переключение получается мгновенным, а
	# при восстановлении переиспользовать нельзя - сессия может быть мёртвой,
	# хотя модем считает её активной (залипание после смены региона). Маркер
	# читает и удаляет сам прото; для остальных протоколов он безвреден.
	printf '%s' "$(date +%s 2>/dev/null)" > "/tmp/5gmodem_fibo_cold_$1" 2>/dev/null
	ubus call network.interface down "{\"interface\":\"$1\"}" >/dev/null 2>&1
	# ПАУЗА ОБЯЗАТЕЛЬНА, И ПОДЪЁМ НАДО ПРОВЕРИТЬ. netifd разбирает down
	# асинхронно: пришедший впритык up он теряет, и интерфейс остаётся лежать с
	# autostart=false. Дальше его обходят стороной оба сторожа - «выключен
	# намеренно», - и модем висит вечно при исправном железе и готовой SIM
	# (стенд 05.08.2026, Quectel EP06: лестница вылечила ступенью 1, подъём
	# пропал, интерфейс пролежал час). Одного повтора хватает.
	sleep 2
	ubus call network.interface up "{\"interface\":\"$1\"}" >/dev/null 2>&1
	case "$(ubus call "network.interface.$1" status 2>/dev/null)" in
		*'"autostart": true'*) ;;
		*)
			sleep 3
			ubus call network.interface up "{\"interface\":\"$1\"}" >/dev/null 2>&1 ;;
	esac
	return 0
}

# Путь активного модема (короткая обёртка - зовётся почти везде).
active_path() {
	# Через снимок, если он взят (реестр печатает признак active в КАЖДОЙ записи,
	# то есть на трёх модемах спрашивал бы активный трижды); без снимка - как раньше.
	uci5g_get "@5gmodem[0]" active_modem
}

# Секция активного модема.
active_sec() {
	_ap=$(active_path)
	[ -n "$_ap" ] || return 1
	secname "$_ap"
}

# Брендовое имя оператора для РФ-MVNO по IMSI.
#
# ЗАЧЕМ. Сеть (и web-API HiLink) отдаёт имя ХОСТ-оператора: Т-Мобайл виден как
# Tele2, потому что физически работает на его сети. Настоящий бренд симки прячется
# в её IMSI (свой MCC-MNC). У AT-модемов это чинит чтение EF_SPN с SIM, но HiLink
# к SPN доступа не даёт, да и SPN у части симок - мусор ("T0"). Поэтому держим
# ВЫВЕРЕННЫЕ РУКАМИ соответствия в apn.list строками opname:<mcc-mnc>:<бренд> и
# применяем их в обоих путях (AT и HiLink) - имя тогда единое.
#
# ВЫВЕРЕННОЕ НАПИСАНИЕ ИМЕНИ ОПЕРАТОРА ПО ЧИСЛОВОМУ PLMN.
#
# ЗАЧЕМ. Модем отдаёт имя СЕТИ так, как его прописал оператор в эфире: с кодом
# страны и в своём регистре («MegaFon RUS», «Tele2 RU», «beeline»). В mccmnc.dat
# лежит выверенное написание («Megafon», «Tele2», «Beeline»), и основной опрос
# уже предпочитает его: если имя с SIM совпадает с базой без учёта регистра,
# берётся вариант из базы (см. SPN_NAME в 5gmodem.sh - там же пример «beeline» ->
# «Beeline»).
#
# А проба netpri этот последний шаг не делала и писала в кэш сырое имя. Из-за
# этого один и тот же модем подписан по-разному в двух местах страницы:
# в «Приоритете интернета» - «MegaFon RUS», в карточке - «Megafon». Разница видна
# как мигание: у НЕАКТИВНОГО модема файла от основного опроса нет вовсе, netpri
# показывает своё имя, а через пару секунд после перехода на карточку модем
# становится активным, опрос пишет файл - и подпись меняется на глазах.
#
# MVNO НЕ ТРОГАЕМ: если сырое имя с базой не совпадает (SIM «T-Mobile» на сети
# «Tele2»), оставляем как есть - различить бренд абонента может только основной
# опрос, он читает SPN с самой карты.
# opname_pretty <plmn> <сырое имя>
# Отсекаем избыточный страновой хвост в имени оператора: "MegaFon RUS" -> "MegaFon",
# "Tele2 Rus" -> "Tele2". Только завершающее " RUS"/" Rus" (любой регистр); одно
# слово "RUS" целиком и имена без хвоста не трогаем. Регистр самого имени сохраняем.
operator_clean() {
	case "$1" in
		*' '[Rr][Uu][Ss]) _oc=${1% *}; [ -n "$_oc" ] && printf '%s' "$_oc" || printf '%s' "$1" ;;
		*) printf '%s' "$1" ;;
	esac
}

opname_pretty() {
	_op_num=$(printf '%s' "$1" | tr -cd '0-9')
	_op_raw=$(printf '%s' "$2" | sed 's/^ *//;s/ *$//')
	# ИМЯ ОТ МОДЕМА - ПРИОРИТЕТНЕЕ БАЗЫ. Отсекаем страновой хвост тем же
	# operator_clean, что и главный опрос: 5gmodem.sh кладёт имя как ОТДАЁТ МОДЕМ
	# ("MegaFon", MVNO "T-Mobile"), и без этого карточка приоритетов расходилась бы
	# с главной по регистру - probe гнал имя через mccmnc.dat и показывал "Megafon"
	# там, где главная честно "MegaFon" (замечание владельца). Базу берём ТОЛЬКО как
	# фолбэк, когда модем имя не отдал (пусто / один код).
	[ -n "$_op_raw" ] && { operator_clean "$_op_raw"; return; }
	[ -n "$_op_num" ] || return
	# tr -d '\r' ОБЯЗАТЕЛЕН: mccmnc.dat в формате CRLF (тот же капкан, что в hilink.sh).
	awk -F';' '/^'"$_op_num"';/ {print $3}' /usr/share/5gmodem/mccmnc.dat 2>/dev/null \
		| head -1 | tr -d '\r' | sed 's/^ *//;s/ *$//'
}

# Пусто (return 1) - оверрайда нет, имя оставляем как отдала сеть.
# opname_brand <imsi>
opname_brand() {
	_ob_imsi=$(echo "$1" | tr -cd '0-9')
	[ "${#_ob_imsi}" -ge 5 ] || return 1
	_ob_f="/usr/share/5gmodem/apn.list"
	[ -f "$_ob_f" ] || return 1
	# Кандидаты PLMN: MNC в 3 и 2 цифры (как в apn_pick). Более специфичный -
	# 3-значный - пробуем первым.
	for _ob_len in 6 5; do
		_ob_p=$(printf '%s' "$_ob_imsi" | cut -c1-"$_ob_len")
		[ "${#_ob_p}" -eq "$_ob_len" ] || continue
		_ob_key="${_ob_p%${_ob_p#???}}-${_ob_p#???}"
		while IFS=: read -r _t _pat _val; do
			[ "$_t" = "opname" ] || continue
			[ "$_pat" = "$_ob_key" ] && [ -n "$_val" ] && { echo "$_val"; return 0; }
		done < "$_ob_f"
	done
	return 1
}

# ==== ИМЯ МОДЕЛИ: валидация ответа AT+CGMM ====
# Переехало из 5gmodem.sh: модель теперь заполняет не только основной опрос
# (он идёт лишь по АКТИВНОМУ модему), но и resolve - остальным присутствующим,
# иначе неактивный модем оставался в списке безымянным до переключения на него.
# ВАЛИДАЦИЯ ОБЯЗАТЕЛЬНА. AT-порт делят опрос метрик, simslot.sh и esim.sh; при
# столкновении ответ одной команды прилетает на чтение другой. Так в секцию уже
# попадало ЭХО ЧУЖОЙ КОМАНДЫ - "AT+SIMTYPE?" (её шлёт simslot.sh) - и висело там
# как имя модема: в интерфейсе показывалось «SimCom AT+SIMTYPE?». Разовая
# коллизия становилась ПОСТОЯННОЙ, потому что мы её сохраняли.
# Поэтому принимаем только правдоподобное имя: не эхо команды (AT.../+CME.../?),
# не ошибка, разумной длины.
_model_sane() {
	case "$1" in
		AT+*|AT^*|AT$*|at+*|at^*) return 1 ;;   # эхо AT-команды
		# эхо AT-команды и в «пробельной» форме: L850 с ATE1 при коллизии на общем
		# AT-порту отдавал "AT  4"/"AT+GTDUALSIM?" - раньше "AT " (пробел) проскакивал
		# мимо шаблонов выше и оседал как имя модема НАВСЕГДА.
		AT|AT[\ 0-9]*|at|at[\ 0-9]*) return 1 ;;
		*ERROR*|*error*) return 1 ;;
		*'?'*|*'='*|*'"'*) return 1 ;;          # синтаксис команды, не имя
		# ОТВЕТЫ чужих команд. Первая версия ловила только ЭХО (AT+...), и мусор
		# вида "Telit #BND: 0,18,A7E0BB0F38DF,42" или "Telit +CSQ: 23,4"
		# проскакивал в конфиг НАВСЕГДА (проверено). У AT-ответа опознаваемая
		# форма: префикс # или + и двоеточие после кода.
		*'#'*|*': '*) return 1 ;;
		+[A-Z]*|*' +'[A-Z]*) return 1 ;;
		'') return 1 ;;
	esac
	[ "${#1}" -ge 3 ] && [ "${#1}" -le 40 ] || return 1
	# СЛОВАРЬ СИМВОЛОВ НАСТОЯЩИХ ИМЁН. Шаблоны выше ловят знакомые ФОРМЫ мусора
	# (эхо, ответы, ERROR), но не произвольные обрывки: PACM-порт телефона
	# Samsung на CGMM отдал «~x~AT», и строка прошла все проверки - осела именем
	# модема (живой случай 03.08.2026). В настоящих моделях встречаются только
	# буквы, цифры, пробел и . _ + / ( ) - : всё остальное - обмен, а не имя.
	[ -z "$(printf '%s' "$1" | tr -d 'A-Za-z0-9 ._+/()-')" ] || return 1
	case "$1" in *[A-Za-z]*) return 0 ;; esac   # хоть одна буква
	return 1
}
# ВЕНДОР В МОДЕЛИ ДОЛЖЕН СОВПАДАТЬ С ВЕНДОРОМ ПО vid:pid.
#
# _model_sane проверяет, ПОХОЖА ли строка на модель, но не ЧЬЯ она - и этого
# оказалось мало. Живой случай: воткнули Huawei, опрос по чужому порту прочитал
# "Fibocom FM350-GL" и записал в секцию Huawei (12d1). Строка была совершенно
# правдоподобной, поэтому проверка на «похоже на модель» её пропустила.
#
# Судим ТОЛЬКО когда уверены: у vid есть однозначный вендор И в строке назван
# ДРУГОЙ известный вендор. Qualcomm-овый 05c6 не трогаем - под ним ходят модемы
# разных производителей, и там расхождение имени с vid нормально.
_vendor_by_vid() {
	case "$1" in
		0e8d:*|2cb7:*) echo fibocom ;;
		12d1:*)        echo huawei ;;
		1bc7:*)        echo telit ;;
		2c7c:*)        echo quectel ;;
		19d2:*)        echo zte ;;
		1e2d:00b7) ;;  # НЕ Cinterion: 1e2d:00b7 - это debug/QMI-композиция Qualcomm
		               # SDX55 (Foxconn T99W175 / Compal RXM-G1 / Dell DW5930e / Thales
		               # MV31-W), одолжившая vid Cinterion. Вернуть "cinterion" здесь -
		               # значит отбраковать наше имя «Compal RXM-G1» (в reject-списке есть
		               # "compal") и оставить сырой SG500M2-X. Пусто = не судим (ID общий).
		1e2d:*)        echo cinterion ;;
		2dee:*)        echo meiglink ;;
		1e0e:*)        echo simcom ;;
	esac
}
_model_vendor_ok() {   # $1 - модель, $2 - vidpid
	_mv_want=$(_vendor_by_vid "$2")
	[ -n "$_mv_want" ] || return 0            # вендор по vid неизвестен - не судим
	# СИНОНИМЫ ОДНОЙ КОМПАНИИ. VID 1e2d принадлежит Cinterion, но это тот же
	# Thales (бывший Gemalto): MV31-W честно отвечает «Thales MV31-W», а гвард
	# считал thales чужим вендором и браковал модель НА КАЖДОМ опросе - в
	# журнале раз в 5 c «модель не от вендора, в профиль не пишем», модель в
	# секции так и не появлялась (живой отчёт 06.08.2026, MV31-W под umbim).
	_mv_syn="$_mv_want"
	case "$_mv_want" in
		cinterion) _mv_syn="cinterion thales gemalto" ;;
	esac
	_mv_low=$(printf '%s' "$1" | tr 'A-Z' 'a-z')
	for _mv_a in $_mv_syn; do
		case "$_mv_low" in *"$_mv_a"*) return 0 ;; esac
	done
	# Имя вендора в строке вообще не названо - тоже не судим: многие модемы
	# отдают голую модель ("RM520N-GL", "E3372"), и это нормально.
	#
	# compal/foxconn/thales/dell - НАШИ синтезированные дружелюбные имена (см.
	# профиль modem/usb/05c690d6: MODEL="Compal RXM-G1"). Сам Qualcomm-модем ходит
	# под 05c6, который выше (return 0) не судим, так что своё имя он сохранит. Но
	# если такое имя по ошибке протекло в секцию модема ДРУГОГО вендора (живой
	# баг: "Compal RXM-G1" осел в секции Fibocom 0e8d после свопа и FM350 стал
	# показываться вторым «Compal» в табах) - вот это ловим и не пишем/не показываем.
	for _mv_other in fibocom huawei telit quectel zte cinterion meiglink simcom \
	                 compal foxconn thales dell; do
		case " $_mv_syn " in *" $_mv_other "*) continue ;; esac
		case "$_mv_low" in *"$_mv_other"*) return 1 ;; esac
	done
	return 0
}

# УРОВЕНЬ СИГНАЛА - ПО ПОРОГАМ СВОЕЙ ТЕХНОЛОГИИ И ПО ХУДШЕЙ ИЗ МЕТРИК.
#
# ЗАЧЕМ. +CSQ - это RSSI, мощность во ВСЕЙ полосе: вместе с соседними сотами,
# их трафиком и шумом. Про качество связи в LTE и NR он не говорит ничего.
# Живой стенд 25.08.2026: RSSI -63 дБм (CSQ 23, то есть «74 %») при RSRP -109,
# RSRQ -19 и SINR 0.0 - и реальных 1 Мбит/с. Поэтому есть метрики своей
# технологии - считаем по ним, а CSQ остаётся для 2G и для модемов, которые
# больше ничего не отдают.
#
# ШКАЛА - ПЯТЬ КОРЗИН ПО ЧЕТЫРЁМ ПОРОГАМ, как принято в отрасли
# (CellSignalStrength.getLevel в Android, операторские правки через
# CarrierConfig). Пороги LTE - значения AOSP по умолчанию. Процент получаем ИЗ
# корзины: номер*20 плюс доля внутри неё. Это ровно шкала наших иконок
# (0/20/40/60/80), поэтому «четыре палки» значат одно и то же на любой
# технологии, а не «столько-то процентов непонятно от чего».
#
# СВОДИМ ПО ХУДШЕЙ, А НЕ ПО СРЕДНЕЙ. Покрытие и качество должны быть хороши
# ОБА: при RSRP -109 и SINR 0 среднее рисует «средне», а канала нет. Узкое
# место - это и есть худшая метрика.
#
# ТЕХНОЛОГИЮ БЕРЁМ ИЗ ЯРЛЫКА РЕЖИМА: у NR свои пороги, шкала LTE дала бы ему
# вечные четыре палки. NSA - исключение: там RSRP приходит от LTE-якоря,
# поэтому пороги LTE (ярлыки у нас так и зовутся, см. endc-разбор в профилях).
sig_percent() {   # $1 - режим, $2 - RSRP, $3 - RSRQ, $4 - SINR, $5 - RSCP, $6 - Ec/Io, $7 - RSSI
	awk -v mode="$1" -v rsrp="$2" -v rsrq="$3" -v sinr="$4" \
	    -v rscp="$5" -v ecio="$6" -v rssi="$7" '
	function isnum(v) { return (v ~ /^-?[0-9]+(\.[0-9]+)?$/) }
	function pctof(v, t0, t1, t2, t3,   l, lo, hi, f) {
		if      (v >= t3) { l = 4; lo = t3; hi = t3 + (t3 - t2) }
		else if (v >= t2) { l = 3; lo = t2; hi = t3 }
		else if (v >= t1) { l = 2; lo = t1; hi = t2 }
		else if (v >= t0) { l = 1; lo = t0; hi = t1 }
		else              { l = 0; lo = t0 - (t1 - t0); hi = t0 }
		f = (v - lo) / (hi - lo)
		if (f < 0) f = 0
		if (f > 1) f = 1
		return l * 20 + f * 20
	}
	function take(v, t0, t1, t2, t3,   p) {
		if (!isnum(v)) return
		p = pctof(v + 0, t0, t1, t2, t3)
		if (best < 0 || p < best) best = p
	}
	BEGIN {
		best = -1
		m = tolower(mode)
		if      (m ~ /nsa/)                  rat = "lte"
		else if (m ~ /5g|nr/)                rat = "nr"
		else if (m ~ /lte|4g/)               rat = "lte"
		else if (m ~ /umts|hspa|wcdma|3g/)   rat = "umts"
		else if (m ~ /gsm|edge|gprs|2g/)     rat = "gsm"
		else                                 rat = "lte"
		# SINR РОВНО НОЛЬ ПРИ ПРИЛИЧНОМ RSRQ - ЭТО «НЕ ИЗМЕРЯЛ», А НЕ НОЛЬ.
		# Часть прошивок отдаёт 0.0 вместо прочерка, когда значения нет, и по
		# правилу худшей метрики такой ноль уронил бы шкалу на ровном месте.
		# Настоящий нулевой SINR почти всегда идёт с плохим RSRQ (наш стенд:
		# SINR 0.0 при RSRQ -19) - его мы засчитываем.
		if (sinr + 0 == 0 && isnum(rsrq) && rsrq + 0 >= -14) sinr = ""
		if (rat == "nr") {
			take(rsrp, -110, -90, -80, -65)
			take(rsrq,  -31, -19, -17, -14)
			take(sinr,   -5,   5,  15,  30)
		} else if (rat == "umts") {
			take(rscp, -115, -105, -95, -85)
			take(ecio,  -24,  -14,  -6,   1)
			if (best < 0) take(rssi, -107, -103, -97, -89)
		} else if (rat == "gsm") {
			take(rssi, -107, -103, -97, -89)
		} else {
			take(rsrp, -128, -118, -108, -98)
			take(rsrq,  -20,  -17,  -14, -11)
			take(sinr,   -3,    1,    5,  13)
		}
		if (best >= 0) printf "%d", best + 0.5
	}' 2>/dev/null
}

# СВОЁ ИМЯ МОДЕМА ДЛЯ ДАННОГО USB-ПУТИ - С УВАЖЕНИЕМ К ПРИВЯЗКЕ ПО IMEI.
#
# Имя хранится в секции слота (alias + alias_imei), но принадлежит ЖЕЛЕЗКЕ:
# 1) сначала ищем по ВСЕМ секциям имя, привязанное к IMEI текущего модема, -
#    так имя находит модем, переехавший в другой разъём;
# 2) фолбэк на alias секции слота - ТОЛЬКО если тот не привязан к ДРУГОМУ
#    IMEI. Иначе после замены модема в разъёме новый показывался бы под именем
#    старого (живой случай 08.08.2026: в слот SIM7100E воткнули EP06-E, и
#    вкладка продолжала звать его SIM7100E). Имя без привязки (IMEI не
#    прочитался при сохранении) достаётся слоту - это осознанный фолбэк для
#    партий с одинаковыми/нечитаемыми IMEI.
# ДОЗВОНЩИК NETIFD НА ПОРТУ. Сторонние прото xmm/atc дозваниваются через gcom
# прямо на AT-порту и НИЧЕГО не знают про нашу очередь at_lock: любое наше
# чтение в этот момент - взаимная кража ответов. Живой отчёт 09.08.2026 (L850,
# передозвон каждые ~20 c): вся диагностика получила ответы со сдвигом на
# команду, из краденых обрывков собрались фантомные вердикты. Дозвонщика не
# обгоняем и не ждём - просто уступаем порт: устаревший снимок честнее
# перемешанных ответов.
at_dialer_busy() {   # $1 - порт; код 0 = на порту живёт дозвонщик
	[ -n "$1" ] || return 1
	pgrep -f "gcom .*-d *$1" >/dev/null 2>&1 && return 0
	pgrep -f "gcom -d *$1" >/dev/null 2>&1
}

# Модемом фактически владеет ModemManager? Проверка ПО ФАКТУ - модем числится
# в списке MM, - а не по прото интерфейса: конфиг может разойтись с реальностью
# (интерфейс mbim/qmi/отсутствует, а MM запущен и модем захватил). Свои модемы
# мы прячем от MM инхибицией (mm-inhibit.sh), их в списке нет - ложных
# срабатываний на них не будет. Нужна там, где под MM нельзя трогать AT-порт и
# канал: у DW5821e/T77W968 наш AT-батч параллельно MM ронял сессию данных при
# каждом открытии вкладки (issue #13).
# mmcli - это D-Bus: ответ кэшируем на минуту, лог - только при смене вердикта.
mm_owns_path() {   # $1 - usb-путь; код 0 = владеет MM
	[ -n "$1" ] || return 1
	pgrep -f '/usr/sbin/ModemManager' >/dev/null 2>&1 || return 1
	_mo_c="/tmp/5gmodem_mmowns_$(echo "$1" | sed 's/[^A-Za-z0-9]/_/g')"
	_mo_v=""
	if [ -s "$_mo_c" ] && [ -n "$(find "$_mo_c" -mmin -1 2>/dev/null)" ]; then
		read -r _mo_v < "$_mo_c" 2>/dev/null
	else
		_mo_old=$(cat "$_mo_c" 2>/dev/null)
		_mo_v=$(/usr/share/5gmodem/modemswitch.sh mmindex "$1" 2>/dev/null)
		_mo_v="${_mo_v:-none}"
		printf '%s\n' "$_mo_v" > "$_mo_c" 2>/dev/null
		if [ "$_mo_v" != "$_mo_old" ] && [ "$_mo_v" != "none" ]; then
			logger -t 5gmodem "modem $1 is registered in ModemManager (index $_mo_v) - leaving AT and the channel alone"
		fi
	fi
	[ -n "$_mo_v" ] && [ "$_mo_v" != "none" ]
}

alias_for_path() {   # $1 - usb-путь; печатает имя или ничего
	[ -n "$1" ] || return 0
	_af_sec=$(secname "$1")
	_af_snap=$(uci -q show 5gmodem 2>/dev/null)
	_af_im=$(printf '%s\n' "$_af_snap" \
		| sed -n "s/^5gmodem\.$_af_sec\.imei='\(.*\)'\$/\1/p" | head -1)
	if [ -n "$_af_im" ]; then
		_af_a=$(printf '%s\n' "$_af_snap" | awk -F"[.=]" -v im="$_af_im" '
			/\.alias_imei=/ { v = $NF; gsub(/^.|.$/, "", v); imei[$2] = v; next }
			/\.alias=/ { line = $0; sub(/^[^=]*=/, "", line); gsub(/^.|.$/, "", line); nm[$2] = line }
			END { for (s in nm) if (imei[s] == im && nm[s] != "") { print nm[s]; exit } }')
		[ -n "$_af_a" ] && { printf '%s\n' "$_af_a"; return 0; }
	fi
	_af_sa=$(printf '%s\n' "$_af_snap" \
		| sed -n "s/^5gmodem\.$_af_sec\.alias='\(.*\)'\$/\1/p" | head -1)
	[ -n "$_af_sa" ] || return 0
	_af_sm=$(printf '%s\n' "$_af_snap" \
		| sed -n "s/^5gmodem\.$_af_sec\.alias_imei='\(.*\)'\$/\1/p" | head -1)
	if [ -z "$_af_sm" ] || [ "$_af_sm" = "$_af_im" ]; then
		printf '%s\n' "$_af_sa"
	fi
}

# USB-путь модема, которому принадлежит tty-порт: /dev/ttyUSB5 -> 1-1.3.
# Жила в detect.sh; понадобилась и опросу метрик, чтобы сверять, ЧЕЙ порт он
# держит в руках, - поэтому переехала сюда. Пусто = определить не удалось.
tty_usbpath() {
	# ПУСТОЙ ВХОД - СРАЗУ ОТКАЗ. Без этой строки basename "" давал пустоту, путь
	# схлопывался в /sys/class/tty/, а разбор ниже возвращал буквальное «tty».
	# Последствия были неочевидные и вредные: гейт штампа IMEI сравнивал «tty» с
	# путём модема, не совпадало - IMEI не записывался, и в лог каждые пять секунд
	# уходило «порт  принадлежит tty». Хуже того, ключ кэша статики у ВСЕХ модемов
	# без AT-порта становился одинаковым («tty»), то есть данные разных модемов
	# складывались в один файл - ровно та беда, ради которой ключ и вводился.
	[ -n "$1" ] || return 1
	_tp=$(readlink -f "/sys/class/tty/$(basename "$1")/device" 2>/dev/null) || return 1
	[ -n "$_tp" ] || return 1
	_tp=${_tp%/*}
	_tp=${_tp##*/}
	echo "${_tp%%:*}"
}

# ЧЕЛОВЕЧЕСКОЕ ИМЯ МОДЕЛИ по сырому дескриптору или ответу mmcli.
# Один и тот же модуль представляется по-разному: «VOS_5G» в USB-дескрипторе,
# «SG500M2-X» в hardware-revision у ModemManager, «RXMG1...» в версии прошивки -
# всё это Compal RXM-G1. Раньше правило жило только в listmodems.sh, и модель,
# записанная в секцию по опросу mmcli, оставалась сырой: у модема с заводской
# прошивкой (05c6:9063) во вкладке значилось «VOS_5G».
# ИДЕНТИФИКАТОР ИЗ ОТВЕТА МОДЕМА - ПО ДЛИНЕ ЦИФРОВОЙ ЦЕПОЧКИ, А НЕ ПО СМЕЩЕНИЮ.
#
# Профили резали ответ фиксированным `cut -c 8-` (IMEI) и `cut -c 9-` (IMSI) в
# расчёте на ЭХО команды: «AT+GSN 357281097818657». Но эхо зависит от ATE: на
# живом EP06 модем отвечает БЕЗ него, и обрезка съедала начало номера - в
# карточке светились «97818657» вместо IMEI и «0366237» вместо IMSI (замечено
# владельцем 07.08.2026). Берём первую цепочку цифр подходящей длины: она же
# найдётся и когда эхо есть - в «AT+GSN» длинных чисел нет.
digits_of() {   # $1 - текст ответа, $2 - мин длина, $3 - макс длина
	printf '%s' "$1" | tr -c '0-9' '\n' \
		| awk -v a="${2:-14}" -v b="${3:-20}" 'length($0) >= a && length($0) <= b { print; exit }'
}

model_alias() {   # $1 - сырое имя; печатает нормализованное (или исходное)
	case "$1" in
		*VOS_5G*|*RXMG1*|*SG500M2*) echo "Compal RXM-G1" ;;
		# SIMCom отдаёт имя с вендорным префиксом (modem.generic.model и AT+CGMM =
		# "SIMCOM_SIM7100E", а часть прошивок - через пробел "SIMCOM SIM7100E").
		# Приводим к общему для приложения виду «Вендор Модель»: SIMCom SIM7100E
		# (официальное написание бренда - SIMCom, не SimCom и не SIMCOM).
		SIMCOM_*) echo "SIMCom ${1#SIMCOM_}" ;;
		SIMCOM\ *) echo "SIMCom ${1#SIMCOM }" ;;
		*) echo "$1" ;;
	esac
}

# УТОЧНИТЬ МОДЕЛЬ ВАРИАНТОМ ИЗ USB-ДЕСКРИПТОРА.
#
# $1 - имя, прочитанное у модема (ATI/CGMM), $2 - строка product с шины.
# Модем в ATI часто называет СЕМЕЙСТВО, а буква варианта остаётся только в
# дескрипторе: Quectel отвечает «Quectel / EP06», а на шине висит «EP06-E»;
# SIMCOM отвечает «SIM7600E», а модуль - «SIM7600E-H». Владелец справедливо
# ждёт увидеть полное имя своей железки (07.08.2026).
#
# Правило узкое и потому безопасное: дополняем ТОЛЬКО когда дескриптор
# ПРОДОЛЖАЕТ прочитанное имя - начинается с последнего слова модели и добавляет
# суффикс из букв/цифр через дефис или подчёркивание. Всё остальное (другое имя,
# чипсет, generic-строка) не трогаем: там дескриптор не точнее, а шумнее.
model_refine() {   # $1 - модель, $2 - product с шины; печатает уточнённую модель
	_mr_m="$1"; _mr_p="$2"
	[ -n "$_mr_m" ] || { printf '%s' "$_mr_m"; return 0; }
	[ -n "$_mr_p" ] || { printf '%s' "$_mr_m"; return 0; }
	_mr_last="${_mr_m##* }"                 # «Quectel EP06» -> «EP06»
	[ -n "$_mr_last" ] || { printf '%s' "$_mr_m"; return 0; }
	case "$_mr_p" in
		"$_mr_last"[-_]*)
			_mr_suf="${_mr_p#$_mr_last}"
			case "$_mr_suf" in
				[-_][A-Za-z0-9]|[-_][A-Za-z0-9][A-Za-z0-9]|[-_][A-Za-z0-9][A-Za-z0-9][A-Za-z0-9])
					printf '%s%s' "$_mr_m" "$_mr_suf"; return 0 ;;
			esac ;;
	esac
	printf '%s' "$_mr_m"
	return 0
}

# СВОБОДЕН ЛИ КАНАЛ cdc-wdm ДЛЯ НАШИХ ЗАПРОСОВ.
#
# Мы ходим в QMI через `qmicli -p`, а он поднимает qmi-proxy, и тот держит
# /dev/cdc-wdm. Штатный протокол qmi у netifd работает с тем же устройством
# НАПРЯМУЮ (uqmi), про прокси не знает: два владельца на одном канале путают
# ответы друг друга. У пользователя это выглядело так - netifd вис на «Waiting
# for network registration» с «Failed to parse message data», интерфейс
# оставался pending, ядро сыпало NETDEV WATCHDOG и ресетило устройство. Со
# стороны: после установки всё работает, а после перезагрузки соединение не
# поднимается, пока не удалить пакет (то есть пока не исчезнет наш опрос).
#
# Возвращает 0 (можно), если интерфейс модема НЕ на proto=qmi. Под ModemManager
# запрет не нужен: прокси там общий, MM сам через него и ходит.
qmi_channel_free() {
	_qcf_if=$(uci -q get "5gmodem.$(active_sec 2>/dev/null).network" 2>/dev/null)
	[ -n "$_qcf_if" ] || _qcf_if=$(uci -q get 5gmodem.@5gmodem[0].network 2>/dev/null)
	[ -n "$_qcf_if" ] || return 0
	# qmi/qmiraw - uqmi напрямую; mbim - umbim напрямую. ОБА не переживают
	# второго хозяина канала: наш qmicli/mbimcli -p поднимает прокси, тот
	# открывает cdc-wdm и ДЕРЖИТ его - прямые запросы netifd рушатся, сессия
	# умирает, а прокси живёт вечно (лечилось только ребутом). Живой случай
	# 17.08.2026, ZBT-Z8102AX + MV31-W на umbim: «открываю страницу 5gmodem -
	# пропадает интернет». Под ModemManager запрет не нужен: там прокси общий,
	# MM сам через него ходит.
	case "$(uci -q get "network.$_qcf_if.proto" 2>/dev/null)" in
		qmi|qmiraw|mbim) : ;;
		*) return 0 ;;
	esac
	# ВЛАДЕЕТ - ЗНАЧИТ ПОДНЯТ. Раньше смотрели ТОЛЬКО на proto, и у модема на
	# proto=qmi канал считался занятым ВСЕГДА - даже когда интерфейс лежит и
	# uqmi не запущен. Из-за этого фоновые QMI-чтения (слоты SIM, дозаполнение
	# метрик) не выполнялись никогда: на живом Quectel EP06 в QMI список слотов
	# был пуст при том, что qmicli читал его без единой заминки (05.08.2026).
	# Это ровно та же ошибка, что была в eSIM-гейте _wdm_owned_by_umbim, и
	# лечится так же - смотрим состояние, а не только запись в конфиге.
	# Опущенный интерфейс канал не держит, и мешать нам некому.
	_qcf_st=$(ubus call "network.interface.$_qcf_if" status 2>/dev/null)
	case "$_qcf_st" in
		*'"up": true'*) return 1 ;;
		# ПОДНИМАЕТСЯ ПРЯМО СЕЙЧАС - самый неудачный момент для чужого запроса:
		# netifd уже в канале, а up ещё false. Без этой ветки получался замкнутый
		# круг - мы читаем, дозвон срывается «Unknown error», интерфейс остаётся
		# опущенным, и мы читаем снова (наблюдалось на Quectel EP06 05.08.2026).
		*'"pending": true'*) return 1 ;;
	esac
	# uqmi/umbim в канале, даже если состояние ещё не обновилось.
	_qcf_dev=$(uci -q get "network.$_qcf_if.device" 2>/dev/null)
	pgrep -f "uqmi .*$_qcf_dev" >/dev/null 2>&1 && return 1
	pgrep -f "umbim .*$_qcf_dev" >/dev/null 2>&1 && return 1
	return 0
}

# ЕДИНАЯ ТОЧКА ДОСТУПА К QMI ДЛЯ ФОНОВЫХ ЧТЕНИЙ.
#
# Раньше `qmicli -p` звали шесть скриптов вразнобой, и гейт приходилось ставить
# в каждом - один пропущенный вызов сводил защиту на нет (так и вышло: прокси
# продолжал подниматься). Теперь фоновые читатели ходят ТОЛЬКО сюда.
#
# FAIL-CLOSED: если проверить занятость канала нечем, запрос НЕ выполняем. Это
# обратное прежнему поведению и сделано намеренно - цена ошибки несимметрична:
# не показать полосу в карточке безобидно, а сорвать подъём соединения нет.
#
# Действия ПО ТРЕБОВАНИЮ (mkiface.sh при создании интерфейса, qmi-recover.sh при
# починке канала, mm-inhibit.sh) сюда НЕ переводятся: они выполняются по явной
# команде пользователя, часто как раз тогда, когда интерфейс лежит, и запрет им
# только помешал бы.
#
# Usage: qmicli_p <устройство> <аргументы qmicli...>
qmicli_p() {
	command -v qmicli >/dev/null 2>&1 || return 1
	command -v qmi_channel_free >/dev/null 2>&1 || return 1
	qmi_channel_free || return 1
	_qp_dev="$1"; shift
	[ -c "$_qp_dev" ] || return 1
	# QMI-ПОВЕРХ-MBIM: на устройстве под cdc_mbim канал открывается ТОЛЬКО с
	# --device-open-mbim. Профиль Compal ставил флаг сам, а все остальные
	# читатели ходили без него - и на MBIM-модеме любой запрос отсюда падал
	# «couldn't open the QmiDevice: Transaction timed out». Живой случай
	# 04.08.2026 (Thales MV31-W на WH3000 Pro): слоты SIM и встроенный eUICC
	# были не видны вовсе, хотя ручной qmicli с флагом их показывал.
	# Драйвер берём из sysfs самого узла - не зависит от того, жив ли MM.
	_qp_mb=""
	case "$(readlink -f "/sys/class/usbmisc/${_qp_dev##*/}/device/driver" 2>/dev/null)" in
		*/cdc_mbim) _qp_mb="--device-open-mbim" ;;
	esac
	# ПРЕДОХРАНИТЕЛЬ ПО ВРЕМЕНИ. qmicli на заклиненном/занятом канале висит
	# БЕСКОНЕЧНО и держит его: живой случай 04.08.2026 - оставшийся с опроса
	# метрик `--nas-get-tx-rx-info=lte` заблокировал канал модема насмерть, и
	# следом отказали слоты SIM, eSIM и все прочие чтения, пока процесс не убили
	# руками. Убиваем ТОЛЬКО свой вызов: ходим через qmi-proxy (-p), поэтому
	# client-ID принадлежит прокси и kill -9 пул модема не течёт (тот же довод,
	# что в simslot.sh).
	# ЗАВИСШИЙ ПРОКСИ - НЕ ПРИГОВОР. mbim-proxy/qmi-proxy после переэнумерации
	# модема остаётся со старыми дескрипторами: ЛЮБОЙ запрос через него виснет
	# («couldn't open the QmiDevice: Transaction timed out»), а прямой заход к
	# устройству работает. Живой случай 04.08.2026: у пользователя пропали
	# кнопки SIM-слотов и «не переключался» слот - на деле прямой qmicli всё
	# читал и переключал, а наш -p упирался в мёртвый прокси.
	# Прямой доступ безопасен ТОЛЬКО когда каналом никто не владеет: MM выключен
	# и интерфейс модема не поднят. Иначе (MM/umbim держат устройство) остаёмся
	# на прокси - лучше не отдать данные, чем сорвать соединение.
	# ПРИ proto=qmi ХОДИМ БЕЗ ПРОКСИ.
	#
	# Сюда мы попадаем, только когда qmi_channel_free разрешил (интерфейс лежит,
	# uqmi не работает) - канал в этот момент свободен, и прямой запрос безопасен.
	# А вот `-p` опасен: он ПОДНИМАЕТ qmi-proxy, тот остаётся жить и держит
	# устройство, после чего netifd (его uqmi ходит НАПРЯМУЮ, без прокси) получает
	# «Request timed out» на каждом дозвоне. Интерфейс при этом не поднимается
	# вовсе, хотя модем зарегистрирован и сессия по QMI уже «connected» - ровно
	# это наблюдалось на живом EP06 05.08.2026, и лечилось killall qmi-proxy.
	# Поэтому для qmi-интерфейсов прокси не трогаем: одно чтение напрямую дешевле
	# и безопаснее, чем демон, конфликтующий с netifd.
	_qp_proto=$(uci -q get "network.$(uci -q get 5gmodem.@5gmodem[0].network 2>/dev/null).proto" 2>/dev/null)
	_qp_direct=""
	if [ "$_qp_proto" = "qmi" ]; then
		_qp_direct=1
	elif ! pgrep -f '/usr/sbin/ModemManager' >/dev/null 2>&1; then
		_qp_if=$(uci -q get 5gmodem.@5gmodem[0].network 2>/dev/null)
		if [ -z "$_qp_if" ] || ! ubus call "network.interface.$_qp_if" status 2>/dev/null \
			| grep -q '"up": true'; then
			_qp_direct=1
		fi
	fi
	# ПОМНИМ, ЧТО ПРОКСИ МЁРТВ, И НЕ ПЛАТИМ ЗА НЕГО КАЖДЫЙ РАЗ.
	# Мёртвым он бывает не эпизодически, а ПОСТОЯННО (у Thales MV31-W на WH3000
	# любой запрос через mbim-proxy упирается в таймаут, а прямой отвечает сразу).
	# Без отметки каждое холодное чтение стоило 20 c ожидания впустую: страница
	# «Сеть» подтормаживала, а кнопки SIM/eSIM появлялись через полминуты - именно
	# так это выглядело у человека 04.08.2026. Отметку держим 120 c: прокси
	# оживает после переподнятия интерфейса, и через две минуты мы его перепробуем.
	# Отметка работает ТОЛЬКО когда есть куда отступать (_qp_direct): если каналом
	# владеет MM или поднятый интерфейс, прямой заход запрещён и прокси - наш
	# единственный путь, каким бы медленным он ни был.
	# ОДИН qmicli НА УСТРОЙСТВО ЗА РАЗ.
	#
	# Канал cdc-wdm не терпит двух хозяев: параллельные вызовы путают ответы и
	# подвешивают друг друга (об этом же сказано ниже про netifd). А хозяев у нас
	# как раз двое - фоновый сбор QMI-метрик (до пяти вызовов подряд, раз в ~5 c)
	# и чтение слотов SIM. На MBIM-модеме каждый вызов идёт секунды, поэтому
	# слоты не пролезали ВООБЩЕ: их qmicli упирался в занятый канал, висел до
	# сторожа и возвращал пустоту - кнопки SIM/eSIM не появлялись ни при открытии
	# страницы, ни после F5 (живой случай 04.08.2026, Thales MV31-W).
	# Ждём очередь до 15 c; не дождались - идём как раньше (лучше рискнуть, чем
	# молча не отдать данные). Дробного sleep в busybox нет, шаг - секунда.
	# fd ЗАКРЫВАЕМ У ВСЕХ ФОНОВЫХ: и qmicli, и сторож наследуют его, и сторож
	# держал бы замок ещё 20 c после нашего выхода (тот же капкан, что с procd).
	_qp_lk="/var/lock/5gmodem_qmi_${_qp_dev##*/}.lock"
	exec 9>"$_qp_lk" 2>/dev/null
	_qp_i=0
	while [ "$_qp_i" -lt 15 ]; do
		flock -n 9 2>/dev/null && break
		sleep 1
		_qp_i=$((_qp_i + 1))
	done
	_qp_bad="/tmp/5gmodem_qmiproxy_bad.${_qp_dev##*/}"
	_qp_now=$(cut -d. -f1 /proc/uptime)
	_qp_skip=""
	if [ -n "$_qp_direct" ] && [ -f "$_qp_bad" ]; then
		_qp_when=$(cat "$_qp_bad" 2>/dev/null)
		case "$_qp_when" in
			''|*[!0-9]*) rm -f "$_qp_bad" ;;
			*) [ $((_qp_now - _qp_when)) -lt 120 ] && _qp_skip=1 || rm -f "$_qp_bad" ;;
		esac
	fi
	_qp_o="/tmp/5gmodem_qmicli.$$"
	# Для qmi-интерфейса пробу через прокси пропускаем совсем (см. выше).
	[ "$_qp_proto" = "qmi" ] && _qp_skip=1
	if [ -z "$_qp_skip" ]; then
		# Ждём прокси МЕНЬШЕ, когда есть фолбэк: 20 c нужны только там, где идти
		# больше некуда. Живой прокси отвечает за доли секунды, так что 6 c с
		# запасом отличают «занят» от «мёртв».
		_qp_w=20; [ -n "$_qp_direct" ] && _qp_w=6
		qmicli -d "$_qp_dev" -p $_qp_mb "$@" > "$_qp_o" 2>/dev/null 9>&- &
		_qp_pid=$!
		( sleep "$_qp_w"; kill -9 "$_qp_pid" 2>/dev/null ) >/dev/null 2>&1 9>&- &
		_qp_k=$!
		# Опрос вместо голого wait: qmicli в D-state на мёртвом cdc-wdm
		# неубиваем, wait висел бы вечно (класс бага - atprobe/at_query).
		sleep_tick_init
		_qp_i=0; _qp_max=$(( (_qp_w + 1) * _TICKS_PER_SEC ))
		while kill -0 "$_qp_pid" 2>/dev/null && [ "$_qp_i" -lt "$_qp_max" ]; do
			_qp_i=$((_qp_i + 1)); sleep "$_SLEEP_TICK"
		done
		if kill -0 "$_qp_pid" 2>/dev/null; then _qp_rc=1; else wait "$_qp_pid" 2>/dev/null; _qp_rc=$?; fi
		kill "$_qp_k" 2>/dev/null; wait "$_qp_k" 2>/dev/null
		if [ -s "$_qp_o" ]; then
			rm -f "$_qp_bad"
		elif [ -n "$_qp_direct" ]; then
			printf '%s\n' "$_qp_now" > "$_qp_bad"
		fi
	fi
	# Прокси не ответил (или пропущен как заведомо мёртвый), а канал свободен -
	# читаем напрямую (см. выше).
	if [ ! -s "$_qp_o" ] && [ -n "$_qp_direct" ]; then
		qmicli -d "$_qp_dev" $_qp_mb "$@" > "$_qp_o" 2>/dev/null 9>&- &
		_qp_pid=$!
		( sleep 20; kill -9 "$_qp_pid" 2>/dev/null ) >/dev/null 2>&1 9>&- &
		_qp_k=$!
		sleep_tick_init
		_qp_i=0; _qp_max2=$(( 21 * _TICKS_PER_SEC ))
		while kill -0 "$_qp_pid" 2>/dev/null && [ "$_qp_i" -lt "$_qp_max2" ]; do
			_qp_i=$((_qp_i + 1)); sleep "$_SLEEP_TICK"
		done
		if kill -0 "$_qp_pid" 2>/dev/null; then _qp_rc=1; else wait "$_qp_pid" 2>/dev/null; _qp_rc=$?; fi
		kill "$_qp_k" 2>/dev/null; wait "$_qp_k" 2>/dev/null
		[ -s "$_qp_o" ] && logger -t 5gmodem "qmi: proxy not responding - read directly from $_qp_dev"
	fi
	cat "$_qp_o" 2>/dev/null; rm -f "$_qp_o"
	exec 9>&- 2>/dev/null
	return "${_qp_rc:-0}"
}

# --- ПРОВЕРКА ВХОДЯЩИХ ЗНАЧЕНИЙ ----------------------------------------------
#
# ЗАЧЕМ. Значения со страницы уходят в AT-команды и в имена устройств. Для
# AT-канала «инъекция» - это возврат каретки: один параметр вида «1<CR>AT+CPIN=…»
# станет ДВУМЯ командами, и вторую модем послушно выполнит. Через веб-морду это
# доступно только администратору (наш ACL и без того равен root, см. README), так
# что это не эскалация прав - но это класс ошибок, который однажды проявится не
# как атака, а как случайно посланная модему команда из чужого поля.
#
# ПРАВИЛО: значение, пришедшее аргументом в скрипт, проверяем ДО первого
# использования. Проверка - белым списком: перечисляем, что можно, а не что
# нельзя. Все предикаты молчат и возвращают код: 0 - годится, 1 - нет.

# Целое без знака: номер слота, номер режима, индекс.
is_num() {
	case "$1" in
		''|*[!0-9]*) return 1 ;;
		*) return 0 ;;
	esac
}

# Список чисел через пробел - так страница передаёт набор диапазонов
# («1 3 7 20»). Пустая строка НЕ годится: пустой набор диапазонов бессмыслен, а
# у нас для сброса есть отдельное слово «default».
is_numlist() {
	[ -n "$1" ] || return 1
	case "$1" in
		*[!0-9\ ]*) return 1 ;;
	esac
	# только пробелы - тоже не список
	case "$1" in
		*[0-9]*) return 0 ;;
		*) return 1 ;;
	esac
}

# Путь к устройству. Разрешаем ровно то, с чем работаем, и никаких «..»:
# значение приходит от страницы и подставляется в -d у sms_tool/qmicli.
is_devpath() {
	case "$1" in
		*..*|*[!A-Za-z0-9/._-]*) return 1 ;;
		/dev/ttyUSB[0-9]*|/dev/ttyACM[0-9]*|/dev/cdc-wdm[0-9]*|/dev/wwan[0-9]*) return 0 ;;
		*) return 1 ;;
	esac
}

# AT-команда целиком - для тех двух мест, где произвольная команда это ФИЧА
# (консоль AT и сбор диагностики). Здесь белый список шире, но главное: никаких
# CR/LF, то есть одной командой и останется.
is_atcmd() {
	[ -n "$1" ] || return 1
	# tr, а не case: в шаблоне case круглые скобки и точка с запятой конфликтуют
	# с его собственным синтаксисом (на этом и споткнулась первая версия).
	# Убираем всё разрешённое - если что-то осталось, значение не годится.
	#
	# ОПАСНЫ ЗДЕСЬ ТОЛЬКО CR И LF. Команда уходит в sms_tool ОТДЕЛЬНЫМ АРГУМЕНТОМ,
	# без eval и без шелла, поэтому «шелловские» символы никакой силы не имеют -
	# смысл проверки в том, чтобы запрос остался ОДНОЙ командой (иначе
	# «AT<CR>AT+CPIN=1234» ушло бы двумя, и вторую модем послушно выполнил бы).
	# Список это и обеспечивает: CR и LF в него не входят.
	#
	# ВЕНДОРНЫЙ ПРЕФИКС - ЗАКОННАЯ ЧАСТЬ AT, и его тут не было. Из-за этого
	# консоль AT отклоняла своей же проверкой почти всё вендорное: `^` (Huawei,
	# Foxconn, Compal, Thales - AT^SLBAND, AT^CUSTOMER, AT^switch_slot, AT^TEMP),
	# `$` (Telit GNSS - AT$GPSACP), `!` (Sierra - AT!BAND), `%` (u-blox), а заодно
	# и совершенно стандартные AT&F / AT&W. Человек видел «bad command» на всё,
	# кроме ATI и AT+CSQ, и думал, что команд не понимает модем - хотя до модема
	# они не доходили вовсе (живой отчёт 04.08.2026, Foxconn T99W175).
	# Точка с запятой нужна сцепкам («AT+COPS=3,0;+COPS?»), скобки - тест-командам.
	# Дефис держим ПОСЛЕДНИМ: в середине набора tr прочитал бы его как диапазон.
	#
	# ПЕРЕВОД СТРОКИ ПРОВЕРЯЕМ ОТДЕЛЬНО, А НЕ СПИСКОМ. Проверка списком его НЕ
	# ЛОВИЛА, причём с самого начала: подстановка команд $(...) срезает хвостовые
	# переводы строки, поэтому когда от команды оставался ровно один LF, тест
	# получал пустую строку и считал значение годным. То есть «AT<LF>AT+CPIN=1234»
	# проходило, и модем послушно выполнял ВТОРУЮ команду - ровно то, ради чего
	# проверка и писалась (найдено 04.08.2026). С CR такого не было: его $(...)
	# не трогает. Ловим оба до списка, шаблоном с литеральными символами.
	case "$1" in
		*'
'*) return 1 ;;
	esac
	case "$1" in
		*"$(printf '\r')"*) return 1 ;;
	esac
	[ -z "$(printf '%s' "$1" | tr -d 'A-Za-z0-9+?=",:;*#._ /()^$!%&@[]{}<>~|'"'"'-')" ]
}

# --- ШАГ ОЖИДАНИЯ ДЛЯ ЦИКЛОВ-СТОРОЖЕЙ ----------------------------------------
#
# Дробный sleep есть НЕ во всех busybox (atlock.sh это уже знал; живьём: стенд
# GL9869 отвечает «invalid number» на sleep 0.1) - там цикл ожидания превратился
# бы в busy-loop с нулевым таймаутом. Проба (sleep 0.0) мгновенна и валидна
# только при FANCY_SLEEP; без него шаг - целая секунда, потолки пересчитываются
# через _TICKS_PER_SEC.
_SLEEP_TICK=""
_TICKS_PER_SEC=1
sleep_tick_init() {
	[ -n "$_SLEEP_TICK" ] && return 0
	if (sleep 0.0) 2>/dev/null; then
		_SLEEP_TICK="0.1"; _TICKS_PER_SEC=10
	else
		_SLEEP_TICK="1"; _TICKS_PER_SEC=1
	fi
}

# --- ОДИН ВХОД ДЛЯ AT-ЗАПРОСА ------------------------------------------------
#
# ЗАЧЕМ. «Спросить модем и разобрать ответ» в этом дереве написано пятьдесят с
# лишним раз, в семнадцати файлах, и каждый раз чуть по-своему. Из этого следуют
# три беды, все наблюдались живьём:
#
#   1. ЧАСТЬ ХОДИТ В ПОРТ БЕЗ ОЧЕРЕДИ. mkiface, qmi-recover, iscompal,
#      mm-inhibit, collect - у них нет at_lock вовсе. Параллельный читатель
#      забирает ответ себе, а спросивший получает пустоту: воспроизведено на
#      стенде (`sms_tool` -> «No response from modem», ответ ушёл в чужой `cat`).
#      Отличить «модем молчит» от «ответ украли» после этого невозможно, и на
#      этом строятся ложные диагнозы - на один такой я потратил полночи.
#   2. У sms_tool НЕТ ТАЙМАУТА: на молчащем порту он висит ~35 c. Обход написан
#      в esim.sh (at_bounded) и в collect.sh (run) - по отдельности.
#   3. Разбор ответа у каждого свой, и ошибки обрабатываются как получится.
#
# ЧТО ДЕЛАЕТ. Берёт очередь к порту, ограничивает время, снимает CR, отдаёт
# ответ. Блокировку СНИМАЕТ ТОЛЬКО ЕСЛИ САМА ВЗЯЛА: at_lock ре-ентрантен (см.
# _AT_LOCK_HELD в atlock.sh), и слепой at_unlock разрушил бы лок вызывающего,
# который держит его на всю свою работу.
#
# Usage: at_query <порт> <команда> [таймаут=8] [ожидание очереди=10]
#        Коды: 0 - ответ (может быть пустым), 1 - нельзя спрашивать, 2 - порт занят
at_query() {
	_aq_p="$1"; _aq_c="$2"; _aq_t="${3:-8}"
	[ -n "$_aq_p" ] && [ -c "$_aq_p" ] || return 1
	command -v sms_tool >/dev/null 2>&1 || return 1
	# Команда уходит в модем - проверяем её так же, как значения со страницы.
	if command -v is_atcmd >/dev/null 2>&1 && ! is_atcmd "$_aq_c"; then
		logger -t 5gmodem "at_query: command rejected by validation"
		return 1
	fi
	[ -n "$AT_LOCK_FD" ] || . /usr/share/5gmodem/atlock.sh 2>/dev/null

	# НЕ ДОЖДАЛИСЬ ОЧЕРЕДИ - УХОДИМ, а не лезем в порт поверх чужого обмена.
	# Первая версия в этом случае всё равно шла в порт, и это обесценивало саму
	# очередь ровно там, где она нужнее: под нагрузкой мы портили данные ТОМУ, кто
	# дождался. Правило взято из netpri.sh, где оно было выведено на живой
	# нагрузке: потерять одно обновление дешевле, чем испортить чужое.
	_aq_mine=0
	if command -v at_lock >/dev/null 2>&1 \
	   && [ "$_AT_LOCK_HELD" != "$(basename "$_aq_p")" ]; then
		if at_lock "$_aq_p" "${4:-10}" 2>/dev/null; then
			_aq_mine=1
		else
			return 2   # 2, а не 1: «порт занят» - это не «модем молчит»
		fi
	fi

	# Ограничение времени: sms_tool своего не имеет. Сторож ЗАКРЫВАЕТ унаследованные
	# дескрипторы - иначе он держит stdout вызывающего, и читатель ждёт EOF лишние
	# секунды уже после того, как ответ готов (эти грабли стоили 1.4 c на опрос).
	_aq_o="/tmp/5gmodem_atq.$$"
	# 8>&- 9>&- ОБЯЗАТЕЛЬНЫ: fd 8 - это flock на самом порту (atlock.sh), и дети
	# наследуют его. Без закрытия killer-подоболочка ДЕРЖАЛА порт до конца своего
	# sleep ПОСЛЕ выхода at_query - следующий at_lock ждал до 6-8 c. Тот же урок
	# давно записан в обёртке sms_tool основного опроса («первый опрос 1 c,
	# каждый следующий 8-9 c») - я переизобрёл этот баг в at_query и поймал его
	# замером: опрос №1 1.8 c, №2-3 по 6.7 c, спящие sleep с fd на ttyUSB2.
	sms_tool -d "$_aq_p" at "$_aq_c" > "$_aq_o" 2>/dev/null 8>&- 9>&- &
	_aq_pid=$!
	( exec >/dev/null 2>&1 8>&- 9>&-; sleep "$_aq_t"; kill "$_aq_pid" 2>/dev/null ) </dev/null & _aq_w=$!
	# НЕ голый wait: sms_tool в D-state (вис в драйвере tty) не убивается
	# сторожем, и wait висел бы вечно - rpcd 30 c, XHR error на страницах
	# (T99W175 05c6:9025, 17.08.2026). Опрос с потолком таймаут+1 c;
	# неубиваемого бросаем сиротой.
	sleep_tick_init
	_aq_i=0; _aq_max=$(( (${_aq_t:-8} + 1) * _TICKS_PER_SEC ))
	while kill -0 "$_aq_pid" 2>/dev/null && [ "$_aq_i" -lt "$_aq_max" ]; do
		_aq_i=$((_aq_i + 1)); sleep "$_SLEEP_TICK"
	done
	kill -0 "$_aq_pid" 2>/dev/null || wait "$_aq_pid" 2>/dev/null
	kill "$_aq_w" 2>/dev/null; wait "$_aq_w" 2>/dev/null

	[ "$_aq_mine" = 1 ] && at_unlock 2>/dev/null
	tr -d '\r' < "$_aq_o" 2>/dev/null
	rm -f "$_aq_o"
	return 0
}

# --- Загрузка из интернета с обходом через локальный прокси -------------------
# Прямой исходящий трафик РОУТЕРА при операторских белых списках мёртв, хотя
# на роутере крутится clash/mihomo и трафик клиентов ходит: tproxy перехватывает
# только форвард из LAN, собственные запросы роутера идут мимо. Лестница
# обкатана в tgnotify (Telegram в РФ): прямая попытка -> HTTP-порт из конфига
# clash -> рантайм mihomo (спросить /configs, при закрытом порте открыть его
# PATCH-ем; порт слушает только 127.0.0.1). Здесь та же лестница общим
# помощником - для кнопки обновления приложения и базы APN (живой запрос
# владельца EM9190, 19.08.2026: «виджеты обновляются через прокси, значит и
# апдейтер должен»). tgnotify пока держит свою копию - объединить при случае.

# HTTP-порт локального clash/mihomo; пусто и код 1, если его нет.
net_proxy_port() {
	_np_p=$(sed -n 's/^ *\(mixed-port\|port\) *: *\([0-9]*\).*/\2/p' \
		/opt/clash/config.yaml /etc/clash/config.yaml 2>/dev/null | head -1)
	case "$_np_p" in ''|0) ;; *) printf '%s' "$_np_p"; return 0 ;; esac
	command -v curl >/dev/null 2>&1 || return 1
	_np_s=$(sed -n "s/^ *secret *: *[\"']*\([^\"' ]*\).*/\1/p" \
		/opt/clash/config.yaml /etc/clash/config.yaml 2>/dev/null | head -1)
	_np_capi() {
		if [ -n "$_np_s" ]; then
			curl -s -m 3 -H "Authorization: Bearer $_np_s" "$@" 2>/dev/null
		else
			curl -s -m 3 "$@" 2>/dev/null
		fi
	}
	_np_r=$(_np_capi "http://127.0.0.1:9090/configs" | jsonfilter -e '@["mixed-port"]' 2>/dev/null)
	case "$_np_r" in ''|*[!0-9]*) return 1 ;; esac
	if [ "$_np_r" = "0" ]; then
		_np_capi -X PATCH "http://127.0.0.1:9090/configs" -d '{"mixed-port":7895}' -o /dev/null || return 1
		_np_r=7895
		logger -t 5gmodem "net: direct path is blocked - opened clash mixed-port 7895 (local API, 127.0.0.1 only)"
	fi
	printf '%s' "$_np_r"
}

# net_fetch <таймаут_с> <url> [файл] - в файл либо в stdout. Прямая попытка,
# при неудаче повтор через локальный прокси: curl -x (умеет CONNECT для https),
# без curl - wget с env-переменными (лучшее, что можно без него).
net_fetch() {
	_nf_t="$1"; _nf_u="$2"; _nf_o="$3"
	if [ -n "$_nf_o" ]; then
		wget -qO "$_nf_o" --timeout="$_nf_t" "$_nf_u" 2>/dev/null && [ -s "$_nf_o" ] && return 0
		rm -f "$_nf_o" 2>/dev/null
	else
		_nf_b=$(wget -qO- --timeout="$_nf_t" "$_nf_u" 2>/dev/null)
		[ -n "$_nf_b" ] && { printf '%s' "$_nf_b"; return 0; }
	fi
	_nf_p=$(net_proxy_port) || return 1
	[ -n "$_nf_p" ] || return 1
	logger -t 5gmodem "net: direct fetch failed - retrying via local proxy 127.0.0.1:$_nf_p"
	if command -v curl >/dev/null 2>&1; then
		if [ -n "$_nf_o" ]; then
			curl -fsSL -m "$_nf_t" -x "http://127.0.0.1:$_nf_p" -o "$_nf_o" "$_nf_u" 2>/dev/null \
				&& [ -s "$_nf_o" ] && return 0
			rm -f "$_nf_o" 2>/dev/null; return 1
		fi
		_nf_b=$(curl -fsSL -m "$_nf_t" -x "http://127.0.0.1:$_nf_p" "$_nf_u" 2>/dev/null)
		[ -n "$_nf_b" ] && { printf '%s' "$_nf_b"; return 0; }
		return 1
	fi
	if [ -n "$_nf_o" ]; then
		http_proxy="http://127.0.0.1:$_nf_p" https_proxy="http://127.0.0.1:$_nf_p" \
			wget -qO "$_nf_o" --timeout="$_nf_t" "$_nf_u" 2>/dev/null && [ -s "$_nf_o" ] && return 0
		rm -f "$_nf_o" 2>/dev/null; return 1
	fi
	_nf_b=$(http_proxy="http://127.0.0.1:$_nf_p" https_proxy="http://127.0.0.1:$_nf_p" \
		wget -qO- --timeout="$_nf_t" "$_nf_u" 2>/dev/null)
	[ -n "$_nf_b" ] && { printf '%s' "$_nf_b"; return 0; }
	return 1
}

# Аплинки ВНЕ зоны wan. Роутер с единственным портом держит интернет на
# LAN-интерфейсе (DHCP-клиент в зоне lan, живой случай: Odroid C2 с одним
# eth0) - в зоне wan его нет, и ряд приоритетов со сторожем его не видели.
# Признак аплинка - default-маршрут: у обычного статического lan его не
# бывает, поэтому на роутерах с отдельным wan-портом список не меняется.
# Виртуальные обёртки (tun/wg/zt...) не считаем: их default - туннель ПОВЕРХ
# аплинка, двигать их метрику из ряда приоритетов бессмысленно и вредно.
# $1 - сети зоны wan (через пробел): уже учтённые не повторяем.
# ДОБАВИТЬ DEFAULT-МАРШРУТ, ПЕРЕЖИВ ЗАНЯТУЮ МЕТРИКУ.
#
# $1 - семейство (-4/-6), $2 - устройство, $3 - метрика, $4 - шлюз или '',
# $5 - "table X" или ''.
#
# МЕТРИКА DEFAULT-МАРШРУТА УНИКАЛЬНА В ТАБЛИЦЕ ЦЕЛИКОМ, А НЕ В ПРЕДЕЛАХ
# УСТРОЙСТВА. `ip route add default dev A metric 130`, когда 130 уже занята
# устройством B, ядро отбивает: "RTNETLINK answers: File exists" (проверено на
# стенде 25.08.2026). Раньше отказ уходил в /dev/null, а вызывающий к тому
# моменту УЖЕ удалил старый маршрут - линк оставался ВООБЩЕ БЕЗ default:
# в списке зелёный (проба ходит с привязкой к устройству, ей маршрут не нужен),
# интернета нет, лечилось только ребутом. Занято - берём следующую свободную
# метрику: шаг между аплинками 10, места хватает, порядок не ломается. Совсем
# не вышло - пишем в журнал, а не молчим.
#
# Шлюз не on-link (адрес /32 у Wi-Fi-клиента и сотовых) - сперва прямой маршрут
# до самого шлюза, как это делает netifd.
route_add_default() {
	_rad_f="$1"; _rad_d="$2"; _rad_m="$3"; _rad_gw="$4"; _rad_t="$5"
	[ "$_rad_f" = "-4" ] && [ -n "$_rad_gw" ] && \
		ip -4 route add "$_rad_gw" dev "$_rad_d" $_rad_t 2>/dev/null
	_rad_i=0
	while [ "$_rad_i" -lt 9 ]; do
		if [ -n "$_rad_gw" ]; then
			_rad_e=$(ip "$_rad_f" route add default via "$_rad_gw" dev "$_rad_d" \
				metric "$((_rad_m + _rad_i))" $_rad_t 2>&1) && return 0
		else
			_rad_e=$(ip "$_rad_f" route add default dev "$_rad_d" \
				metric "$((_rad_m + _rad_i))" scope link $_rad_t 2>&1) && return 0
		fi
		case "$_rad_e" in *"File exists"*) ;; *) break ;; esac
		_rad_i=$((_rad_i + 1))
		# Съехали с задуманной метрики - это стоит увидеть в журнале: значит
		# метрику занял кто-то со стороны (туннель, чужой демон маршрутов).
		logger -t 5gmodem "route: metric $((_rad_m + _rad_i - 1)) is taken by another device, trying $((_rad_m + _rad_i)) for $_rad_d"
	done
	logger -t 5gmodem "route: cannot add default ${_rad_gw:+via $_rad_gw }dev $_rad_d metric $_rad_m: $_rad_e"
	return 1
}

extra_uplink_nets() {
	_eu_wan=" $1 "
	_eu_dump=$(ubus call network.interface dump 2>/dev/null)
	[ -n "$_eu_dump" ] || return 0
	ip -4 route show default 2>/dev/null \
		| sed -n 's/.* dev \([^ ]*\).*/\1/p' | sort -u | while read -r _eu_dev; do
		case "$_eu_dev" in
			tun*|tap*|wg*|zt*|vti*|xfrm*|gre*|tailscale*) continue ;;
		esac
		_eu_if=$(printf '%s' "$_eu_dump" \
			| jsonfilter -e "@.interface[@.l3_device=\"$_eu_dev\"].interface" 2>/dev/null | head -1)
		[ -n "$_eu_if" ] || continue
		case "$_eu_if" in loopback) continue ;; esac
		case "$_eu_wan" in *" $_eu_if "*) continue ;; esac
		printf '%s\n' "$_eu_if"
	done
