}

# СВОБОДЕН ЛИ КАНАЛ cdc-wdm ДЛЯ НАШИХ ЗАПРОСОВ.
#
# Мы ходим в QMI через `qmicli -p`, а он поднимает qmi-proxy, и тот держит
# /dev/cdc-wdm. Штатный протокол qmi у netifd работает с тем же устройством
# НАПРЯМУЮ (uqmi), про прокси не знает: два владельца на одном канале путают
# ответы друг друга. У пользователя это выглядело так - netifd вис на «Waiting
# for network registration» с «Failed to parse message data», интерфейс
# оставался pending, ядро сыпало NETDEV WATCHDOG и ресетило устройство. Со
# стороны: после установки всё работает, а после перезагрузки соединение не
# поднимается, пока не удалить пакет (то есть пока не исчезнет наш опрос).
#
# Возвращает 0 (можно), если интерфейс модема НЕ на proto=qmi. Под ModemManager
# запрет не нужен: прокси там общий, MM сам через него и ходит.
qmi_channel_free() {
	_qcf_if=$(uci -q get "5gmodem.$(active_sec 2>/dev/null).network" 2>/dev/null)
	[ -n "$_qcf_if" ] || _qcf_if=$(uci -q get 5gmodem.@5gmodem[0].network 2>/dev/null)
	[ -n "$_qcf_if" ] || return 0
	case "$(uci -q get "network.$_qcf_if.proto" 2>/dev/null)" in
		qmi) return 1 ;;
		*) return 0 ;;
	esac
}

# ЕДИНАЯ ТОЧКА ДОСТУПА К QMI ДЛЯ ФОНОВЫХ ЧТЕНИЙ.
#
# Раньше `qmicli -p` звали шесть скриптов вразнобой, и гейт приходилось ставить
# в каждом - один пропущенный вызов сводил защиту на нет (так и вышло: прокси
# продолжал подниматься). Теперь фоновые читатели ходят ТОЛЬКО сюда.
#
# FAIL-CLOSED: если проверить занятость канала нечем, запрос НЕ выполняем. Это
# обратное прежнему поведению и сделано намеренно - цена ошибки несимметрична:
# не показать полосу в карточке безобидно, а сорвать подъём соединения нет.
#
# Действия ПО ТРЕБОВАНИЮ (mkiface.sh при создании интерфейса, qmi-recover.sh при
# починке канала, mm-inhibit.sh) сюда НЕ переводятся: они выполняются по явной
# команде пользователя, часто как раз тогда, когда интерфейс лежит, и запрет им
# только помешал бы.
#
# Usage: qmicli_p <устройство> <аргументы qmicli...>
qmicli_p() {
	command -v qmicli >/dev/null 2>&1 || return 1
	command -v qmi_channel_free >/dev/null 2>&1 || return 1
	qmi_channel_free || return 1
	_qp_dev="$1"; shift
	[ -c "$_qp_dev" ] || return 1
	qmicli -d "$_qp_dev" -p "$@"
}

# --- ПРОВЕРКА ВХОДЯЩИХ ЗНАЧЕНИЙ ----------------------------------------------
#
# ЗАЧЕМ. Значения со страницы уходят в AT-команды и в имена устройств. Для
# AT-канала «инъекция» - это возврат каретки: один параметр вида «1<CR>AT+CPIN=…»
# станет ДВУМЯ командами, и вторую модем послушно выполнит. Через веб-морду это
# доступно только администратору (наш ACL и без того равен root, см. README), так
# что это не эскалация прав - но это класс ошибок, который однажды проявится не
# как атака, а как случайно посланная модему команда из чужого поля.
#
# ПРАВИЛО: значение, пришедшее аргументом в скрипт, проверяем ДО первого
# использования. Проверка - белым списком: перечисляем, что можно, а не что
# нельзя. Все предикаты молчат и возвращают код: 0 - годится, 1 - нет.

# Целое без знака: номер слота, номер режима, индекс.
is_num() {
	case "$1" in
		''|*[!0-9]*) return 1 ;;
		*) return 0 ;;
	esac
}

# Список чисел через пробел - так страница передаёт набор диапазонов
# («1 3 7 20»). Пустая строка НЕ годится: пустой набор диапазонов бессмыслен, а
# у нас для сброса есть отдельное слово «default».
is_numlist() {
	[ -n "$1" ] || return 1
	case "$1" in
		*[!0-9\ ]*) return 1 ;;
	esac
	# только пробелы - тоже не список
	case "$1" in
		*[0-9]*) return 0 ;;
		*) return 1 ;;
	esac
}

# Путь к устройству. Разрешаем ровно то, с чем работаем, и никаких «..»:
# значение приходит от страницы и подставляется в -d у sms_tool/qmicli.
is_devpath() {
	case "$1" in
		*..*|*[!A-Za-z0-9/._-]*) return 1 ;;
		/dev/ttyUSB[0-9]*|/dev/ttyACM[0-9]*|/dev/cdc-wdm[0-9]*|/dev/wwan[0-9]*) return 0 ;;
		*) return 1 ;;
	esac
}

# USSD-код: цифры и служебные символы набора. Ничего больше в него не входит.
is_ussd() {
	case "$1" in
		''|*[!0-9*#+]*) return 1 ;;
		*) return 0 ;;
	esac
}

# AT-команда целиком - для тех двух мест, где произвольная команда это ФИЧА
# (консоль AT и сбор диагностики). Здесь белый список шире, но главное: никаких
# CR/LF, то есть одной командой и останется.
is_atcmd() {
	[ -n "$1" ] || return 1
	# tr, а не case: в шаблоне case круглые скобки и точка с запятой конфликтуют
	# с его собственным синтаксисом (на этом и споткнулась первая версия).
	# Убираем всё разрешённое - если что-то осталось, значение не годится.
	# CR и LF в список не входят, значит команда останется одной командой.
	# Точка с запятой - ЗАКОННАЯ часть AT: команды сцепляются («AT+COPS=3,0;+COPS?»),
	# и без неё проверка отклоняла рабочий запрос имени оператора. Скобки нужны
	# тест-командам. Опасны здесь только CR и LF - их в списке нет.
	[ -z "$(printf '%s' "$1" | tr -d 'A-Za-z0-9+?=",:;*#._ /()-')" ]
}

# --- ОДИН ВХОД ДЛЯ AT-ЗАПРОСА ------------------------------------------------
#
# ЗАЧЕМ. «Спросить модем и разобрать ответ» в этом дереве написано пятьдесят с
# лишним раз, в семнадцати файлах, и каждый раз чуть по-своему. Из этого следуют
# три беды, все наблюдались живьём:
#
#   1. ЧАСТЬ ХОДИТ В ПОРТ БЕЗ ОЧЕРЕДИ. mkiface, qmi-recover, iscompal,
#      mm-inhibit, collect - у них нет at_lock вовсе. Параллельный читатель
#      забирает ответ себе, а спросивший получает пустоту: воспроизведено на
#      стенде (`sms_tool` -> «No response from modem», ответ ушёл в чужой `cat`).
#      Отличить «модем молчит» от «ответ украли» после этого невозможно, и на
#      этом строятся ложные диагнозы - на один такой я потратил полночи.
#   2. У sms_tool НЕТ ТАЙМАУТА: на молчащем порту он висит ~35 c. Обход написан
#      в esim.sh (at_bounded) и в collect.sh (run) - по отдельности.
#   3. Разбор ответа у каждого свой, и ошибки обрабатываются как получится.
#
# ЧТО ДЕЛАЕТ. Берёт очередь к порту, ограничивает время, снимает CR, отдаёт
# ответ. Блокировку СНИМАЕТ ТОЛЬКО ЕСЛИ САМА ВЗЯЛА: at_lock ре-ентрантен (см.
# _AT_LOCK_HELD в atlock.sh), и слепой at_unlock разрушил бы лок вызывающего,
# который держит его на всю свою работу.
#
# Usage: at_query <порт> <команда> [таймаут=8] [ожидание очереди=10]
#        Коды: 0 - ответ (может быть пустым), 1 - нельзя спрашивать, 2 - порт занят
#        at_field <порт> <команда> <префикс>   - первое значение «+ПРЕФИКС: …»
at_query() {
	_aq_p="$1"; _aq_c="$2"; _aq_t="${3:-8}"
	[ -n "$_aq_p" ] && [ -c "$_aq_p" ] || return 1
	command -v sms_tool >/dev/null 2>&1 || return 1
	# Команда уходит в модем - проверяем её так же, как значения со страницы.
	if command -v is_atcmd >/dev/null 2>&1 && ! is_atcmd "$_aq_c"; then
		logger -t 5gmodem "at_query: команда отклонена проверкой"
		return 1
	fi
	[ -n "$AT_LOCK_FD" ] || . /usr/share/5gmodem/atlock.sh 2>/dev/null

	# НЕ ДОЖДАЛИСЬ ОЧЕРЕДИ - УХОДИМ, а не лезем в порт поверх чужого обмена.
	# Первая версия в этом случае всё равно шла в порт, и это обесценивало саму
	# очередь ровно там, где она нужнее: под нагрузкой мы портили данные ТОМУ, кто
	# дождался. Правило взято из netpri.sh, где оно было выведено на живой
	# нагрузке: потерять одно обновление дешевле, чем испортить чужое.
	_aq_mine=0
	if command -v at_lock >/dev/null 2>&1 \
	   && [ "$_AT_LOCK_HELD" != "$(basename "$_aq_p")" ]; then
		if at_lock "$_aq_p" "${4:-10}" 2>/dev/null; then
			_aq_mine=1
		else
			return 2   # 2, а не 1: «порт занят» - это не «модем молчит»
		fi
	fi

	# Ограничение времени: sms_tool своего не имеет. Сторож ЗАКРЫВАЕТ унаследованные
	# дескрипторы - иначе он держит stdout вызывающего, и читатель ждёт EOF лишние
	# секунды уже после того, как ответ готов (эти грабли стоили 1.4 c на опрос).
	_aq_o="/tmp/5gmodem_atq.$$"
	# 8>&- 9>&- ОБЯЗАТЕЛЬНЫ: fd 8 - это flock на самом порту (atlock.sh), и дети
	# наследуют его. Без закрытия killer-подоболочка ДЕРЖАЛА порт до конца своего
	# sleep ПОСЛЕ выхода at_query - следующий at_lock ждал до 6-8 c. Тот же урок
	# давно записан в обёртке sms_tool основного опроса («первый опрос 1 c,
	# каждый следующий 8-9 c») - я переизобрёл этот баг в at_query и поймал его
	# замером: опрос №1 1.8 c, №2-3 по 6.7 c, спящие sleep с fd на ttyUSB2.
	sms_tool -d "$_aq_p" at "$_aq_c" > "$_aq_o" 2>/dev/null 8>&- 9>&- &
	_aq_pid=$!
	( exec >/dev/null 2>&1 8>&- 9>&-; sleep "$_aq_t"; kill "$_aq_pid" 2>/dev/null ) </dev/null & _aq_w=$!
	wait "$_aq_pid" 2>/dev/null
	kill "$_aq_w" 2>/dev/null; wait "$_aq_w" 2>/dev/null

	[ "$_aq_mine" = 1 ] && at_unlock 2>/dev/null
	tr -d '\r' < "$_aq_o" 2>/dev/null
	rm -f "$_aq_o"
	return 0
}

at_field() {
	at_query "$1" "$2" | sed -n "s/^+$3: *//p" | head -1
}
