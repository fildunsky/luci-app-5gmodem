#
# ЗАЧЕМ. Две операции повторялись по всему коду и уже начали расходиться:
#
# 1) Имя секции модема из USB-пути - 22 копии в 12 файлах.
# 2) Поиск секции по имени интерфейса - ДЕВЯТЬ вариантов одной регулярки,
#    отличавшихся тремя способами сразу:
#      m_[^.]*        против  m_[A-Za-z0-9_]*
#      '\?$1'\?       против  '$1'        (терпит вывод uci без кавычек или нет)
#      с head -1      против  без
#    Расхождение не косметическое: строгие варианты не находят секцию там, где
#    находят мягкие, и поведение зависит от того, какой файл спросил.
#
# Держим по одной реализации: расходиться станет нечему.

# --- SERIAL ИЗ SYSFS: ТРЕТИЙ ПРИЗНАК ЛИЧНОСТИ МОДЕМА -------------------------
#
# ЗАЧЕМ. Личность модема мы храним по IMEI, а IMEI надо ПРОЧИТАТЬ - командой в
# AT-порт. Пока он не прочитан (или прочитан не из того порта), два одинаковых
# модема неразличимы, и именно там случались подмены: у пользователя с двумя
# Thales MV31-W (05c6:90d5) оба профиля показывали один номер. Serial доступен
# СРАЗУ, из sysfs, без AT-порта, без очереди к нему и независимо от того,
# отвечает ли модем вообще - то есть отвечает на вопрос «тот же это аппарат?»
# в тот самый момент, когда все остальные способы ещё молчат.
#
# НО КЛЮЧОМ ОН БЫТЬ НЕ МОЖЕТ. Замер по реальному железу (стенд + собранные
# диагностики пользователей):
#
#   05c6:90d5  d383e5d6 / 1afc7c2d   два MV31-W различимы
#   05c6:9025  c7f2a76c / 72f642f6   два T99W175 различимы
#   05c6:90d6  2e6172c9              уникален
#   05c6:9063  81e6896d              уникален
#   0489:e0b5  0123456789ABCDEF      ЗАГЛУШКА на всю партию
#   413c:81d7  0123456789ABCDEF      ЗАГЛУШКА
#   0e8d:7127  (пусто)               НЕТ ВООБЩЕ (FM350, проверено на стенде)
#
# То есть serial уникален ровно там, где живёт проблема «два одинаковых модема»,
# но у части железа его нет или он одинаков у всей партии. Заглушка ХУЖЕ
# отсутствия: по ней два разных модема слились бы в один. Поэтому - фильтр.
#
# serial_valid <строка> - годится ли как признак личности
serial_valid() {
	_sv="$1"
	[ -n "$_sv" ] || return 1
	case "$_sv" in
		-|0|none|None|N/A) return 1 ;;
		# Заводские заглушки, встреченные живьём.
		0123456789ABCDEF|0123456789abcdef) return 1 ;;
		*[!A-Za-z0-9._:-]*) return 1 ;;
	esac
	# Слишком короткий - не идентификатор.
	[ "${#_sv}" -ge 6 ] || return 1
	# Один символ, повторённый целиком (000000, FFFFFFFF): тоже заглушка.
	_sv1=$(printf '%s' "$_sv" | cut -c1)
	case "$_sv" in
		*[!"$_sv1"]*) ;;
		*) return 1 ;;
	esac
	return 0
}

# serial_of <путь к usb-устройству в sysfs> -> годный serial или пусто
#
# ВТОРАЯ ПРОВЕРКА - РАНТАЙМОВАЯ, И ОНА ВАЖНЕЕ СПИСКА ЗАГЛУШЕК: если тот же serial
# СЕЙЧАС рапортуют два устройства на шине, он партийный, каким бы правдоподобным
# ни выглядел. Так мы ловим заглушки, которых нет в списке выше, не заводя
# картотеку вендоров.
serial_of() {
	_so_s=$(cat "$1/serial" 2>/dev/null | tr -d '\r\n')
	serial_valid "$_so_s" || { printf ''; return 1; }
	_so_n=0
	for _so_d in /sys/bus/usb/devices/*; do
		[ -f "$_so_d/serial" ] || continue
		[ "$(cat "$_so_d/serial" 2>/dev/null | tr -d '\r\n')" = "$_so_s" ] && _so_n=$((_so_n + 1))
	done
	[ "$_so_n" = 1 ] || { printf ''; return 1; }
	printf '%s' "$_so_s"
}

# ЧУЖИЕ НЕЗАКОММИЧЕННЫЕ ПРАВКИ UCI - ЗАПИСАТЬ В ЖУРНАЛ ДО НАШЕГО КОММИТА.
#
# ЗАЧЕМ. Дельты uci лежат в ОБЩЕМ /tmp/.uci до коммита, и `uci commit network`
# коммитит ВСЁ скопом - и своё, и чужое. Кнопка «Сохранить» (без «Применить») в
# LuCI, скрипт, умерший между set и commit, ручной uci set в консоли - всё это
# оставляет мину, которую взводит первый же чужой коммит. Наш код коммитит
# network из netpri (переключение приоритета) и mkiface - то есть детонатором
# можем оказаться мы, а взрыв (например, смена lan.ipaddr) выглядит как наш баг.
# Живой случай 30.07: wwGate, «пинга до роутера нет, инет есть» - точный симптом
# слетевшего lan-адреса; кто его менял - улик не осталось.
#
# Отменять чужое нельзя (это может быть настоящая незасейвленная работа
# пользователя) - но МОЛЧА закоммитить тоже нельзя. Пишем в журнал, ЧТО именно
# ждало в очереди: если после нашего коммита что-то сломается, в логе будет
# видно, чья это правка была.
# note_foreign_uci <конфиг> <метка вызывающего>
note_foreign_uci() {
	_nf=$(uci changes "$1" 2>/dev/null | head -20)
	[ -n "$_nf" ] || return 0
	logger -t 5gmodem "$2: в очереди uci ЧУЖИЕ правки $1 - коммичу вместе с ними: $(printf '%s' "$_nf" | tr '\n' '; ' | head -c 400)"
}

# КЛЮЧ ФАЙЛОВ-СНИМКОВ МЕТРИК по USB-пути.
#
# Формула повторена буква в букву из 5gmodem.sh, включая `printf '%s\n'`: перевод
# строки тоже попадает под `tr` и даёт ЗАВЕРШАЮЩЕЕ подчёркивание, поэтому файлы
# зовутся `5gmodem_metrics_1_1_3_.json`, а не `..._1_1_3.json`. Я на этом уже
# ошибся: написал ключ «как логично» и подогрев искал несуществующий файл, считая
# снимок отсутствующим всегда. Держим одну реализацию - расходиться станет нечему.
# Менять формат НЕЛЬЗЯ: по нему названы уже лежащие снимки.
snap_key() {   # $1 - usb-путь
	_sk=$(printf '%s\n' "$1" | tr -c 'A-Za-z0-9' '_')
	[ -n "$_sk" ] || _sk="none"
	printf '%s' "$_sk"
}

# Секунды аптайма БЕЗ подпроцесса. Раньше повсюду звался `cut -d. -f1
# /proc/uptime` - по замеру это 21 спавн на ОДИН опрос метрик (циклы, штампы
# кэшей). read из /proc + подстановка делают то же ядерными средствами.
uptime_s() {
	read -r _us _ < /proc/uptime
	printf '%s\n' "${_us%%.*}"
}

# secname <usb-путь> -> имя секции (m_1_1_3)
# Секции uci допускают только [A-Za-z0-9_], а в пути есть точки и дефисы.
# МЕМО НА ПОСЛЕДНИЙ ОТВЕТ: за один опрос метрик secname спрашивают ~10 раз и
# почти всегда ПРО ОДИН И ТОТ ЖЕ путь (_POLL_AM) - это 10 спавнов sed за то,
# что уже посчитано. Кэш из одной пары «вход-выход» снимает их все.
_SN_IN=""; _SN_OUT=""
secname() {
	if [ -n "$1" ] && [ "$1" = "$_SN_IN" ]; then
		printf '%s\n' "$_SN_OUT"
		return
	fi
	_SN_IN="$1"
	_SN_OUT="m_$(echo "$1" | sed 's/[^A-Za-z0-9]/_/g')"
	printf '%s\n' "$_SN_OUT"
}

# СНИМОК КОНФИГА ДЛЯ ЧИТАЮЩИХ ЦИКЛОВ.
#
# ЗАЧЕМ. `uci show 5gmodem` - это отдельный процесс, и по нему работает
# sec_for_iface, которую в цикле по интерфейсам зовут по цепочке is_modem ->
# iface_type -> modem_path_for -> model_for. Замер netpri.sh list на стенде:
# 690 мс на вызов и ~145 подпроцессов, из них 70 - uci. А зовётся он КАЖДЫЕ 5 c,
# пока открыта страница метрик, то есть роутер тратит на список аплинков больше
# полусекунды из каждых пяти.
#
# ПРАВИЛО: снимок берёт только тот, кто ТОЛЬКО ЧИТАЕТ и живёт недолго (netpri
# list). Писателям он не нужен и опасен: после `uci set` снимок устареет молча.
# Поэтому это не автоматический кэш, а явное включение - и явный сброс.
_UCI_NL='
'
# ЧТЕНИЕ ЗНАЧЕНИЯ ИЗ СНИМКА - БЕЗ ЕДИНОГО ПОДПРОЦЕССА.
#
# Подстановки ${x#...} и ${x%...} - это встроенные операции оболочки, то есть
# поиск идёт в C и не стоит ни fork, ни exec. Именно этим снимок и полезен: иначе
# он экономил бы один `uci show`, но каждое чтение всё равно спавнило бы `uci get`
# или `sed`.
#
# РАЗДЕЛИТЕЛЬ - ПЕРЕВОД СТРОКИ, и это не деталь: `uci show` печатает по одной
# опции на строку, поэтому ЗНАЧЕНИЕ содержать перевод строки не может, и
# сопоставление не может ошибиться на данных пользователя. Любой другой
# разделитель (пробел, вертикальная черта) в значении встретиться мог бы.
#
# eval здесь НЕ используется намеренно: превращать конфиг в переменные оболочки
# (`eval $(uci show ... | sed ...)`) - это исполнение пользовательских данных,
# ровно тот приём, который в аудите помечен к удалению из listmodems.sh.
_uci_snap_get() {   # $1 - снимок (с ведущим переводом строки), $2 - полный ключ
	case "$1" in
		*"$_UCI_NL$2="*)
			_usv="${1#*"$_UCI_NL$2="}"
			_usv="${_usv%%"$_UCI_NL"*}"
			# uci show заключает значение в одиночные кавычки
			_usv="${_usv#\'}"
			printf '%s' "${_usv%\'}" ;;
	esac
}

_UCI5G_SNAP=""
uci5g_snapshot() { _UCI5G_SNAP="$_UCI_NL$(uci -q show 5gmodem 2>/dev/null)"; }
uci5g_snapshot_drop() { _UCI5G_SNAP=""; }
_uci5g_dump() {
	[ -n "$_UCI5G_SNAP" ] && { printf '%s\n' "$_UCI5G_SNAP"; return; }
	uci -q show 5gmodem 2>/dev/null
}
# uci5g_get <секция> <опция> - значение из снимка, иначе обычным uci.
uci5g_get() {
	if [ -n "$_UCI5G_SNAP" ]; then
		_uci_snap_get "$_UCI5G_SNAP" "5gmodem.$1.$2"
		return
	fi
	uci -q get "5gmodem.$1.$2" 2>/dev/null
}

_UCINET_SNAP=""
ucinet_snapshot() { _UCINET_SNAP="$_UCI_NL$(uci -q show network 2>/dev/null)"; }
ucinet_snapshot_drop() { _UCINET_SNAP=""; }
# ucinet_get <интерфейс> <опция> - значение из снимка, иначе обычным uci.
ucinet_get() {
	if [ -n "$_UCINET_SNAP" ]; then
		_uci_snap_get "$_UCINET_SNAP" "network.$1.$2"
		return
	fi
	uci -q get "network.$1.$2" 2>/dev/null
}
# Существует ли секция интерфейса (замена `uci -q get network.$1 >/dev/null`).
ucinet_has() {
	if [ -n "$_UCINET_SNAP" ]; then
		case "$_UCINET_SNAP" in
			*"$_UCI_NL"network."$1"=*) return 0 ;;
			*) return 1 ;;
		esac
	fi
	uci -q get "network.$1" >/dev/null 2>&1
}

# sec_for_iface <имя интерфейса> -> имя секции модема, который им владеет
# Кавычки вокруг значения НЕОБЯЗАТЕЛЬНЫ: разные версии uci выводят по-разному,
# и строгий вариант молча не находил секцию.
sec_for_iface() {
	[ -n "$1" ] || return 1
	_uci5g_dump \
		| sed -n "s/^5gmodem\.\(m_[^.]*\)\.network='\?$1'\?\$/\1/p" \
		| head -1
}

# ВЛАДЕНИЕ ИНТЕРФЕЙСОМ - ПО ЖЕЛЕЗУ (IMEI), А НЕ ПО ПОРТУ.
#
# Штамп network.<if>.modem_path (usb-путь) НЕ различал два РАЗНЫХ модема в одном
# разъёме: путь у них один, и при подмене интерфейс прежнего сносился - у
# пользователя с двумя модемами по очереди в одном порту (issue #2) переподключение
# каждый раз шло через пересоздание. IMEI - настоящая личность железа, он и есть
# первичный ключ владения. modem_path продолжаем писать: он нужен для диагностики
# и как запасной признак для старых конфигов и модемов без читаемого IMEI.

# IMEI из секции модема по usb-пути (пусто, если неизвестен).
imei_for_path() {   # $1 - usb-путь
	[ -n "$1" ] || return 1
	uci -q get "5gmodem.$(secname "$1").imei"
}

# Интерфейс, принадлежащий модему с таким IMEI (пусто - такого нет).
iface_for_imei() {   # $1 - imei
	[ -n "$1" ] || return 1
	uci -q show network 2>/dev/null \
		| sed -n "s/^network\.\([^.]*\)\.modem_imei='\?$1'\?\$/\1/p" \
		| head -1
}

# Принадлежит ли интерфейс $1 модему (путь $2, IMEI $3)?
# IMEI-first: есть штамп IMEI и знаем IMEI модема - решает ТОЛЬКО он (два модема
# в одном порту различаются). Иначе - прежнее поведение по modem_path. Штампа нет
# вовсе = интерфейс из старых версий, считаем своим (миграция проставит).
iface_owned_by() {   # $1 - iface, $2 - usb-путь, $3 - imei (может быть пуст)
	[ -n "$1" ] || return 1
	_ow_i=$(uci -q get "network.$1.modem_imei")
	if [ -n "$_ow_i" ]; then
		# Интерфейс ЗАКРЕПЛЁН за конкретным железом. Совпал IMEI - наш. Не совпал
		# ИЛИ мы своего IMEI не знаем - ЧУЖОЙ: по пути его забирать нельзя, там
		# может ждать возвращения вытесненный из этого же разъёма модем.
		[ -n "$3" ] && [ "$_ow_i" = "$3" ] || return 1
		# IMEI СОВПАЛ - но он не всегда уникален. У пользователя с четырьмя
		# модемами два одинаковых Thales MV31-W отдают ОДИН И ТОТ ЖЕ IMEI
		# (клонированный на восстановленных модулях): по IMEI каждый из них
		# считал бы своим и чужой интерфейс, и первый же resolve перенастроил бы
		# соседу device/APN. Если штамп пути указывает на ДРУГОЕ устройство,
		# которое СЕЙЧАС на шине, - IMEI неуникален, решаем по пути.
		_ow_p=$(uci -q get "network.$1.modem_path")
		if [ -n "$_ow_p" ] && [ "$_ow_p" != "$2" ] && [ -e "/sys/bus/usb/devices/$_ow_p" ]; then
			return 1
		fi
		return 0
	fi
	_ow_p=$(uci -q get "network.$1.modem_path")
	[ -n "$_ow_p" ] || return 0
	[ "$_ow_p" = "$2" ]
}

# Проставить ОБА штампа владельца. IMEI берём из секции, если не передан явно.
stamp_iface_owner() {   # $1 - iface, $2 - usb-путь, [$3 - imei]
	[ -n "$1" ] && [ -n "$2" ] || return 0
	note_foreign_uci network "stamp_iface_owner"
	uci -q set "network.$1.modem_path=$2"
	_si_i="$3"
	[ -n "$_si_i" ] || _si_i=$(imei_for_path "$2")
	[ -n "$_si_i" ] && uci -q set "network.$1.modem_imei=$_si_i"
	uci -q commit network
}

# Путь активного модема (короткая обёртка - зовётся почти везде).
active_path() {
	# Через снимок, если он взят (реестр печатает признак active в КАЖДОЙ записи,
	# то есть на трёх модемах спрашивал бы активный трижды); без снимка - как раньше.
	uci5g_get "@5gmodem[0]" active_modem
}

# Секция активного модема.
active_sec() {
	_ap=$(active_path)
	[ -n "$_ap" ] || return 1
	secname "$_ap"
}

# Брендовое имя оператора для РФ-MVNO по IMSI.
#
# ЗАЧЕМ. Сеть (и web-API HiLink) отдаёт имя ХОСТ-оператора: Т-Мобайл виден как
# Tele2, потому что физически работает на его сети. Настоящий бренд симки прячется
# в её IMSI (свой MCC-MNC). У AT-модемов это чинит чтение EF_SPN с SIM, но HiLink
# к SPN доступа не даёт, да и SPN у части симок - мусор ("T0"). Поэтому держим
# ВЫВЕРЕННЫЕ РУКАМИ соответствия в apn.list строками opname:<mcc-mnc>:<бренд> и
# применяем их в обоих путях (AT и HiLink) - имя тогда единое.
#
# ВЫВЕРЕННОЕ НАПИСАНИЕ ИМЕНИ ОПЕРАТОРА ПО ЧИСЛОВОМУ PLMN.
#
# ЗАЧЕМ. Модем отдаёт имя СЕТИ так, как его прописал оператор в эфире: с кодом
# страны и в своём регистре («MegaFon RUS», «Tele2 RU», «beeline»). В mccmnc.dat
# лежит выверенное написание («Megafon», «Tele2», «Beeline»), и основной опрос
# уже предпочитает его: если имя с SIM совпадает с базой без учёта регистра,
# берётся вариант из базы (см. SPN_NAME в 5gmodem.sh - там же пример «beeline» ->
# «Beeline»).
#
# А проба netpri этот последний шаг не делала и писала в кэш сырое имя. Из-за
# этого один и тот же модем подписан по-разному в двух местах страницы:
# в «Приоритете интернета» - «MegaFon RUS», в карточке - «Megafon». Разница видна
# как мигание: у НЕАКТИВНОГО модема файла от основного опроса нет вовсе, netpri
# показывает своё имя, а через пару секунд после перехода на карточку модем
# становится активным, опрос пишет файл - и подпись меняется на глазах.
#
# MVNO НЕ ТРОГАЕМ: если сырое имя с базой не совпадает (SIM «T-Mobile» на сети
# «Tele2»), оставляем как есть - различить бренд абонента может только основной
# опрос, он читает SPN с самой карты.
# opname_pretty <plmn> <сырое имя>
opname_pretty() {
	_op_num=$(printf '%s' "$1" | tr -cd '0-9')
	_op_raw=$(printf '%s' "$2" | sed 's/^ *//;s/ *$//')
	[ -n "$_op_num" ] || { printf '%s' "$_op_raw"; return; }
	# tr -d '\r' ОБЯЗАТЕЛЕН: mccmnc.dat в формате CRLF, и возврат каретки уезжает
	# в конец поля. Без него сравнение с сырым именем не совпадает НИКОГДА
	# («megafon\r» против «megafon rus»), то есть функция молча ничего не делает -
	# именно так она и не работала при первом прогоне. Тот же капкан уже описан в
	# hilink.sh.
	_op_db=$(awk -F';' '/^'"$_op_num"';/ {print $3}' /usr/share/5gmodem/mccmnc.dat 2>/dev/null \
		| head -1 | tr -d '\r' | sed 's/^ *//;s/ *$//')
	[ -n "$_op_db" ] || { printf '%s' "$_op_raw"; return; }
	[ -n "$_op_raw" ] || { printf '%s' "$_op_db"; return; }
	_op_l=$(printf '%s' "$_op_raw" | tr 'A-Z' 'a-z')
	_op_dl=$(printf '%s' "$_op_db" | tr 'A-Z' 'a-z')
	# Совпало целиком или до странового хвоста («megafon rus» -> «megafon»).
	case "$_op_l" in
		"$_op_dl") printf '%s' "$_op_db"; return ;;
		"$_op_dl "*) printf '%s' "$_op_db"; return ;;
	esac
	printf '%s' "$_op_raw"
}

# Пусто (return 1) - оверрайда нет, имя оставляем как отдала сеть.
# opname_brand <imsi>
opname_brand() {
	_ob_imsi=$(echo "$1" | tr -cd '0-9')
	[ "${#_ob_imsi}" -ge 5 ] || return 1
	_ob_f="/usr/share/5gmodem/apn.list"
	[ -f "$_ob_f" ] || return 1
	# Кандидаты PLMN: MNC в 3 и 2 цифры (как в apn_pick). Более специфичный -
	# 3-значный - пробуем первым.
	for _ob_len in 6 5; do
		_ob_p=$(printf '%s' "$_ob_imsi" | cut -c1-"$_ob_len")
		[ "${#_ob_p}" -eq "$_ob_len" ] || continue
		_ob_key="${_ob_p%${_ob_p#???}}-${_ob_p#???}"
		while IFS=: read -r _t _pat _val; do
			[ "$_t" = "opname" ] || continue
			[ "$_pat" = "$_ob_key" ] && [ -n "$_val" ] && { echo "$_val"; return 0; }
		done < "$_ob_f"
	done
	return 1
}

# ==== ИМЯ МОДЕЛИ: валидация ответа AT+CGMM ====
# Переехало из 5gmodem.sh: модель теперь заполняет не только основной опрос
# (он идёт лишь по АКТИВНОМУ модему), но и resolve - остальным присутствующим,
# иначе неактивный модем оставался в списке безымянным до переключения на него.
# ВАЛИДАЦИЯ ОБЯЗАТЕЛЬНА. AT-порт делят опрос метрик, simslot.sh и esim.sh; при
# столкновении ответ одной команды прилетает на чтение другой. Так в секцию уже
# попадало ЭХО ЧУЖОЙ КОМАНДЫ - "AT+SIMTYPE?" (её шлёт simslot.sh) - и висело там
# как имя модема: в интерфейсе показывалось «SimCom AT+SIMTYPE?». Разовая
# коллизия становилась ПОСТОЯННОЙ, потому что мы её сохраняли.
# Поэтому принимаем только правдоподобное имя: не эхо команды (AT.../+CME.../?),
# не ошибка, разумной длины.
_model_sane() {
	case "$1" in
		AT+*|AT^*|AT$*|at+*|at^*) return 1 ;;   # эхо AT-команды
		# эхо AT-команды и в «пробельной» форме: L850 с ATE1 при коллизии на общем
		# AT-порту отдавал "AT  4"/"AT+GTDUALSIM?" - раньше "AT " (пробел) проскакивал
		# мимо шаблонов выше и оседал как имя модема НАВСЕГДА.
		AT|AT[\ 0-9]*|at|at[\ 0-9]*) return 1 ;;
		*ERROR*|*error*) return 1 ;;
		*'?'*|*'='*|*'"'*) return 1 ;;          # синтаксис команды, не имя
		# ОТВЕТЫ чужих команд. Первая версия ловила только ЭХО (AT+...), и мусор
		# вида "Telit #BND: 0,18,A7E0BB0F38DF,42" или "Telit +CSQ: 23,4"
		# проскакивал в конфиг НАВСЕГДА (проверено). У AT-ответа опознаваемая
		# форма: префикс # или + и двоеточие после кода.
		*'#'*|*': '*) return 1 ;;
		+[A-Z]*|*' +'[A-Z]*) return 1 ;;
		'') return 1 ;;
	esac
	[ "${#1}" -ge 3 ] && [ "${#1}" -le 40 ] || return 1
	case "$1" in *[A-Za-z]*) return 0 ;; esac   # хоть одна буква
	return 1
}
# ВЕНДОР В МОДЕЛИ ДОЛЖЕН СОВПАДАТЬ С ВЕНДОРОМ ПО vid:pid.
#
# _model_sane проверяет, ПОХОЖА ли строка на модель, но не ЧЬЯ она - и этого
# оказалось мало. Живой случай: воткнули Huawei, опрос по чужому порту прочитал
# "Fibocom FM350-GL" и записал в секцию Huawei (12d1). Строка была совершенно
# правдоподобной, поэтому проверка на «похоже на модель» её пропустила.
#
# Судим ТОЛЬКО когда уверены: у vid есть однозначный вендор И в строке назван
# ДРУГОЙ известный вендор. Qualcomm-овый 05c6 не трогаем - под ним ходят модемы
# разных производителей, и там расхождение имени с vid нормально.
_vendor_by_vid() {
	case "$1" in
		0e8d:*|2cb7:*) echo fibocom ;;
		12d1:*)        echo huawei ;;
		1bc7:*)        echo telit ;;
		2c7c:*)        echo quectel ;;
		19d2:*)        echo zte ;;
		1e2d:00b7) ;;  # НЕ Cinterion: 1e2d:00b7 - это debug/QMI-композиция Qualcomm
		               # SDX55 (Foxconn T99W175 / Compal RXM-G1 / Dell DW5930e / Thales
		               # MV31-W), одолжившая vid Cinterion. Вернуть "cinterion" здесь -
		               # значит отбраковать наше имя «Compal RXM-G1» (в reject-списке есть
		               # "compal") и оставить сырой SG500M2-X. Пусто = не судим (ID общий).
		1e2d:*)        echo cinterion ;;
		2dee:*)        echo meiglink ;;
		1e0e:*)        echo simcom ;;
	esac
}
_model_vendor_ok() {   # $1 - модель, $2 - vidpid
	_mv_want=$(_vendor_by_vid "$2")
	[ -n "$_mv_want" ] || return 0            # вендор по vid неизвестен - не судим
	_mv_low=$(printf '%s' "$1" | tr 'A-Z' 'a-z')
	case "$_mv_low" in *"$_mv_want"*) return 0 ;; esac
	# Имя вендора в строке вообще не названо - тоже не судим: многие модемы
	# отдают голую модель ("RM520N-GL", "E3372"), и это нормально.
	#
	# compal/foxconn/thales/dell - НАШИ синтезированные дружелюбные имена (см.
	# профиль modem/usb/05c690d6: MODEL="Compal RXM-G1"). Сам Qualcomm-модем ходит
	# под 05c6, который выше (return 0) не судим, так что своё имя он сохранит. Но
	# если такое имя по ошибке протекло в секцию модема ДРУГОГО вендора (живой
	# баг: "Compal RXM-G1" осел в секции Fibocom 0e8d после свопа и FM350 стал
	# показываться вторым «Compal» в табах) - вот это ловим и не пишем/не показываем.
	for _mv_other in fibocom huawei telit quectel zte cinterion meiglink simcom \
	                 compal foxconn thales dell; do
		[ "$_mv_other" = "$_mv_want" ] && continue
		case "$_mv_low" in *"$_mv_other"*) return 1 ;; esac
	done
	return 0
}

# sig_weighted <rsrp> <sinr> <rsrq> -> процент качества сигнала (0..100) или пусто
#
# ЕДИНАЯ реализация взвешенной оценки. Была скопирована в профиль FM350 и в
# центральный fallback 5gmodem.sh - копии по определению расходятся (ровно этим
# в 1e2d00b7 объяснялось пропадавшее «тепловое состояние»). Держим одну.
#
# RSRP один плохо отражает «толщину» канала: при сильном RSRP, но низком SINR
# (край соты/интерференция) голая линейка рисует 80%, а связь ели тянется.
# Веса и шкалы выверены на живом FM350 (3GPP TS 36.133):
#   RSRP  -130..-80 дБм -> 0..100 (вес .5)
#   SINR   -10..20  дБ  -> 0..100 (вес .3)
#   RSRQ   -20..-3   дБ  -> 0..100 (вес .2)
# RSRP обязателен; отсутствующие SINR/RSRQ выпадают из среднего (веса
# перенормируются), поэтому «только RSRP» тоже даёт результат.
sig_weighted() {
	case "$1" in -[0-9]*|[0-9]*) ;; *) return 0 ;; esac   # без RSRP считать нечего
	awk -v rp="$1" -v si="$2" -v rq="$3" 'BEGIN{
		acc = 0; w = 0;
		p = (rp + 130) * 2;                                        # -130 -> 0, -80 -> 100
		if (p < 0) p = 0; if (p > 100) p = 100; acc += 0.5 * p; w += 0.5;
		if (si ~ /^-?[0-9]/) { p = (si + 10) * 100 / 30;           # -10 -> 0, 20 -> 100
			if (p < 0) p = 0; if (p > 100) p = 100; acc += 0.3 * p; w += 0.3; }
		if (rq ~ /^-?[0-9]/) { p = (rq + 20) * 100 / 17;           # -20 -> 0, -3 -> 100
			if (p < 0) p = 0; if (p > 100) p = 100; acc += 0.2 * p; w += 0.2; }
		if (w > 0) printf "%d", acc / w + 0.5;
	}' 2>/dev/null
}

# USB-путь модема, которому принадлежит tty-порт: /dev/ttyUSB5 -> 1-1.3.
# Жила в detect.sh; понадобилась и опросу метрик, чтобы сверять, ЧЕЙ порт он
# держит в руках, - поэтому переехала сюда. Пусто = определить не удалось.
tty_usbpath() {
	# ПУСТОЙ ВХОД - СРАЗУ ОТКАЗ. Без этой строки basename "" давал пустоту, путь
	# схлопывался в /sys/class/tty/, а разбор ниже возвращал буквальное «tty».
	# Последствия были неочевидные и вредные: гейт штампа IMEI сравнивал «tty» с
	# путём модема, не совпадало - IMEI не записывался, и в лог каждые пять секунд
	# уходило «порт  принадлежит tty». Хуже того, ключ кэша статики у ВСЕХ модемов
	# без AT-порта становился одинаковым («tty»), то есть данные разных модемов
	# складывались в один файл - ровно та беда, ради которой ключ и вводился.
	[ -n "$1" ] || return 1
	_tp=$(readlink -f "/sys/class/tty/$(basename "$1")/device" 2>/dev/null) || return 1
	[ -n "$_tp" ] || return 1
	_tp=${_tp%/*}
	_tp=${_tp##*/}
	echo "${_tp%%:*}"
}

