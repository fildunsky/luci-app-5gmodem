# Общие помощники. Подключается через "." (не запускается).
#
# ЗАЧЕМ. Две операции повторялись по всему коду и уже начали расходиться:
#
# 1) Имя секции модема из USB-пути - 22 копии в 12 файлах.
# 2) Поиск секции по имени интерфейса - ДЕВЯТЬ вариантов одной регулярки,
#    отличавшихся тремя способами сразу:
#      m_[^.]*        против  m_[A-Za-z0-9_]*
#      '\?$1'\?       против  '$1'        (терпит вывод uci без кавычек или нет)
#      с head -1      против  без
#    Расхождение не косметическое: строгие варианты не находят секцию там, где
#    находят мягкие, и поведение зависит от того, какой файл спросил.
#
# Держим по одной реализации: расходиться станет нечему.

# secname <usb-путь> -> имя секции (m_1_1_3)
# Секции uci допускают только [A-Za-z0-9_], а в пути есть точки и дефисы.
secname() {
	echo "m_$(echo "$1" | sed 's/[^A-Za-z0-9]/_/g')"
}

# sec_for_iface <имя интерфейса> -> имя секции модема, который им владеет
# Кавычки вокруг значения НЕОБЯЗАТЕЛЬНЫ: разные версии uci выводят по-разному,
# и строгий вариант молча не находил секцию.
sec_for_iface() {
	[ -n "$1" ] || return 1
	uci -q show 5gmodem 2>/dev/null \
		| sed -n "s/^5gmodem\.\(m_[^.]*\)\.network='\?$1'\?\$/\1/p" \
		| head -1
}

# Путь активного модема (короткая обёртка - зовётся почти везде).
active_path() {
	uci -q get 5gmodem.@5gmodem[0].active_modem 2>/dev/null
}

# Секция активного модема.
active_sec() {
	_ap=$(active_path)
	[ -n "$_ap" ] || return 1
	secname "$_ap"
}

# Брендовое имя оператора для РФ-MVNO по IMSI.
#
# ЗАЧЕМ. Сеть (и web-API HiLink) отдаёт имя ХОСТ-оператора: Т-Мобайл виден как
# Tele2, потому что физически работает на его сети. Настоящий бренд симки прячется
# в её IMSI (свой MCC-MNC). У AT-модемов это чинит чтение EF_SPN с SIM, но HiLink
# к SPN доступа не даёт, да и SPN у части симок - мусор ("T0"). Поэтому держим
# ВЫВЕРЕННЫЕ РУКАМИ соответствия в apn.list строками opname:<mcc-mnc>:<бренд> и
# применяем их в обоих путях (AT и HiLink) - имя тогда единое.
#
# Пусто (return 1) - оверрайда нет, имя оставляем как отдала сеть.
# opname_brand <imsi>
opname_brand() {
	_ob_imsi=$(echo "$1" | tr -cd '0-9')
	[ "${#_ob_imsi}" -ge 5 ] || return 1
	_ob_f="/usr/share/5gmodem/apn.list"
	[ -f "$_ob_f" ] || return 1
	# Кандидаты PLMN: MNC в 3 и 2 цифры (как в apn_pick). Более специфичный -
	# 3-значный - пробуем первым.
	for _ob_len in 6 5; do
		_ob_p=$(printf '%s' "$_ob_imsi" | cut -c1-"$_ob_len")
		[ "${#_ob_p}" -eq "$_ob_len" ] || continue
		_ob_key="${_ob_p%${_ob_p#???}}-${_ob_p#???}"
		while IFS=: read -r _t _pat _val; do
			[ "$_t" = "opname" ] || continue
			[ "$_pat" = "$_ob_key" ] && [ -n "$_val" ] && { echo "$_val"; return 0; }
		done < "$_ob_f"
	done
	return 1
}
