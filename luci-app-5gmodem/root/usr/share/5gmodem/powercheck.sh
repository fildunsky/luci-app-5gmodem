#!/bin/sh
#
# Признаки нехватки питания на USB-модемах.
#
# ЗАЧЕМ. Модем, которому не хватает тока, не пропадает целиком - он перечисляется
# ЧАСТИЧНО, и это выглядит как программная поломка. Наблюдалось дважды за день на
# одном стенде: FM350 держал AT-канал, но радио было мертво (CSQ 99,99, сети нет),
# а Compal поднял только AT-порты, тогда как его CDC-интерфейс (MBIM) остался без
# драйвера - без cdc-wdm ModemManager честно отвечал "модемов не найдено".
# В обоих случаях интерфейс показывал бы просто "нет метрик", и причина была бы
# не видна вовсе; на поиск ушло полдня.
#
# Два модема по 896 мА в заявке дают почти 1.8 А - шине столько обычно взять
# неоткуда, и ядро жалуется "device descriptor read/8, error -71" и
# "Cannot enable. Maybe the USB cable is bad?" (про кабель - его догадка).
#
# Печатает JSON. Ничего не меняет: только смотрит.

RES=/usr/share/5gmodem

# Пути модемов берём у того же источника, что и весь остальной интерфейс.
PATHS=$("$RES/listmodems.sh" 2>/dev/null | jsonfilter -e '@[*].path' 2>/dev/null)

TOTAL=0
COUNT=0
SUSPECT=0
WHO=""

for P in $PATHS; do
	D="/sys/bus/usb/devices/$P"
	[ -d "$D" ] || continue
	COUNT=$((COUNT + 1))

	# Заявленное потребление. Формат "896mA".
	MA=$(cat "$D/bMaxPower" 2>/dev/null | tr -cd '0-9')
	[ -n "$MA" ] && TOTAL=$((TOTAL + MA))

	# ГЛАВНЫЙ признак: управляющий интерфейс CDC (класс 02) есть, а драйвера у
	# него нет. Именно так выглядит недокормленный модем: AT-порты поднялись,
	# а MBIM/QMI - нет. Интерфейсы класса ff (DIAG и т.п.) без драйвера
	# встречаются и в норме, поэтому их НЕ считаем за поломку.
	for I in "$D"/*:*; do
		[ -d "$I" ] || continue
		[ "$(cat "$I/bInterfaceClass" 2>/dev/null)" = "02" ] || continue
		if [ ! -e "$I/driver" ]; then
			SUSPECT=1
			WHO="$WHO $P"
		fi
	done
done

# Второй признак - жалобы ядра по шине, но ТОЛЬКО СВЕЖИЕ, по метке времени.
#
# Раньше здесь было `dmesg | tail -80` в расчёте на "последние события". Это
# неверно: tail отсчитывает СТРОКИ, а не время, и на спокойной шине ошибка
# получасовой давности остаётся в хвосте журнала сколь угодно долго. Из-за этого
# предупреждение висело на работающем модеме (наблюдалось: ошибка на 3482-й
# секунде, аптайм 3992 - разница больше восьми минут, а плашка горела).
#
# Метка dmesg - секунды с загрузки, то же основание, что у /proc/uptime.
NOW=$(cut -d. -f1 /proc/uptime 2>/dev/null)
KERR=0
if [ -n "$NOW" ]; then
	RECENT=$(dmesg 2>/dev/null \
		| grep -iE "error -71|Cannot enable|over-current" \
		| sed -n 's/^\[ *\([0-9]\{1,\}\)\..*/\1/p' \
		| tail -10 \
		| awk -v now="$NOW" 'now - $1 <= 120 { c++ } END { print c + 0 }')
	if [ "${RECENT:-0}" -gt 0 ]; then
		KERR=1
		SUSPECT=1
	fi
fi

printf '{"modems":%d,"total_ma":%d,"kernel_errors":%d,"suspect":%d,"paths":"%s"}\n' \
	"$COUNT" "$TOTAL" "$KERR" "$SUSPECT" "$(echo $WHO)"
