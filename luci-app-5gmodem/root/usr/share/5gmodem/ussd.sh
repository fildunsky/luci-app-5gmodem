#!/bin/sh
#
# USSD С АВТОМАТИЧЕСКИМ УХОДОМ В 3G.
#
# ЗАЧЕМ. USSD - услуга канала CS, а в LTE его нет. Модем пытается сделать CSFB
# сам, но это тупик: замерено на живом Telit LM960 (МегаФон) - 30 секунд, по
# дороге `+CREG: 3` (denied) и `+CREG: 2` (searching), в конце `+CUSD: 4` =
# «operation not supported», и ещё полминуты модем возвращается в сеть. Тот же
# код при модеме, УЖЕ зарегистрированном в 3G, отдаёт баланс за секунды.
#
# Поэтому уходим в 3G сами: это быстрее и, в отличие от CSFB, работает. Смена
# одного RAT применяется вживую, без перезапуска радио - 5 секунд в каждую
# сторону (Telit AT+WS46=22/31, FM350 AT+GTACT=1/20,6,3). Полный цикл вместе с
# запросом укладывается в ~20 секунд против 30 секунд неудачного CSFB.
#
# ПОЧЕМУ ФОНОМ. rpcd рвёт вызов на 30 секундах, а цикл к этой границе слишком
# близок. Поэтому работа идёт в отсоединённом процессе, а страница опрашивает
# состояние - заодно она может показывать, что происходит прямо сейчас.
#
# РЕЖИМ ВОЗВРАЩАЕМ ВСЕГДА. Оставить модем в 3G - это молча посадить человека на
# втрое меньшую скорость, поэтому восстановление стоит в trap: оно случится и
# при ошибке, и если запрос не дождался ответа.
#
# Usage: ussd.sh send <код> [порт]
#        ussd.sh status
#        ussd.sh cancel

RES=/usr/share/5gmodem
CFG=5gmodem
ST=/tmp/5gmodem_ussd.json
LOCK=/tmp/5gmodem_ussd.lock

. "$RES/lib.sh" 2>/dev/null
. "$RES/atlock.sh" 2>/dev/null

# Ждём регистрации не дольше этого. 25 с - с запасом к замеренным 5 с: столько
# уходит, когда сота 3G занята или её приходится искать.
REG_WAIT=25

_st() {   # $1 - status, $2 - stage, $3.. - хвост полей JSON
	_s="$1"; _g="$2"; shift 2
	printf '{"status":"%s","stage":"%s"%s}\n' "$_s" "$_g" "$*" > "$ST"
}

# ВСЁ ПРО МОДЕМ - ИЗ РЕЕСТРА. Здесь были три своих помощника: выбор порта,
# проверка «порт активного модема» и поиск владельца порта. Они делали то же, что
# registry.sh, только каждый по-своему - а именно из такого расхождения и вырос
# баг «USSD ушёл не тому модему» (30.07). Теперь связку собирает одно место.
#
# Реестр вдобавок делает то, чего мои функции не делали: сверяет сохранённый
# at_port со СПИСКОМ портов этого модема и отдаёт пустой, если настройка устарела.
_reg=""            # кэш ответа на время работы: состав за один запрос не меняется
_reg_for_port() {  # $1 - tty; заполняет _reg записью владельца порта
	_reg=$("$RES/registry.sh" port "$1" 2>/dev/null)
	[ -n "$_reg" ] && [ "$_reg" != "{}" ]
}
_reg_field() {     # $1 - имя поля записи в _reg
	printf '%s' "$_reg" | jsonfilter -e "@.$1" 2>/dev/null
}

# ПОРТ. Первым - из настройки страницы: по нему она определяет, ЧЕЙ модем
# показывает, и запрос обязан уйти туда же, куда смотрит пользователь. «Порт
# активного модема» я уже пробовал ставить первым - вышло хуже: активный и
# открытая вкладка расходятся, и запрос уходил не тому модему.
_port() {
	_p=$(uci -q get "$CFG.sms.ussdport")
	[ -n "$_p" ] && [ -c "$_p" ] && { echo "$_p"; return; }
	_p=$("$RES/registry.sh" active 2>/dev/null | jsonfilter -e '@.at_port' 2>/dev/null)
	[ -n "$_p" ] && [ -c "$_p" ] && { echo "$_p"; return; }
	"$RES/detect.sh" 2>/dev/null
}

# Технология из AT+COPS? - последнее поле. 7 = LTE, 11/13 = NR, остальное 2G/3G.
# Берём COPS, а не CREG: у CREG формат зависит от <n>, и при n=0 технологии в
# ответе нет вовсе (проверено: FM350 отдаёт «+CREG: 0,1»).
_act() {
	sms_tool -d "$1" at 'AT+COPS?' 2>/dev/null | tr -d '\r' \
		| sed -n 's/^+COPS:[[:space:]]*[0-9]*,[0-9]*,"[^"]*",\([0-9]*\).*/\1/p' | head -1
}

_is_cs() {   # технология даёт канал CS?
	case "$1" in
		''|7|11|13) return 1 ;;
		*) return 0 ;;
	esac
}

# id режима «3G» из профиля модема. Профили нумеруют режимы ПО-СВОЕМУ (у Telit
# 2:3G, у FM350 1:3G), поэтому ищем по МЕТКЕ, а не по номеру, и берём ровно
# «3G»: у FM350 рядом есть «3G+4G», а он нам не подходит - модем останется в LTE.
_mode_by_label() {   # $1 - метка ровно как в профиле
	"$RES/bands.sh" getsupportedmodes 2>/dev/null | tr ' ' '\n' | while IFS=: read -r _id _lb; do
		[ "$_lb" = "$1" ] && { echo "$_id"; break; }
	done
}
_mode_3g()   { _mode_by_label 3G ; }
# Куда возвращаться, если исходный режим прочитать не удалось. Оставить модем в
# 3G - худший исход из возможных: человек молча теряет скорость и не понимает,
# почему. Профили называют этот режим «Auto» (метка не переводится).
_mode_auto() { _mode_by_label Auto ; }

# ЧАСТО В НАЧАЛЕ, РЕДКО ПОТОМ. Прежний фиксированный шаг в пять секунд добавлял
# к циклу USSD до восьми секунд пустого ожидания: регистрация обычно приходит на
# пятой секунде, а замечалась только на следующем тике. Шаг в одну секунду на
# всём пределе тоже плох - это двадцать пять AT-запросов в порт вместо пяти, а
# лишний трафик в занятый порт мы уже проходили. Поэтому первые шесть секунд
# спрашиваем каждую секунду (там ответ и приходит), дальше - раз в три.
_wait_reg() {   # $1 - порт, $2 - хотим CS (1) или любую регистрацию (0)
	_w=0
	while [ "$_w" -lt "$REG_WAIT" ]; do
		if [ "$_w" -lt 6 ]; then _s=1; else _s=3; fi
		sleep "$_s"; _w=$((_w + _s))
		at_lock "$1" 10 2>/dev/null
		_a=$(_act "$1")
		at_unlock 2>/dev/null
		if [ "$2" = 1 ]; then
			_is_cs "$_a" && return 0
		else
			[ -n "$_a" ] && return 0
		fi
	done
	return 1
}

case "$1" in
status)
	[ -f "$ST" ] && cat "$ST" || echo '{"status":"idle","stage":""}'
	exit 0 ;;
cancel)
	_p=$(_port)
	[ -n "$_p" ] && { at_lock "$_p" 10 2>/dev/null; sms_tool -d "$_p" at 'AT+CUSD=2' >/dev/null 2>&1; at_unlock 2>/dev/null; }
	_st idle ""
	exit 0 ;;
send) : ;;
*) echo '{"error":"usage: send <code> | status | cancel"}'; exit 2 ;;
esac

CODE="$2"
# Код уходит В AT-КОМАНДУ, поэтому пропускаем только то, из чего USSD и состоит.
# Без этой проверки кавычка в поле закрывала бы строку и остаток ушёл бы модему
# как отдельная команда.
case "$CODE" in
	''|*[!0-9*#+]*) echo '{"error":"bad code"}'; exit 2 ;;
esac

PORT="${3:-$(_port)}"
[ -n "$PORT" ] && [ -c "$PORT" ] || { echo '{"error":"no port"}'; exit 2; }

# ОДИН ЗАПРОС ЗА РАЗ - через flock, а не чтением файла состояния.
#
# Прежняя проверка смотрела в $ST на «running» и на возраст файла, и между
# чтением и записью оставалось окно: два одновременных send успевали пройти оба,
# а дальше передёргивали бы RAT навстречу друг другу. flock закрывает окно
# целиком - ядро отдаёт замок ровно одному.
#
# Держим его на ВСЁ время работы: замок наследуется подоболочкой и снимается
# ядром, когда та завершится, - даже если её убьют. Поэтому дескриптор здесь не
# закрываем.
_ussd_busy() { echo '{"error":"busy"}'; exit 2; }
if command -v flock >/dev/null 2>&1; then
	exec 9>"$LOCK" 2>/dev/null || true
	flock -n 9 2>/dev/null || _ussd_busy
else
	# busybox без flock - остаётся прежняя, менее строгая проверка.
	if [ -f "$ST" ] && grep -q '"status":"running"' "$ST" 2>/dev/null; then
		_age=$(( $(date +%s) - $(date -r "$ST" +%s 2>/dev/null || echo 0) ))
		[ "$_age" -lt 120 ] && _ussd_busy
	fi
fi

# Нейтральная стадия: решение «уходить ли в 3G» принимается НИЖЕ, в фоне.
# Прежний stage=switching здесь означал «перевожу в 3G» ещё ДО решения - и
# страница показывала перевод даже там, где его не будет вовсе (галка снята,
# квирка нет; живой случай 31.07.2026 на Compal).
_st running starting
# ФД ОТВЯЗЫВАЕМ НА САМОЙ ПОДОБОЛОЧКЕ, а не внутри: иначе rpcd продолжает ждать
# наш вывод и упирается в свои 30 секунд (грабли, знакомые по collect.sh).
(
	MODE3G=$(_mode_3g)
	# Исходный режим читаем НАСТОЙЧИВО: именно его пустое значение однажды
	# оставило модем в 3G. Один повтор через паузу закрывает случай «порт был
	# занят опросом метрик».
	CUR=$("$RES/bands.sh" getmode 2>/dev/null)
	[ -n "$CUR" ] || { sleep 3; CUR=$("$RES/bands.sh" getmode 2>/dev/null); }
	at_lock "$PORT" 15 2>/dev/null
	ACT=$(_act "$PORT")
	at_unlock 2>/dev/null

	SWITCHED=0
	# Возврат режима - в trap: он обязан случиться при любом выходе.
	#
	# И ОН ПРОВЕРЯЕТСЯ. Первая версия молча оставила модем в 3G: исходный режим
	# не прочитался (порт был занят), в setmodelive ушла пустая строка, он ответил
	# «no mode» - и никто этого не заметил. Теперь есть и запасная цель, и сверка
	# результата с одной повторной попыткой.
	_restore() {
		[ "$SWITCHED" = 1 ] || return 0
		_tgt="$CUR"
		[ -n "$_tgt" ] || _tgt=$(_mode_auto)
		[ -n "$_tgt" ] || return 0
		"$RES/bands.sh" setmodelive "$_tgt" >/dev/null 2>&1
		_wait_reg "$PORT" 0
		if [ "$("$RES/bands.sh" getmode 2>/dev/null)" = "$MODE3G" ]; then
			logger -t 5gmodem "ussd: режим не вернулся с 3G, повторяю ($_tgt)"
			"$RES/bands.sh" setmodelive "$_tgt" >/dev/null 2>&1
			_wait_reg "$PORT" 0
		fi
		_if=$(uci -q get "$CFG.$(secname "$(active_path)").network" 2>/dev/null)
		[ -n "$_if" ] && ifup "$_if" >/dev/null 2>&1
	}
	trap '_restore' EXIT INT TERM

	# ВСЁ РЕШАЕМ ПРО МОДЕМ, КОТОРОМУ ПРИНАДЛЕЖИТ ПОРТ, а не про «активного».
	# Это разные вещи, и путать их дорого: страница показывает модем по своему
	# ussdport, а активным может быть другой.
	NOTE=""
	# Одна запись реестра отвечает сразу на всё: чей это порт, что за модель и
	# активен ли он.
	_reg_for_port "$PORT" || _reg=""
	_MODEL=$(_reg_field model)
	_VIDPID=$(_reg_field vidpid)
	_ISACT=$(_reg_field active)

	# USSD НЕ РАБОТАЕТ В ПРИНЦИПЕ? Тогда ни 3G, ни ожидания - только честная
	# отметка в ответе. У FM350 прошивка не отвечает на +CUSD ни в одном режиме
	# (проверено полной матрицей), и «нет ответа от модема» в такой ситуации
	# ничего человеку не объясняет. Сам запрос всё равно отправляем: база может
	# отставать от новой прошивки, и запретить попытку хуже, чем дать ей пройти
	# дешёвым способом - без ухода в 3G и без потери связи.
	if [ -n "$_VIDPID" ] && [ -r "$RES/quirks.sh" ]; then
		. "$RES/quirks.sh" 2>/dev/null
		if command -v ussd_supported_for >/dev/null 2>&1 \
		   && [ "$(ussd_supported_for "$_MODEL" "$_VIDPID")" = "0" ]; then
			MODE3G=""
			NOTE=',"unsupported":1'
			logger -t 5gmodem "ussd: $_MODEL в базе как «USSD не работает» - в 3G не уводим"
		fi
	fi

	# РЕЖИМ МЕНЯЕМ ТОЛЬКО СВОЕМУ МОДЕМУ. bands.sh работает с АКТИВНЫМ модемом, и
	# если запрос идёт в порт другого - переключать нечего: мы передёрнули бы сеть
	# соседу. Тогда запрос отправим как есть, а в ответе скажем, почему без 3G.
	if [ -n "$MODE3G" ] && [ "$_ISACT" != "true" ]; then
		MODE3G=""
		NOTE=',"noswitch":"not_active"'
		logger -t 5gmodem "ussd: $PORT не принадлежит активному модему - режим сети не трогаем"
	fi

	# ОДНА ПОПЫТКА ЗАПРОСА.
	#
	# АРГУМЕНТЫ sms_tool СОБИРАЕМ ЗДЕСЬ, а не на странице: политика «как слать»
	# должна жить в одном месте, иначе она разъедется между вкладкой и скриптом.
	#   -R  - код текстом. Иначе sms_tool упаковывает его в GSM7-хекс, а это верно
	#         лишь при наборе символов TE "HEX", которого мы не выставляем.
	#   -r  - ответ сырым: расшифровывает страница, у sms_tool разбор ломается на
	#         модемах с переставленными байтами UCS2.
	#   -c  - схема кодирования, если пользователь задал её явно.
	#
	# $1 = 1 - взять ФОРМУ НАОБОРОТ той, что в настройке. Нужно для второй попытки:
	# правильная форма зависит от прошивки, и угадывать за пользователя мы не
	# вправе - но попробовать обе дёшево и никого не задевает.
	_try() {
		set -- -d "$PORT"
		[ "$(uci -q get "$CFG.sms.ussd")" = "0" ] || set -- "$@" -R
		set -- "$@" -r
		_cd=$(uci -q get "$CFG.sms.coding")
		case "$_cd" in ''|auto) : ;; *) set -- "$@" -c "$_cd" ;; esac

		at_lock "$PORT" 20 2>/dev/null
		OUT=$(sms_tool "$@" ussd "$CODE" 2>/tmp/5gmodem_ussd.err)
		at_unlock 2>/dev/null
		ERR=$(cat /tmp/5gmodem_ussd.err 2>/dev/null)
		rm -f /tmp/5gmodem_ussd.err
		[ -n "$OUT" ]
	}

	# ПО УМОЛЧАНИЮ - ОБЫЧНЫЙ ЗАПРОС, НИЧЕГО НЕ ПЕРЕКЛЮЧАЯ.
	#
	# Так работала программа всегда, и у части модемов USSD в LTE отвечает сам
	# (CSFB отрабатывает). Уход в 3G стоит около двадцати секунд без связи, и
	# назначать его всем - значит ломать то, что у людей работает. Поэтому
	# переключение включается ГАЛКОЙ, а база проверенных модемов (quirks.sh)
	# лишь выставляет её значение при выборе модема.
	#
	# Пробовать «форму наоборот» тоже не пытаемся: лишний +CUSD в LTE сам
	# запускает CSFB и роняет регистрацию на полминуты - измерено. Одна попытка,
	# как настроено.
	# РЕШАЕТ НАСТРОЙКА ЭТОГО МОДЕМА, А НЕ ГЛОБАЛЬНАЯ ГАЛКА.
	#
	# sms.ussd_3g - глобальный ключ, он описывает лишь АКТИВНЫЙ модем и
	# обновляется при его смене (msw/identity.sh apply_ussd_quirk). Если этот
	# момент не наступил (модем не переключали, свежая установка, апгрейд), в
	# нём мог остаться '1' от ДРУГОГО модема - и незнакомый модуль зря уходил в
	# 3G, рвал сессию и всё равно отвечал «модем не ответил» (живой случай
	# 31.07.2026, Fibocom L850: 3G-режимы у профиля появились, и чужая галка
	# сразу их применила).
	#
	# Порядок теперь строгий: ЯВНАЯ настройка секции модема -> база проверенных
	# (quirks: сейчас только Telit LM960A18) -> НЕТ. Незнакомый модем в 3G не
	# уводим никогда, даже если глобальный ключ включён.
	_u3_p=$(uci -q get "$CFG.@5gmodem[0].active_modem")
	_u3_s="m_$(echo "$_u3_p" | sed 's/[^A-Za-z0-9]/_/g')"
	NEED3G=$(uci -q get "$CFG.$_u3_s.ussd_3g" 2>/dev/null)
	if [ -z "$NEED3G" ]; then
		. "$RES/quirks.sh" 2>/dev/null
		if command -v ussd_needs_3g_for >/dev/null 2>&1; then
			NEED3G=$(ussd_needs_3g_for \
				"$(uci -q get "$CFG.$_u3_s.model" 2>/dev/null)" \
				"$(uci -q get "$CFG.$_u3_s.vidpid" 2>/dev/null)")
		fi
	fi
	case "$NEED3G" in 1) : ;; *) NEED3G=0 ;; esac

	# ПЕРЕКЛЮЧАЕМСЯ ТОЛЬКО ПО ГАЛКЕ и только если модем действительно не в CS.
	# Уже в 3G - переключать нечего; галка снята - ведём себя как раньше.
	if [ "$NEED3G" = "1" ] && ! _is_cs "$ACT" && [ -n "$MODE3G" ] && [ "$CUR" != "$MODE3G" ]; then
		_st running switching ',"from":"'"$ACT"'","mode_was":"'"$CUR"'","mode_3g":"'"$MODE3G"'"'
		# УСПЕХ ОПРЕДЕЛЯЕМ ПО ФАКТУ CS-РЕГИСТРАЦИИ, а не по ответу setmodelive:
		# он сверяет режим через getmode, а тот читает AT-порт и на занятом порту
		# отвечает не сразу. Здесь важно ровно одно - появился ли канал CS.
		#
		# SWITCHED ставим СРАЗУ после отправки команды: если она подействовала,
		# режим обязан вернуться, чем бы ожидание ни кончилось. Возврат
		# идемпотентен - выставить Auto, когда он и так Auto, ничего не портит.
		"$RES/bands.sh" setmodelive "$MODE3G" >/dev/null 2>&1
		SWITCHED=1
		if ! _wait_reg "$PORT" 1; then
			NOTE=',"reason":"no_3g"'
			logger -t 5gmodem "ussd: CS-регистрация не появилась за ${REG_WAIT}c - запрос уйдёт как есть"
		fi
	fi

	# ЗАПРОС - ВСЕГДА ОДИН, переключались мы или нет. Отдельной попытки «формой
	# наоборот» не делаем: лишний +CUSD в LTE сам запускает CSFB и роняет
	# регистрацию на полминуты (измерено), то есть «дешёвая» попытка дороже всего.
	_st running sending
	_try || :

	[ "$SWITCHED" = 1 ] && _st running restoring
	_restore
	SWITCHED=0
	trap - EXIT INT TERM

	# Сырой вывод отдаём в base64: в нём кавычки и переводы строк, а собирать
	# JSON руками из такого - верный способ получить битый ответ.
	_st done "" ',"out":"'"$(printf '%s' "$OUT" | base64 | tr -d '\n')"'","err":"'"$(printf '%s' "$ERR" | base64 | tr -d '\n')"'"'"$NOTE"
) >/dev/null 2>&1 </dev/null &

cat "$ST"
exit 0
