# Сериализатор доступа к AT-порту. Подключается через "." (не запускается).
#
# ЗАЧЕМ. Опрос метрик, simslot.sh, esim.sh, bands.sh, smsbridge.sh и профили
# делят ОДИН tty. При наложении ответы перепутываются, и это не теория:
#   - на AT#MONI приходил +COPS: 0 - ответ чужой команды от сборщика метрик;
#   - AT+COPS? возвращал пустоту, и это выглядело как зависший модем;
#   - ATI возвращал +CPIN/+CSQ, а эхо AT+SIMTYPE? оседало в имени модема.
# Замерено: поодиночке опрос стабилен (6/6, JSON валиден 12/12), но при двух
# опросчиках сразу поля разом пустеют.
#
# Хуже всего не порча данных, а то, что ОТЛИЧИТЬ «модем не ответил» от «ответ
# украли» невозможно - на этом строятся ложные диагнозы.
#
# ПОЧЕМУ БЛОКИРУЮЩИЙ FLOCK, А НЕ ЦИКЛ -n. Раньше был цикл `flock -n` с шагом
# sleep 1: у busybox нет ни дробного sleep, ни usleep, ни timeout (проверено на
# живом роутере), поэтому ЛЮБОЕ ожидание округлялось ВВЕРХ до целой секунды. При
# нескольких потребителях на холодном открытии страницы одно это округление
# добавляло 3-4 c. Плюс `flock -n`-гонка НЕ честная: порядок случаен.
#
# Блокирующий `flock` просыпается МГНОВЕННО в момент освобождения и честен (ядро
# будит ждущих по очереди). Его единственная беда - у busybox нет -w, и зависший
# держатель блокировал бы навсегда (rpcd убил бы вызов на 30-й секунде -> "XHR
# error"). Ограничиваем время САМИ: блокирующий flock идёт в ФОНОВОМ подшелле, а
# сторож `sleep <max>; kill` снимает его по таймауту. Замок берётся на общий OFD
# (fd открыт в НАШЕМ процессе через exec ниже), поэтому переживает выход подшелла
# и держится, пока мы не закроем fd / не выйдем. Сторож ЗАКРЫВАЕТ свою копию fd
# (exec >&-), иначе он сам держал бы OFD и лок не снимался бы по нашему выходу.
# Проверено на роутере: конкурент берёт лок в тот же миг, как держатель отпустил;
# таймаут-ветка укладывается ровно в <max>.
#
# ОСВОБОЖДАТЬ ЯВНО НЕ НУЖНО. Блокировка живёт на файловом дескрипторе и снимается
# ядром при завершении процесса. Наши потребители - короткоживущие скрипты, так
# что достаточно взять её перед первой AT-командой; at_unlock нужен только если
# после AT-работы скрипт продолжает заниматься чем-то долгим.

# Дескриптор 8, а НЕ 9: девятый занят хотплагом (71-5gmodem-resolve), и общий
# номер означал бы, что взятие нашей блокировки рушит его собственную.
AT_LOCK_FD=8

# at_lock <порт> [сек ожидания, по умолчанию 10]
# 0 - блокировка взята; 1 - не дождались (вызывающий решает, что делать).
at_lock() {
	[ -n "$1" ] || return 0
	# Ключ - ИМЯ ПОРТА, а не модема: два модема на разных tty друг другу не
	# мешают, и общая блокировка зря выстраивала бы их в очередь.
	_al_key=$(basename "$1")
	# РЕ-ЕНТРАНТНОСТЬ. Лок ЭТОГО порта уже держит ПРЕДОК (опрос метрик держит его
	# всю свою жизнь и синхронно зовёт simslot.sh, а тот берёт лок снова). Повторно
	# брать через flock НЕЛЬЗЯ: у busybox лок висит на fd, второй `exec 8>файл`
	# открывает НОВЫЙ OFD, и flock на нём конфликтует со СТАРЫМ OFD того же дерева
	# процессов - процесс дедлочит сам себя до таймаута (наблюдалось: холодный
	# опрос 11 c = 10 c таймаут simslot + 1 c работы). Раз предок держит лок и
	# синхронно нас ждёт, мы уже сериализованы - работаем без повторного захвата.
	# Флаг ЭКСПОРТИРОВАН, поэтому виден в дочернем процессе (simslot.sh и т.п.).
	[ "$_AT_LOCK_HELD" = "$_al_key" ] && return 0
	# ДРУГОЙ порт поверх уже взятого лока - явный отказ, а не тихая подмена:
	# переоткрытие fd 8 снимало лок с ПЕРВОГО порта незаметно (ревью, баг №13).
	if [ -n "$_AT_LOCK_HELD" ]; then
		logger -t 5gmodem "at_lock: отказ - держим '$_AT_LOCK_HELD', запрошен '$_al_key' (сначала at_unlock)"
		return 1
	fi
	_al_d=/var/lock
	[ -d "$_al_d" ] || _al_d=/tmp
	_al_f="$_al_d/5gmodem-at-$_al_key.lock"
	eval "exec $AT_LOCK_FD>\"\$_al_f\"" 2>/dev/null || return 0
	_al_max="${2:-10}"
	# Быстрый путь: лок свободен - берём без фоновой возни.
	if flock -n "$AT_LOCK_FD" 2>/dev/null; then
		_AT_LOCK_HELD="$_al_key"; export _AT_LOCK_HELD
		return 0
	fi
	# Занят: блокирующий flock в фоне + сторож по таймауту (см. шапку файла).
	( flock "$AT_LOCK_FD" ) 2>/dev/null & _al_p=$!
	( eval "exec $AT_LOCK_FD>&-"; sleep "$_al_max"; kill "$_al_p" 2>/dev/null ) \
		>/dev/null 2>&1 </dev/null & _al_w=$!
	if wait "$_al_p" 2>/dev/null; then
		kill "$_al_w" 2>/dev/null; wait "$_al_w" 2>/dev/null
		_AT_LOCK_HELD="$_al_key"; export _AT_LOCK_HELD
		return 0
	fi
	kill "$_al_w" 2>/dev/null; wait "$_al_w" 2>/dev/null
	# ГОНКА НА ТАЙМАУТЕ: фоновый flock мог УСПЕТЬ взять замок ровно в момент
	# kill - тогда замок уже висит на нашем общем OFD, мы отвечаем «не взял», и
	# порт остался бы заперт на всю нашу жизнь, о чём не знал бы никто. Снимаем
	# и закрываем fd: на невзятом OFD и то и другое - безвредный no-op, а чужой
	# замок мы тронуть не можем (_AT_LOCK_HELD пуст - проверено на входе).
	flock -u "$AT_LOCK_FD" 2>/dev/null
	eval "exec $AT_LOCK_FD>&-" 2>/dev/null
	logger -t 5gmodem "at_lock: порт $1 занят дольше ${_al_max}c"
	return 1
}

at_unlock() {
	flock -u "$AT_LOCK_FD" 2>/dev/null
	eval "exec $AT_LOCK_FD>&-" 2>/dev/null
	unset _AT_LOCK_HELD
	return 0
}
