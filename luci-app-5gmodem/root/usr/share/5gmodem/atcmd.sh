#!/bin/sh
#
# КОНСОЛЬ AT - ЕДИНСТВЕННЫЙ ВХОД ДЛЯ ПРОИЗВОЛЬНОЙ КОМАНДЫ.
#
# ЗАЧЕМ ОТДЕЛЬНЫЙ СКРИПТ. Раньше страница «AT» исполняла БИНАРЬ sms_tool напрямую:
# в ACL было разрешено `exec` на /usr/bin/sms_tool, а аргументы приходили из
# браузера. Проверить их на роутере в таком виде НЕВОЗМОЖНО - фильтр живёт в
# странице, а страница выполняется у пользователя. То есть через эту дырку в
# модем (и в любой /dev/*) уходило что угодно: не только AT-команда, но и
# `send <номер> <текст>`, `delete all`, чужой порт.
#
# Это та же модель, что в setopt.sh: узкий глагол вместо общего исполнителя.
# Здесь проверяется И порт, И команда, И принадлежность порта нашему модему.
#
# ПРОИЗВОЛЬНАЯ КОМАНДА ОСТАЁТСЯ ФИЧЕЙ - консоль AT для этого и нужна. Мы не
# ограничиваем набор команд, мы ограничиваем ФОРМУ: без CR/LF внутри значения,
# то есть одной командой и останется (иначе «AT<CR>AT+CPIN=1234» уходило бы
# двумя, и вторую модем послушно выполнял).
#
# Usage: atcmd.sh <порт> <команда> [таймаут]

RES=/usr/share/5gmodem
. "$RES/lib.sh" 2>/dev/null

PORT="$1"
CMD="$2"
TMO="${3:-10}"

command -v is_devpath >/dev/null 2>&1 || { echo "lib unavailable" >&2; exit 1; }

if ! is_devpath "$PORT"; then
	logger -t 5gmodem "atcmd: device path rejected"
	echo "bad port" >&2; exit 2
fi
if ! is_atcmd "$CMD"; then
	logger -t 5gmodem "atcmd: command rejected by input validation"
	echo "bad command" >&2; exit 2
fi
case "$TMO" in ''|*[!0-9]*) TMO=10 ;; esac
[ "$TMO" -gt 40 ] && TMO=40

# ПОРТ ДОЛЖЕН БЫТЬ НАШИМ. is_devpath пропускает любой /dev/ttyUSB*, а на роутере
# бывают и посторонние переходники USB-UART. Спрашивать у них AT незачем, а
# главное - незачем давать такую возможность из браузера.
_known=0
for _t in $("$RES/listmodems.sh" 2>/dev/null | jsonfilter -e '@[*].tty[*]' 2>/dev/null); do
	[ "$_t" = "$PORT" ] && { _known=1; break; }
done
if [ "$_known" != 1 ]; then
	logger -t 5gmodem "atcmd: port $PORT does not belong to any known modem"
	echo "unknown port" >&2; exit 2
fi

# КОМАНДА ЧЕЛОВЕКА ИДЁТ БЕЗУСЛОВНО.
#
# Здесь не фоновый опрос, который можно пропустить, а явное действие: человек
# нажал «Отправить». Отвечать ему «порт занят другим запросом, повторите» -
# бессмысленно: занят порт нашим же опросом метрик, и повтор попадает в ту же
# картину (живой отчёт 05.08.2026: сброс диапазонов у человека не проходил
# вовсе). Поэтому очередь ЖДЁМ ДОЛЬШЕ обычного, а не дождались - выполняем
# всё равно: пусть рискует один пропущенный тик метрик, а не команда человека.
# Ждём очередь не дольше, чем страница готова ждать ответа: клиентский предел
# ubus-вызова 20 c, а 25 c ожидания + таймаут команды его перекрывали всегда -
# человек получал «XHR error» вместо ответа (аудит 12.09.2026, группа 7, №22).
at_query "$PORT" "$CMD" "$TMO" 8
_rc=$?
if [ "$_rc" = 2 ]; then
	logger -t 5gmodem "atcmd: queue for $PORT busy for over 8s - running the user command without it"
	# Сами берём порт мимо очереди: at_query с занятым локом сюда уже не пустит.
	# Ограничено по времени: зависший модем иначе держал бы порт до таймаута rpcd.
	_ac_o=$(mktemp /tmp/5gmodem_atcmd.XXXXXX 2>/dev/null) || _ac_o="/tmp/5gmodem_atcmd.$$"
	sms_tool -d "$PORT" at "$CMD" > "$_ac_o" 2>/dev/null &
	_ac_p=$!
	( sleep "$(( ${TMO:-8} + 1 ))"; kill "$_ac_p" 2>/dev/null ) >/dev/null 2>&1 </dev/null & _ac_k=$!
	wait "$_ac_p" 2>/dev/null; kill "$_ac_k" 2>/dev/null; wait "$_ac_k" 2>/dev/null
	tr -d '\r' < "$_ac_o"; rm -f "$_ac_o"
fi
exit 0
